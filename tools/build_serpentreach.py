def _duchy_title_lines(realm: Realm, dkey: str, colour: dict) -> list:
    lines = [f"\t\t{dkey} = {{", f"\t\t\tcolor = {colour[dkey]}", f"\t\t\tcapital = {realm.duchy_capital(dkey)}", ""]
    for ckey in realm.duchies[dkey][1]:
        lines += [f"\t\t\t{ckey} = {{", f"\t\t\t\tcolor = {colour[ckey]}", ""]
        for bkey, pid in zip(realm.barony_keys(ckey), realm.county[ckey].baronies):
            lines += [f"\t\t\t\t{bkey} = {{", f"\t\t\t\t\tprovince = {pid}",
                      f"\t\t\t\t\tcolor = {colour[ckey]}", "\t\t\t\t}"]
        lines.append("\t\t\t}")
    lines.append("\t\t}")
    return lines


def render_titles(realm: Realm, cfg=None) -> bytes:
    """The empire with its new kingdoms, duchies and counties in place; the new duchies of Anbennar's kingdoms
    (EXISTING_KINGDOMS) in PARKING_KINGDOM inside it, so each title has a full chain at load (history moves them)."""
    cfg = cfg or realm.cfg
    colour = {key: rgb_text(rgb) for key, rgb in realm.colours().items()}
    lines = header_lines(cfg) + ["", f"{cfg.EMPIRE[0]} = {{", f"\tcolor = {colour[cfg.EMPIRE[0]]}",
                                 f"\tcapital = {cfg.EMPIRE_CAPITAL}", ""]
    for kkey in realm.new_kingdoms():
        lines += [f"\t{kkey} = {{", f"\t\tcolor = {colour[kkey]}",
                  f"\t\tcapital = {cfg.KINGDOM_CAPITALS[kkey]}", ""]
        for dkey in realm.kingdoms[kkey][1]:
            lines += _duchy_title_lines(realm, dkey, colour)
        lines.append("\t}")
    parked = realm.parked_duchies()
    if parked:
        grey = rgb_text(getattr(cfg, "PARKING_COLOUR", (90, 90, 90)))
        lines += [f"\t{cfg.PARKING_KINGDOM} = {{", f"\t\tcolor = {grey}",
                  f"\t\tcapital = {realm.duchy_capital(parked[0])}", ""]
        for dkey in parked:
            lines += _duchy_title_lines(realm, dkey, colour)
        lines.append("\t}")
    lines.append("}")
    return _text(lines)


def render_province_history(realm: Realm, cfg=None) -> bytes:
    cfg = cfg or realm.cfg
    lines = header_lines(cfg)
    for c in realm.lay.counties:
        holdings = cfg.HOLDINGS[c.type]
        for i, (pid, name) in enumerate(zip(c.baronies, realm.barony_names(c.key))):
            holding = holdings[i] if i < len(holdings) else None
            lines += ["", f"{pid} = {{\t# {name}", f"\tculture = {realm.culture_of(realm.duchy_of[c.key])}",
                      f"\treligion = {cfg.RELIGION}",
                      f"\tholding = {holding or 'none'}", "}"]
    return _text(lines)


def male_names(anbennar: Path) -> list:
    path = anbennar / "common/culture/name_lists/anb_dwarven.txt"
    if not path.is_file():
        raise GeneratorError(f"Anbennar not found: {path} does not exist")
    text = path.read_text(encoding="utf-8-sig")
    m = re.search(r"name_list_dwarven\s*=\s*\{.*?male_names\s*=\s*\{([^}]*)\}", text, re.S)
    if not m:
        raise GeneratorError(f"{path}: no male_names in name_list_dwarven")
    names = [n for n in m.group(1).split() if re.fullmatch(r"[A-Za-z]+", n)]
    if not names:
        raise GeneratorError(f"{path}: name_list_dwarven has no plain male names")
    return names


class People:
    """Two generations per duchy (the emperor's duchy has the emperor's line): (dynasty, [(id, name, birth,
    death or None)]). Character ids start with CHARACTER_PREFIX, dynasties with DYNASTY_PREFIX (key, name key)."""

    def __init__(self, realm: Realm, names: list, cfg=None):
        cfg = cfg or realm.cfg
        self.lines = {}  # duchy key -> {"dynasty", "dyn_key", "dyn_name", "eu4_name", "culture", "chars": [...]}
        dynasty_names = getattr(cfg, "DYNASTY_NAMES", {})
        dyn_prefix, name_prefix = getattr(cfg, "DYNASTY_PREFIX", ("aov_dynasty_", "dynn_aov_"))
        used = set(dynasty_names.values())  # a generated name never repeats an EU4 one
        for dkey, (dname, _) in realm.duchies.items():
            if dkey in realm.existing_duchies:
                continue
            prefix = (f"{cfg.CHARACTER_PREFIX}_emperor" if dkey == realm.emperor_duchy
                      else f"{cfg.CHARACTER_PREFIX}_{dkey[2:]}")
            elder, son = f"{prefix}_1", f"{prefix}_2"
            chars = []
            for cid, birth, death in ((elder, life_date(elder, cfg.ELDER_BIRTH), life_date(elder + "d", cfg.ELDER_DEATH)),
                                      (son, life_date(son, cfg.SON_BIRTH), None)):
                chars.append((cid, names[_hash("name:" + cid) % len(names)], birth, death))
            eu4_name = dynasty_names.get(dkey)
            if eu4_name:
                dyn_name = eu4_name
            else:
                base = re.sub(r"[\d|]+", "", dname).strip(" -")
                dyn_name = base if base not in used else f"{base}-{chars[0][1]}"
                used.add(dyn_name)
            self.lines[dkey] = {"dynasty": f"{dyn_prefix}{dkey[2:]}", "dyn_key": f"{name_prefix}{dkey[2:]}",
                                "dyn_name": dyn_name, "eu4_name": bool(eu4_name), "culture": realm.culture_of(dkey),
                                "chars": chars}


def render_dynasties(people: People, cfg=None) -> bytes:
    lines = header_lines(cfg)
    for line in people.lines.values():
        prefix = [] if line["eu4_name"] else ['\tprefix = "dynnp_az"']  # EU4's names stand alone
        lines += ["", f"{line['dynasty']} = {{"] + prefix + [f"\tname = \"{line['dyn_key']}\"",
                                                             f"\tculture = {line['culture']}", "}"]
    return _text(lines)


def render_characters(people: People, cfg=None) -> bytes:
    cfg = cfg or data
    lines = header_lines(cfg)
    for line in people.lines.values():
        elder = line["chars"][0][0]
        for cid, name, birth, death in line["chars"]:
            lines += ["", f"{cid} = {{", f'\tname = "{name}"', f"\tdynasty = {line['dynasty']}",
                      f'\treligion = "{cfg.RELIGION}"', f'\tculture = "{line["culture"]}"', "\ttrait = race_dwarf"]
            if cid != elder:
                lines.append(f"\tfather = {elder}")
            lines.append(f"\t{birth} = {{ birth = yes }}")
            if death:
                lines.append(f"\t{death} = {{ death = yes }}")
            lines.append("}")
    return _text(lines)


def render_title_history(realm: Realm, people: People, cfg=None) -> bytes:
    cfg = cfg or realm.cfg
    lines = header_lines(cfg)

    def block(key, liege, line):
        (elder, _, _, death), (son, _, _, _) = line["chars"]
        extra = f" liege = {liege}" if liege else ""
        return ["", f"{key} = {{", f"\t{cfg.START} = {{ holder = {elder}{extra} }}",
                f"\t{death} = {{ holder = {son} }}", "}"]

    # Each kingdom is held by the lord of its hold's duchy, a vassal of the emperor (who holds the capital hold's); the
    # other dukes of a kingdom are the king's vassals. A title's liege is the highest title of its holder's liege.
    empire = cfg.EMPIRE[0]
    lines += block(empire, None, people.lines[realm.emperor_duchy])
    for kkey in realm.new_kingdoms():
        duchies = realm.kingdoms[kkey][1]
        hold = realm.hold_duchy[kkey]
        royal = hold == realm.emperor_duchy
        lines += block(kkey, None if royal else empire, people.lines[hold])
        for dkey in duchies:
            line = people.lines[dkey]
            mine = dkey == realm.emperor_duchy
            liege = None if mine else empire if royal or dkey == hold else kkey
            lines += block(dkey, liege, line)
            for ckey in realm.duchies[dkey][1]:
                lines += block(ckey, empire if mine else dkey, line)
    return _text(lines)


def duchy_arms(dkey: str, area: str, field: tuple, charges: dict = None, cfg=None) -> list:
    """A dwarven charge (`charges`, default the data module's DUCHY_CHARGES) on a field of `field`, divided by a
    pattern picked from the key."""
    cfg = cfg or data
    charges = cfg.DUCHY_CHARGES if charges is None else charges
    pattern = cfg.DUCHY_PATTERNS[_hash("arms:" + dkey) % len(cfg.DUCHY_PATTERNS)]
    pale = colorsys.rgb_to_hls(*(v / 255 for v in field))[1] > cfg.PALE_FIELD
    charge, accent = cfg.CHARGE_DARK if pale else cfg.CHARGE_METAL
    lines = [f"{dkey} = {{", f'\tpattern = "{pattern}"', f"\tcolor1 = rgb {rgb_text(field)}",
             f"\tcolor2 = rgb {rgb_text(shade(field, -0.15))}"]
    for texture, (x, y), (sx, sy) in charges[area]:
        lines += ["\tcolored_emblem = {", f'\t\ttexture = "{texture}"', f"\t\tcolor1 = rgb {rgb_text(charge)}",
                  f"\t\tcolor2 = rgb {rgb_text(accent)}",
                  f"\t\tinstance = {{ position = {{ {x} {y} }} scale = {{ {sx} {sy} }} }}", "\t}"]
    return lines + ["}"]


def render_arms(realm: Realm, cfg=None) -> bytes:
    """Each kingdom, its hold's duchy and its hold county carry the EU4 hold's flag as a textured emblem; the other
    new duchies a dwarven charge on their map colour."""
    cfg = cfg or realm.cfg
    lines = header_lines(cfg)
    colours = realm.colours()
    for kkey, (kname, duchies) in realm.kingdoms.items():
        tag, _, background = cfg.KINGDOM_ARMS[kkey]
        lines += ["", f"# {kname} (EU4 {tag})"]
        for key in (kkey, realm.hold_duchy[kkey], cfg.KINGDOM_CAPITALS[kkey]):
            lines += [f"{key} = {{", '\tpattern = "pattern_solid.dds"', f"\tcolor1 = rgb {rgb_text(background)}",
                      "\ttextured_emblem = {", f'\t\ttexture = "{emblem(kkey)}"', "\t}", "}"]
        for dkey in duchies:
            if dkey != realm.hold_duchy[kkey] and dkey not in realm.existing_duchies:
                lines += duchy_arms(dkey, realm.duchy_area[dkey], colours[dkey], cfg=cfg)
    return _text(lines)


def missing_charges(anbennar: Path, game: Path, charges: dict = None, cfg=None) -> list:
    """Colored emblems of `charges` (default the data module's DUCHY_CHARGES) found in none of the mod, Anbennar and
    the game."""
    folder = "gfx/coat_of_arms/colored_emblems"
    charges = (cfg or data).DUCHY_CHARGES if charges is None else charges
    textures = {t for entry in charges.values() for t, _, _ in entry}
    return sorted(t for t in textures if not any((root / folder / t).is_file() for root in (SUBMOD, anbennar, game)))


def render_terrain(lay: sl.Layout, cfg=None) -> bytes:
    lines = header_lines(cfg) + [""]
    for c in lay.counties:
        lines += [f"{pid}={c.type}" for pid in c.baronies]
    return _text(lines)


def render_regions(cfg=None, kingdoms=None, name="world_serpentreach") -> bytes:
    # regions take kingdoms, duchies, counties or provinces, not empires
    cfg = cfg or data
    kingdoms = list(cfg.KINGDOMS) if kingdoms is None else kingdoms
    return _text(header_lines(cfg) + ["", f"{name} = {{", f"\tkingdoms = {{ {' '.join(kingdoms)} }}", "}"])


def render_loc(realm: Realm, people: People, cfg=None) -> bytes:
    cfg = cfg or realm.cfg

    def pair(key, name, adj=True):
        out = [f' {key}:0 "{name}"']
        return out + ([f' {key}_adj:0 "{name}"'] if adj else [])

    lines = ["l_english:"]
    lines += pair(cfg.EMPIRE[0], cfg.EMPIRE[1])
    for kkey in realm.new_kingdoms():
        lines += pair(kkey, realm.kingdoms[kkey][0])
    if realm.existing_kingdoms:
        lines += pair(cfg.PARKING_KINGDOM, cfg.PARKING_NAME)
    for dkey, (dname, _) in realm.duchies.items():
        if dkey not in realm.existing_duchies:
            lines += pair(dkey, dname)
    for ckey, c in realm.county.items():
        lines += pair(ckey, c.name)
        for bkey, bname in zip(realm.barony_keys(ckey), realm.barony_names(ckey)):
            lines += pair(bkey, bname, adj=False)
    for line in people.lines.values():
        lines.append(f' {line["dyn_key"]}:0 "{line["dyn_name"]}"')
    return _text(lines)


def render_definition(original: bytes, lays) -> bytes:
    nl = b"\r\n" if b"\r\n" in original else b"\n"
    out = original if original.endswith(nl) else original + nl
    rows = []
    for lay, c in ((lay, c) for lay in lays for c in lay.counties):
        for i, pid in enumerate(c.baronies):
            p = lay.provinces[pid]
            name = ascii_name(c.name if i == 0 else f"{c.name} {data.BARONY_SUFFIXES[i - 1]}")
            rows.append(f"{pid};{p.colour[0]};{p.colour[1]};{p.colour[2]};{name};x;".encode("ascii"))
    return out + nl.join(rows) + nl


def render_provinces(png: bytes, lays) -> bytes:
    img = pngio.read_png(png)
    if img.bit_depth != 8 or img.color_type not in (2, 6):
        raise GeneratorError("provinces.png must be 8-bit RGB or RGBA")
    bpp = 3 if img.color_type == 2 else 4
    px = bytearray(img.pixels)
    for lay in lays:
        for (x, y), pid in lay.owner.items():
            k = ((img.height - 1 - y) * img.width + x) * bpp
            px[k:k + 3] = bytes(lay.provinces[pid].colour)
    return pngio.write_png(pngio.Image(img.width, img.height, 8, img.color_type, bytes(px)))


def render_locators(anbennar: Path, lays) -> dict:
    instances = [(pid, p.interior[0] + 0.5, p.interior[1] + 0.5)
                 for lay in lays for pid, p in sorted(lay.provinces.items())]
    out = {}
    for name in LOCATOR_FILES:
        path = anbennar / LOCATOR_DIR / f"{name}.txt"
        if not path.is_file():
            raise GeneratorError(f"Anbennar not found: {path} does not exist")
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        out[f"{LOCATOR_DIR}/{name}.txt"] = locator_override(text, instances).encode("utf-8")
    return out


def layouts(anbennar: Path = ANBENNAR, eu4: Path = EU4, ck3=None) -> tuple:
    """(Serpentreach's layout, Segbandal's, West Dwarovar's): each region's ids follow the one before and its colours
    avoid theirs."""
    ck3 = ck3 or sl.load_ck3(anbennar)
    serp = sl.layout(anbennar, eu4, ck3)
    seg = sl.layout(anbennar, eu4, ck3, cfg=segbandal_data, first_id=max(serp.provinces) + 1,
                    used={p.colour for p in serp.provinces.values()})
    return serp, seg, west_dwarovar_layout(anbennar, eu4, ck3, serp, seg)


def west_dwarovar_layout(anbennar: Path, eu4: Path, ck3, serp: sl.Layout, seg: sl.Layout) -> sl.Layout:
    """West Dwarovar's layout after Serpentreach's and Segbandal's: ids after Segbandal's, colours apart from both,
    floors kept off theirs, and EU4 adjacencies.csv tunnels to their provinces in LINK_TARGETS (Dwarovrod 24 -> 25)."""
    earlier = (serp, seg)
    return sl.layout(anbennar, eu4, ck3, cfg=west_dwarovar_data, first_id=max(seg.provinces) + 1,
                     used={p.colour for lay in earlier for p in lay.provinces.values()},
                     avoid={p: pid for lay in earlier for p, pid in lay.owner.items()},
                     targets={c.eu4_id: list(c.baronies) for lay in earlier for c in lay.counties
                              if c.eu4_id in west_dwarovar_data.LINK_TARGETS})


def build_all(anbennar: Path = ANBENNAR, eu4: Path = EU4, ck3=None) -> dict:
    """Every output (rel path -> bytes); nothing is written here."""
    return build_from_layout(anbennar, layouts(anbennar, eu4, ck3))


def build_from_layout(anbennar: Path, lays) -> dict:
    """Serpentreach's files from `lays` (Serpentreach's layout first); the shared map files hold every layout."""
    lay = lays[0]
    realm = Realm(lay)
    titles_text = "\n".join(p.read_text(encoding="utf-8-sig", errors="replace")
                            for p in sorted((anbennar / "common/landed_titles").glob("*.txt")))
    check_new_keys(realm.all_keys(), titles_text)
    missing = [emblem(k) for k in realm.kingdoms if not (SUBMOD / EMBLEM_DIR / emblem(k)).is_file()]
    if missing:
        raise GeneratorError(f"flag emblems missing from {EMBLEM_DIR} (see KINGDOM_ARMS): {', '.join(missing)}")
    missing = missing_charges(anbennar, DEFAULT_GAME)
    if missing:
        raise GeneratorError(f"DUCHY_CHARGES emblems found nowhere: {', '.join(missing)}")
    people = People(realm, male_names(anbennar))
    folder = anbennar / "map_data"
    files = {
        PROVINCES_PNG: render_provinces((folder / "provinces.png").read_bytes(), lays),
        DEFINITION: render_definition((folder / "definition.csv").read_bytes(), lays),
        TITLES: render_titles(realm),
        PROVINCE_HISTORY: render_province_history(realm),
        TITLE_HISTORY: render_title_history(realm, people),
        CHARACTERS: render_characters(people),
        DYNASTIES: render_dynasties(people),
        TERRAIN: render_terrain(lay),
        REGIONS: render_regions(),
        LOC: render_loc(realm, people),
        ARMS: render_arms(realm),
    }
    files.update(render_locators(anbennar, lays))
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=ANBENNAR)
    parser.add_argument("--eu4", type=Path, default=EU4)
    args = parser.parse_args()
    try:
        lays = layouts(args.anbennar, args.eu4)
        files = build_from_layout(args.anbennar, lays)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for lay in lays:
        for note in lay.notes:
            print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files: " + "; ".join(f"{len(lay.counties)} counties, {len(lay.provinces)} provinces"
                                                    for lay in lays))
    return 0


if __name__ == "__main__":
    sys.exit(main())
