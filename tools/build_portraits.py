def triggers_file() -> dict:
    """The culture triggers in vanilla's shape (00_clothing_triggers.txt): the plain trigger reads scope:culture, the
    spouse trigger the character's culture."""
    lines = [BOM + HEADER()[0], HEADER()[1],
             "# Culture triggers of the RiE portrait entries (tools/data/portraits.py), in vanilla's shape."]
    for key in our_inputs():
        for suffix, scope in (("", "scope:culture"), ("_spouse", "culture")):
            if key in data.FLAG_INPUTS:
                body = ["\tportrait_shared_clothing_contents_trigger = {",
                        f"\t\tCULTURE_SCOPE = {scope}", f"\t\tCULTURE_FLAG = {key}", "\t}"]
            elif key in data.COMBINED_INPUTS:
                need, exclude = data.COMBINED_INPUTS[key]
                body = [f"\tportrait_{need}_clothing{suffix}_trigger = yes",
                        f"\tNOT = {{ portrait_{exclude}_clothing{suffix}_trigger = yes }}"]
            else:
                body = ["\talways = no"]
            lines += ["", f"portrait_{key}_clothing{suffix}_trigger = {{"] + body + ["}"]
    lines += ["", "# Culture scope: RiE's dwarf heritages."]
    for name, body in data.CULTURE_TRIGGERS.items():
        lines += [f"{name} = {{", f"\t{body}", "}"]
    return {TRIGGERS_FILE: ("\n".join(lines) + "\n").encode("utf-8")}


# ---------------------------------------------------------------------------------------------------------- genes

def gene_uses(entries: dict) -> list:
    """[(gene, template)] the copied entries' accessory and morph modifiers name, in order, each once."""
    found = []
    for groups in entries.values():
        for _settings, texts in groups.values():
            for text in texts:
                body = code(text)
                for names, start, end in blocks(body):
                    if names[-1] not in ("accessory", "morph"):
                        continue
                    part = body[start:end]
                    gene = re.search(r"\bgene\s*=\s*(\w+)", part)
                    template = re.search(r"\btemplate\s*=\s*(\w+)", part)
                    if gene and template and (gene.group(1), template.group(1)) not in found:
                        found.append((gene.group(1), template.group(1)))
    return found


def gene_index(files, strict=True) -> dict:
    """(gene, template) -> (file, start, end) and gene -> (file, gene start, gene end), from [(file, text)]."""
    index = {}
    for path, text in files:
        for names, start, end in blocks(text, 3, strict):
            index.setdefault(("gene", names[2]), (path, start, end))
        for names, start, end in blocks(text, 4, strict):
            index.setdefault((names[2], names[3]), (path, start, end))
    return index


def build_genes(roots: Roots, entries: dict) -> tuple:
    """(overridden gene files, accessory names the new templates use, notes)."""
    ours = effective_texts(roots, GENES_DIR)
    texts = dict(ours)
    ours_index = gene_index(ours, strict=False)
    rie = list(_texts(str(roots.rie / GENES_DIR), "*.txt"))
    rie_texts = dict(rie)
    rie_index = gene_index(rie, strict=False)
    anbennar_files = {path for path, _t in _texts(str(roots.anbennar / GENES_DIR), "*.txt")}
    additions, accessories = {}, []
    for gene, template in gene_uses(entries):
        if (gene, template) in ours_index:
            continue
        if (gene, template) not in rie_index:
            raise GeneratorError(f"gene {gene} template {template} is in neither Anbennar, the game nor RiE")
        if ("gene", gene) not in ours_index:
            raise GeneratorError(f"gene {gene} is not defined by Anbennar or the game")
        path = ours_index[("gene", gene)][0]
        if path not in anbennar_files:
            raise GeneratorError(f"gene {gene} lives in the game's {path}, which Anbennar does not override")
        rpath, start, end = rie_index[(gene, template)]
        body = rie_texts[rpath][start:end]
        additions.setdefault((path, gene), []).append((template, body))
        for name in TEMPLATE_ACCESSORY.findall(code(body)):
            if name != "empty" and name not in accessories:
                accessories.append(name)
    out, notes = {}, []
    for path in sorted({p for p, _g in additions}):
        text = texts[path]
        inserts = []
        for (file, gene), templates in additions.items():
            if file != path:
                continue
            _p, gstart, gend = ours_index[("gene", gene)]
            used = set()
            for names, s, e in blocks(text, 4):
                if names[2] == gene and gstart <= s < gend:
                    match = INDEX.search(code(text[s:e]))
                    if match:
                        used.add(int(match.group(1)))
            free = [i for i in range(MAX_TEMPLATE_INDEX + 1) if i not in used]
            if len(free) < len(templates):
                raise GeneratorError(f"gene {gene}: {len(templates)} new templates but only {len(free)} free indices "
                                     f"(0..{MAX_TEMPLATE_INDEX})")
            pieces = [f"\t\t{MARKER}: Realms in Exile templates (tools/build_portraits.py)\n"]
            for (template, body), index in zip(templates, free):
                pieces.append(lf(INDEX.sub(f"index = {index}", body, count=1)))
            pieces.append(f"\t\t{MARKER}: end of Realms in Exile templates\n")
            closing = text.rfind("\n", 0, gend - 1) + 1
            inserts.append((closing, "".join(pieces)))
            notes.append(f"gene {gene}: {len(templates)} RiE templates at indices {free[0]}..{free[len(templates) - 1]}"
                         f" ({len(used) + len(templates)} of {MAX_TEMPLATE_INDEX + 1} used)")
        for offset, piece in sorted(inserts, reverse=True):
            text = text[:offset] + piece + text[offset:]
        out[f"{GENES_DIR}/{path}"] = (BOM + text).encode("utf-8")
    return out, accessories, notes


# -------------------------------------------------------------------------------------------------- accessories

def top_blocks(files) -> dict:
    """top-level block name (or name field for kind blocks) -> (kind, path, text) from [(path, text)]."""
    index = {}
    for path, text in files:
        for names, start, end in blocks(text, 1, strict=False):
            body = text[start:end]
            key = names[0]
            index.setdefault(key, (key, path, body))
    return index


def build_accessories(roots: Roots, names: list) -> tuple:
    ours = top_blocks(effective_texts(roots, "gfx/portraits/accessories"))
    rie = top_blocks(_texts(str(roots.rie / "gfx/portraits/accessories"), "*.txt"))
    lines = [BOM + HEADER()[0], HEADER()[1], "# Realms in Exile accessories the RiE gene templates use."]
    entities, count = [], 0
    for name in names:
        if name in ours:
            continue
        if name not in rie:
            raise GeneratorError(f"accessory {name} is in neither Anbennar, the game nor RiE")
        _kind, path, body = rie[name]
        lines += ["", f"# from RiE gfx/portraits/accessories/{path}", lf(body).rstrip("\n")]
        count += 1
        for entity in ACCESSORY_ENTITY.findall(code(body)):
            if entity not in entities:
                entities.append(entity)
    return {ACCESSORIES_FILE: ("\n".join(lines) + "\n").encode("utf-8")}, entities, count


