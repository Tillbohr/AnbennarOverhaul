    "\t\t\tvisible = \"[EqualTo_string( Lifestyle.GetKey, 'wanderer_lifestyle' )]\"\n"
    "\t\t\tprogresstexture = \"gfx/interface/progressbars/progress_brown.dds\"\n"
    "\t\t\tnoprogresstexture = \"gfx/interface/progressbars/progress_brown_bg.dds\"\n"
