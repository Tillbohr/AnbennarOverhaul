"""Tests for tools/build_governments_override.py.

    python -I -m unittest discover -s tools/tests -p test_build_governments_override.py
"""

import re
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # python -I does not add the tools folder
import build_governments_override as gov  # noqa: E402
from eu4_monuments import parse_blocks  # noqa: E402

GOV_FIXTURE = """feudal_government = {
\tfallback = 1
\tprimary_holding = castle_holding
\tvalid_holdings = { temple_citadel_holding }
}

clan_government = {
\tprimary_holding = tribal_holding
\tvalid_holdings = { tribal_holding castle_holding }
}

tribal_government = {
\tprimary_holding = castle_holding
\trequired_county_holdings = { castle_holding city_holding }
}

republic_government = {
\tprimary_holding = city_holding
\tvalid_holdings = { temple_citadel_holding }
}
"""


class AddValidHoldingTests(unittest.TestCase):
    def test_governments_gain_hold(self):
        out = gov.add_valid_holding(GOV_FIXTURE)
        b = parse_blocks(out)
        self.assertIn("dwarven_hold_holding", b["feudal_government"])
        self.assertIn("dwarven_hold_holding", b["clan_government"])
        self.assertNotIn("dwarven_hold_holding", b["republic_government"])

    def test_valid_holdings_line_created_after_primary(self):
        out = gov.add_valid_holding(GOV_FIXTURE)
        lines = out.split("\n")
        i = next(i for i, l in enumerate(lines) if "valid_holdings = { dwarven_hold_holding }" in l)
        self.assertTrue(lines[i - 1].strip().startswith("primary_holding = castle_holding"))
        self.assertTrue(lines[i].endswith(gov.MARKER))

    def test_changed_lines_marked_and_idempotent(self):
        out = gov.add_valid_holding(GOV_FIXTURE)
        changed = [l for l in out.split("\n") if "dwarven_hold_holding" in l]
        self.assertEqual(len(changed), 3)
        self.assertTrue(all(l.endswith(gov.MARKER) for l in changed))
        self.assertEqual(gov.add_valid_holding(out), out)


def live_paths():
    return [(gov.DEFAULT_ANBENNAR / p, gov.SUBMOD / p) for p in gov.REL_PATHS]


class GeneratedFileTests(unittest.TestCase):
    @unittest.skipUnless(all(a.is_file() and o.is_file() for a, o in live_paths()),
                         "needs Anbennar and the generated files")
    def test_generated_governments_differ_only_by_added_key(self):
        for src_path, out_path in live_paths():
            src = src_path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
            out = out_path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
            lines = out.split("\n")
            self.assertTrue(lines[0].startswith(gov.MARKER + ": generated by tools/build_governments_override.py"))
            self.assertTrue(lines[1].startswith(gov.MARKER + ": do not edit"))
            rest = []
            for l in lines[2:]:
                if l.endswith(" " + gov.MARKER):
                    l = l[:-len(gov.MARKER) - 1]
                    if l.strip() == f"valid_holdings = {{ {gov.HOLDING} }}":
                        continue  # a created line
                    l = l.replace(f" {gov.HOLDING}", "")
                rest.append(l)
            self.assertEqual("\n".join(rest), src, out_path.name)

    @unittest.skipUnless(all(o.is_file() for _, o in live_paths()), "needs the generated files")
    def test_every_castle_government_accepts_hold(self):
        seen = 0
        for _, out_path in live_paths():
            for name, body in parse_blocks(out_path.read_bytes().decode("utf-8-sig")).items():
                prim = re.search(r"^\s*primary_holding = castle_holding\s*$", body, re.M)
                valid = re.search(r"^\s*valid_holdings = \{([^}]*)\}", body, re.M)
                if prim or (valid and "castle_holding" in valid.group(1).split()):
                    seen += 1
                    self.assertIsNotNone(valid, name)
                    self.assertIn(gov.HOLDING, valid.group(1).split(), name)
        self.assertGreater(seen, 10)


if __name__ == "__main__":
    unittest.main()
