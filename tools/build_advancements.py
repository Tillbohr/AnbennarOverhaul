"""Generate the per-advancement magic files from tools/data/advancements.py.

Every file written here repeats one block per advancement, so it is generated rather than written by hand.
Each level's effect is hand-written (aov_adv_<key>_<n>_effect in
common/scripted_effects/aov_advancement_level_effects.txt). Rerun after editing tools/data/advancements.py:

    python -I tools/build_advancements.py
"""

import importlib.util
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I does not add the script's folder
from build_inventions import GeneratorError  # noqa: E402
from build_spells import SCHOOLS  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
DATA = SUBMOD / "tools" / "data" / "advancements.py"
HEADER = "# Anbennar Overhaul: generated by tools/build_advancements.py from tools/data/advancements.py; do not edit by hand.\n"

GOLD = (100, 200, 400)
MANA = (50, 75, 100)
YEARS = (2, 3, 4)
ADV_OF_SCHOOL = {
    "abjuration": "magical_fortress",
    "conjuration": "summon_extraplanars",
    "divination": "orb_of_omniscience",
    "enchantment": "enchanted_artifact",
    "evocation": "battlemage_academy",
    "illusion": "mirror_image",
    "necromancy": "lichdom",
    "transmutation": "homunculus",
}


def load_advancements(path: Path = DATA) -> list:
    spec = importlib.util.spec_from_file_location("aov_advancements_data", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.ADVANCEMENTS


def validate(advs: list) -> None:
    keys = [a["key"] for a in advs]
    if len(set(keys)) != len(keys):
        raise GeneratorError("duplicate advancement keys")
    for a in advs:
        k = a["key"]
        if not re.fullmatch(r"[a-z_]+", k):
            raise GeneratorError(f"{k}: bad key")
        if a["school"] not in SCHOOLS:
            raise GeneratorError(f"{k}: unknown school {a['school']}")
        if ADV_OF_SCHOOL[a["school"]] != k:
            raise GeneratorError(f"{k}: {a['school']}'s advancement is {ADV_OF_SCHOOL[a['school']]}")
        if len(a["levels"]) != 3:
            raise GeneratorError(f"{k}: needs exactly 3 levels")
        for n, names in a["requires"].items():
            if n not in (1, 2, 3) or not all(re.fullmatch(r"[a-z_]+", t) for t in names):
                raise GeneratorError(f"{k}: bad requires {n}: {names}")
        texts = [a["name"], a["desc"]] + [lv["name"] + lv["desc"] for lv in a["levels"]]
        if any('"' in t for t in texts):
            raise GeneratorError(f"{k}: double quote in a text")
