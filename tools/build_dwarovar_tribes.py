"""Generate the Dwarovar tribes' governments, pool of blank titles and overrides from tools/data/dwarovar_tribes.py.

The two governments are copies of tribal_government in the overhaul's generated 00_government_types.txt, so run this
after build_governments_override.py. Rerun after editing the data file, or after an Anbennar or CK3 update:

    python -I tools/build_dwarovar_tribes.py [--anbennar PATH] [--game PATH]

Spec: docs/superpowers/specs/2026-11-05-dwarovar-tribes-design.md
"""

import argparse
import colorsys
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I does not add the script's folder
import build_portraits as bp  # noqa: E402
import build_race_relations as brr  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402
from data import dwarovar_tribes as dt  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"
GAME = Path("C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game")
BOM = "\ufeff"
HEADER = ("# Anbennar Overhaul: generated by tools/build_dwarovar_tribes.py; do not edit by hand. "
          "See docs/systems/dwarovar-tribes.md.\n")

GOVERNMENTS_PATH = "common/governments/aov_dwarovar_governments.txt"
TITLES_PATH = "common/landed_titles/aov_dwarovar_tribes.txt"
EFFECTS_PATH = "common/scripted_effects/aov_tribes_pool_effects.txt"
TRIGGERS_PATH = "common/scripted_triggers/aov_tribes_pool_triggers.txt"
VALUES_PATH = "common/script_values/aov_tribes_values.txt"
OVERRIDES_PATH = "common/decisions/zz_aov_dwarovar_tribes_overrides.txt"
MODIFIERS_PATH = "common/modifiers/aov_tribes_modifiers.txt"
LOC_PATH = "localization/english/aov_dwarovar_tribes_l_english.yml"

GOVERNMENT_SOURCE = "common/governments/00_government_types.txt"
# key, race trait, flag, colour, name, realm word, description
GOVERNMENTS = (
    ("orcish_warband_government", "race_orc", "government_is_orcish_warband", "hsv{ 0.00 0.80 0.30 }",
     "Orcish Warband", "Warband",
     "The strongest orc rules until a stronger one kills them. No one here cares whose land it was before."),
    ("goblin_chiefdom_government", "race_goblin", "government_is_goblin_chiefdom", "hsv{ 0.28 0.60 0.30 }",
     "Goblin Chiefdom", "Chiefdom",
     "A chief and their kin hold what the tribe can keep. No one here cares whose land it was before."),
)
ADDED_RULES = ("government_ignores_rightful_liege_penalties", "sticky_government", "use_as_base_on_landed",
               "use_as_base_on_rank_up", "dynasty_named_realms")

POOL_STEM = {"orc": "warband", "goblin": "chiefdom"}
POOL_WORD = {("orc", "duchy"): "Warband", ("orc", "kingdom"): "Warhost", ("orc", "empire"): "Horde",
             ("goblin", "duchy"): "Chiefdom", ("goblin", "kingdom"): "High Chiefdom", ("goblin", "empire"): "Swarm"}
TIER_PREFIX = {"duchy": "d", "kingdom": "k", "empire": "e"}
RACE_TRAIT = {"orc": "race_orc", "goblin": "race_goblin"}
# set_capital_county overwrites these whenever a title is taken; a title must name some county in its definition.
PLACEHOLDER_CAPITAL = {"orc": "c_gor_burad", "goblin": "c_verkal_skomdihr"}
HUE_START = {"orc": 0.0, "goblin": 0.5}

# The decisions that would let a tribe feudalise, challenge the vanilla way or found a dynamic title.
# convert_whole_realm_to_feudalism_west_african_pagan_decision is not here: it is in the game's
# 80_major_decisions.txt, which Anbennar's replaces without it.
DECISION_KEYS = ("convert_to_feudalism_liege_converted_decision", "convert_whole_realm_to_feudalism_decision",
                 "tribal_challenge_ruler_decision", "found_duchy_decision", "found_kingdom_decision",
                 "found_empire_decision")
DECISION_GATE = ("\t\tNOT = { government_has_flag = government_is_dwarovar_tribe } "
                 "# Anbennar Overhaul: Dwarovar tribes")
IS_SHOWN = re.compile(r"^\tis_shown\s*=\s*\{\s*$")


def pool_keys(race: str = None, tier: str = None) -> list:
    """Pool title keys in pool order: every title, or one race's, or one race's in one tier."""
    return [f"{TIER_PREFIX[t]}_aov_{POOL_STEM[r]}_{n:02d}"
            for r in ([race] if race else dt.POOL) for t in ([tier] if tier else dt.POOL[r])
            for n in range(1, dt.POOL[r][t] + 1)]


def render_governments(source: str) -> str:
    m = re.search(r"^tribal_government = \{\n.*?^\}\n", bp.lf(source.lstrip(BOM)), re.S | re.M)
    if not m:
        raise GeneratorError(f"no tribal_government in {GOVERNMENT_SOURCE}")
    out = [HEADER, "\n"]
    for key, trait, flag, colour, *_words in GOVERNMENTS:
        block = m.group(0)
        for old, new in (
                ("tribal_government = {\n", f"{key} = {{\n"),
                ("\tgovernment_rules = {\n", "\tgovernment_rules = {\n" + "".join(f"\t\t{r} = yes\n" for r in ADDED_RULES)),
                ("\troyal_court = any\n", f"\tcan_get_government = {{\n\t\thas_trait = {trait}\n\t}}\n\n\troyal_court = any\n"),
                ("\tflags = {\n", f"\tflags = {{\n\t\tgovernment_is_dwarovar_tribe\n\t\t{flag}\n"),
                ("\tcolor = hsv{ 0.02 0.75 0.36 }\n", f"\tcolor = {colour}\n")):
            if block.count(old) != 1:
                raise GeneratorError(f"tribal_government in {GOVERNMENT_SOURCE} no longer has one line {old.strip()!r}")
            block = block.replace(old, new)
        out += [block, "\n"]
    return "".join(out).rstrip("\n") + "\n"


def pool_colour(race: str, index: int, total: int) -> str:
    """Spread over half the hue circle per race, so no two pool titles share a map colour."""
    hue = HUE_START[race] + 0.5 * index / total
    r, g, b = colorsys.hsv_to_rgb(hue, 0.70, 0.62 + 0.2 * (index % 3) / 2)
    return f"{round(r * 255)} {round(g * 255)} {round(b * 255)}"


def render_pool_titles() -> str:
    out = [HEADER, "# Blank top-level titles with no de jure land, modelled on vanilla's k_danelaw. Only script creates them.\n\n"]
    for race in dt.POOL:
        keys = pool_keys(race)
        for i, key in enumerate(keys):
            out.append(f"{key} = {{\n\tcolor = {{ {pool_colour(race, i, len(keys))} }}\n"
                       f"\tcapital = {PLACEHOLDER_CAPITAL[race]}\n\tde_jure_drift_disabled = yes\n"
                       "\tno_automatic_claims = yes\n\tignore_titularity_for_title_weighting = yes\n\tdefinite_form = yes\n"
                       "\tcan_create = {\n\t\talways = no\n\t}\n}\n\n")
    return "".join(out).rstrip("\n") + "\n"


def render_pool_triggers() -> str:
    out = [HEADER, "\n# Title scope: one of the pool's blank titles.\naov_is_pool_title_trigger = {\n\tOR = {\n"]
    out += [f"\t\tthis = title:{key}\n" for key in pool_keys()]
    out.append("\t}\n}\n\n# Character scope, the future holder: a pool title of TIER (duchy, kingdom, empire) of their race is free.\n"
               "aov_tribe_has_free_title_trigger = {\n\tOR = {\n"
               "\t\tAND = {\n\t\t\thas_trait = race_orc\n\t\t\taov_tribe_free_orc_$TIER$_trigger = yes\n\t\t}\n"
               "\t\tAND = {\n\t\t\thas_trait = race_goblin\n\t\t\taov_tribe_free_goblin_$TIER$_trigger = yes\n\t\t}\n\t}\n}\n\n")
    for race in dt.POOL:
        for tier in dt.POOL[race]:
            out.append(f"aov_tribe_free_{race}_{tier}_trigger = {{\n\tOR = {{\n")
            out += [f"\t\ttitle:{key} = {{ NOT = {{ exists = holder }} }}\n" for key in pool_keys(race, tier)]
            out.append("\t}\n}\n\n")
    return "".join(out).rstrip("\n") + "\n"


def render_pool_effects() -> str:
    out = [HEADER, """
# Character scope, the future holder: saves a free pool title of TIER (duchy, kingdom, empire) of their race as
# scope:aov_new_title, with its capital at their capital county. The caller transfers it, after checking
# aov_tribe_has_free_title_trigger; on_title_gain applies the arms.
aov_tribe_take_free_title_effect = {
	save_scope_as = aov_title_taker
	if = {
		limit = { has_trait = race_orc }
		aov_tribe_free_orc_$TIER$_effect = yes
	}
	else_if = {
		limit = { has_trait = race_goblin }
		aov_tribe_free_goblin_$TIER$_effect = yes
	}
	scope:aov_new_title ?= {
		set_capital_county = scope:aov_title_taker.capital_county
	}
}

"""]
    for race in dt.POOL:
        for tier in dt.POOL[race]:
            out.append(f"aov_tribe_free_{race}_{tier}_effect = {{\n")
            for i, key in enumerate(pool_keys(race, tier)):
                out.append(f"\t{'else_if' if i else 'if'} = {{\n\t\tlimit = {{ title:{key} = {{ NOT = {{ exists = holder }} }} }}\n"
                           f"\t\ttitle:{key} = {{ save_scope_as = aov_new_title }}\n\t}}\n")
            out.append("}\n\n")
    out.append("# Game start: every pool title history gave a holder takes its holder's capital and arms.\n"
               "aov_tribe_sync_all_pool_titles_effect = {\n")
    for key in pool_keys():
        out.append(f"\ttitle:{key} = {{\n\t\tif = {{\n\t\t\tlimit = {{ exists = holder }}\n"
                   "\t\t\tset_capital_county = holder.capital_county\n\t\t\taov_tribe_title_sync_effect = yes\n\t\t}\n\t}\n")
    out.append("}\n")
    return "".join(out)


def render_values() -> str:
    lines = [HEADER, "\n"]
    for tier, (counties, prestige) in dt.FORM.items():
        lines += [f"aov_form_{tier}_counties = {counties}\n", f"aov_form_{tier}_prestige = {prestige}\n"]
    lines.append(f"aov_raise_prestige = {dt.RAISE_PRESTIGE}\n")
    return "".join(lines)


def render_modifiers() -> str:
    return (HEADER + "\n# A ruler who refused an orc's challenge, for life.\naov_refused_challenge = {\n"
            f"\ticon = prestige_negative\n\tgeneral_opinion = {dt.REFUSAL_OPINION}\n}}\n")


def render_decision_overrides(anbennar: Path, game: Path) -> str:
    """Each decision in DECISION_KEYS copied from the loaded file that defines it, gated first thing in is_shown. A game
    file with the same name in Anbennar is not loaded, so it is not searched."""
    folder = "common/decisions"
    ours = {p.name: p for p in sorted((Path(anbennar) / folder).glob("*.txt"))}
    theirs = {p.name: p for p in sorted((Path(game) / folder).glob("*.txt")) if p.name not in ours}
    found = {}
    for path in [*ours.values(), *theirs.values()]:
        text = bp.lf(path.read_bytes().decode("utf-8-sig"))
        keys = tuple(k for k in DECISION_KEYS if re.search(rf"(?m)^{k}\s*=\s*\{{", text))
        if keys:
            bodies = brr.top_blocks(text, keys, path.name)
            found.update({k: (bodies[k], text, path) for k in keys})
    missing = [k for k in DECISION_KEYS if k not in found]
    if missing:
        raise GeneratorError(f"not in the loaded {folder}: " + ", ".join(missing))
    brr.check_clash(DECISION_KEYS, SUBMOD, OVERRIDES_PATH)
    variables, blocks = [], []
    for key in DECISION_KEYS:
        body, text, path = found[key]
        lines = body.split("\n")
        opens = [i for i, line in enumerate(lines) if IS_SHOWN.match(line)]
        if len(opens) != 1:
            raise GeneratorError(f"{key} in {path.name} has {len(opens)} is_shown blocks")
        lines.insert(opens[0] + 1, DECISION_GATE)
        blocks += ["\n".join(lines), ""]
        variables += [v for v in brr.file_variables(text, [body]) if v not in variables]
    return "\n".join([HEADER + "# The vanilla decisions tribes must not reach, with one line added.", "", *variables,
                      *([""] if variables else []), *blocks])


def render_loc() -> str:
    out = ["l_english:"]
    for key, _trait, _flag, _colour, name, realm, desc in GOVERNMENTS:
        out += [f' {key}:0 "{name}"', f' {key}_adj:0 "{realm}"', f' {key}_adjective:0 "{realm}"',
                f' {key}_realm:0 "{realm}"', f' {key}_desc:0 "{desc}"']
    for race in dt.POOL:
        for tier in dt.POOL[race]:
            for key in pool_keys(race, tier):
                dynasty = f"[GetTitleByKey('{key}').GetHolder.GetDynasty.GetName]"
                out += [f' {key}:0 "{dynasty} {POOL_WORD[(race, tier)]}"', f' {key}_adj:0 "{dynasty}"',
                        f' {key}_article:0 "the "']
    out += [' aov_refused_challenge:0 "Refused the Challenge"',
            ' aov_refused_challenge_desc:0 "This ruler was challenged by their own vassal and would not fight."']
    return "\n".join(out) + "\n"


def build_all(anbennar: Path = ANBENNAR, game: Path = GAME) -> dict:
    """{relative path: file bytes} of every generated file."""
    source = (SUBMOD / GOVERNMENT_SOURCE).read_bytes().decode("utf-8-sig")
    texts = {GOVERNMENTS_PATH: render_governments(source), TITLES_PATH: render_pool_titles(),
             EFFECTS_PATH: render_pool_effects(), TRIGGERS_PATH: render_pool_triggers(), VALUES_PATH: render_values(),
             OVERRIDES_PATH: render_decision_overrides(anbennar, game), MODIFIERS_PATH: render_modifiers(),
             LOC_PATH: render_loc()}
    return {rel: (BOM + text).encode("utf-8") for rel, text in texts.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=ANBENNAR)
    parser.add_argument("--game", type=Path, default=GAME)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.game)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, data in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
