"""Regenerate the Lich men-at-arms overrides for Anbennar Overhaul.

A Lich raises the dead (common/men_at_arms_types/aov_lich_maa_types.txt) instead of recruiting living soldiers:
- the generic men-at-arms of Anbennar's 00_maa_types.txt (the game's if Anbennar has none), siege engines excepted,
  are copied with NOT = { has_trait = lich } added to can_recruit (men-at-arms types override by key);
- the same list becomes aov_lich_maa_forbidden_regiment, the regiments a new Lich loses;
- the recruit screens (gui/window_menatarms_type_view.gui, gui/window_menatarms.gui, whole-file only) show mana instead
  of gold for the raised dead (told apart by their icon key) and pay it right after Create and Increase Size.
Rerun after every Anbennar update and CK3 patch:

    python -I tools/build_lich_maa.py [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_portraits as bp  # noqa: E402
from build_hud_override import GeneratorError, brace_delta  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
DEFAULT_ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"
DEFAULT_GAME = Path("C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game")
MARKER = "# Anbennar Overhaul"
BOM = "\ufeff"

MAA_SOURCE = "common/men_at_arms_types/00_maa_types.txt"
MAA_FILE = "common/men_at_arms_types/zz_aov_lich_maa_overrides.txt"
TRIGGERS_FILE = "common/scripted_triggers/aov_lich_maa_forbidden_triggers.txt"
TYPE_VIEW = "gui/window_menatarms_type_view.gui"
REGIMENT_VIEW = "gui/window_menatarms.gui"
OWN_MAA_DIR = "common/men_at_arms_types"
KEEP_TYPES = ("siege_weapon",)  # a Lich still builds siege engines (user choice)
LICH_GATE = f"NOT = {{ has_trait = lich }} {MARKER}: a Lich raises the dead instead"

ICON_KEY = "aov_raised_undead"  # the raised dead's icon (aov_lich_maa_types.txt); the GUI has no type key
IS_ITEM = f"EqualTo_string( MenAtArmsType.GetIconKey, '{ICON_KEY}' )"
IS_SELECTED = f"EqualTo_string( MenAtArmsTypeView.GetSelectedMenAtArmsType.GetIconKey, '{ICON_KEY}' )"
IS_REGIMENT = f"EqualTo_string( Regiment.GetMAAType.GetIconKey, '{ICON_KEY}' )"
PAY = "onclick = \"[GetScriptedGui('aov_lich_maa_pay').Execute( GuiScope.SetRoot( GetPlayer.MakeScope ).End )]\""


def header(source: str) -> str:
    return (f"{MARKER}: generated by tools/build_lich_maa.py from {source}.\n"
            f"{MARKER}: do not edit by hand; edit the script and rerun it.\n")


# ------------------------------------------------------------------------------------------------- men-at-arms

def generic_types(text: str) -> list:
    """(key, block) of every men-at-arms type in the source, siege engines excepted."""
    out = []
    for names, start, end in bp.blocks(text, 1, strict=False):
        body = text[start:end]
        kind = re.search(r"^\ttype\s*=\s*(\w+)", bp.code(body), re.M)
        if not kind:
            raise GeneratorError(f"men-at-arms {names[0]} has no type")
        if kind.group(1) not in KEEP_TYPES:
            out.append((names[0], body))
    if not out:
        raise GeneratorError(f"no men-at-arms types in {MAA_SOURCE}")
    return out


def gate(key: str, body: str) -> str:
    """The block with the Lich gate first in can_recruit (a new can_recruit if it has none)."""
    lines = body.split("\n")
    opens = [i for i, l in enumerate(lines) if re.match(r"^\tcan_recruit\s*=\s*\{\s*$", l)]
    if len(opens) > 1:
        raise GeneratorError(f"{key} has {len(opens)} can_recruit blocks")
    if opens:
        lines.insert(opens[0] + 1, f"\t\t{LICH_GATE}")
    else:
        close = max(i for i, l in enumerate(lines) if l.rstrip() == "}")
        lines[close:close] = ["", "\tcan_recruit = {", f"\t\t{LICH_GATE}", "\t}"]
    return "\n".join(lines)


def own_overrides(submod: Path) -> dict:
    """Keys our other men-at-arms files define, so two overrides never fight."""
    keys = {}
    for path in sorted((submod / OWN_MAA_DIR).glob("*.txt")):
        if path.name == Path(MAA_FILE).name:
            continue
        text = bp.lf(path.read_bytes().decode("utf-8-sig"))
        for names, _s, _e in bp.blocks(text, 1, strict=False):
            keys[names[0]] = path.name
    return keys


def build_maa(text: str, source: str, submod: Path = SUBMOD) -> dict:
    text = bp.lf(text.lstrip(BOM))
    types = generic_types(text)
    taken = own_overrides(submod)
    clash = [f"{k} ({taken[k]})" for k, _b in types if k in taken]
    if clash:
        raise GeneratorError("already overridden elsewhere in the mod: " + ", ".join(clash))
    # The file-local @variables the copied blocks use
    variables = re.findall(r"^@\w+\s*=.*$", text, re.M)
    used = [v for v in variables if any(v.split("=")[0].strip() in body for _k, body in types)]
    parts = [BOM + header(source), "# Anbennar's generic men-at-arms (siege engines excepted) with a Lich gate.", ""]
    parts += used + [""]
    for key, body in types:
        parts += [gate(key, body), ""]
    triggers = [BOM + header(source),
                "# Regiment scope: the living generic soldiers a Lich cannot recruit and loses on becoming one",
                "aov_lich_maa_forbidden_regiment = {", "\tOR = {"]
    triggers += [f"\t\tis_maa_type = {key}" for key, _b in types] + ["\t}", "}", ""]
    return {MAA_FILE: "\n".join(parts).encode("utf-8"), TRIGGERS_FILE: "\n".join(triggers).encode("utf-8")}


# ---------------------------------------------------------------------------------------------------------- GUI

def _block(lines: list, opening: int) -> int:
    depth = 0
    for end in range(opening, len(lines)):
        depth += brace_delta(lines[end])
        if depth == 0:
            return end
    raise GeneratorError(f"unbalanced braces from line {opening + 1}")


def _indent(line: str) -> str:
    return line[: len(line) - len(line.lstrip("\t"))]


def _find(lines: list, needle: str, opener: str) -> tuple:
    """(start, end) of the one block opening with `opener` that holds the line `needle`."""
    hits = [i for i, l in enumerate(lines) if l.strip() == needle]
    if len(hits) != 1:
        raise GeneratorError(f"expected one '{needle}', found {len(hits)}")
    try:
        start = next(i for i in range(hits[0], -1, -1) if lines[i].strip() == opener)
    except StopIteration:
        raise GeneratorError(f"no '{opener}' opens '{needle}'")
    return start, _block(lines, start)


def _mark(indent: str, block: list) -> list:
    return [f"{indent}{MARKER}: begin Lich mana"] + block + [f"{indent}{MARKER}: end Lich mana"]


def patch_type_view(text: str) -> str:
    """The type list's price and the Create button show mana for the raised dead; Create then pays it."""
    if "aov_lich_maa_pay" in text:
        raise GeneratorError(f"{TYPE_VIEW} is already patched")
    lines = text.split("\n")
    # Create button: ours for the raised dead, vanilla's for the rest
    start, end = _find(lines, 'onclick = "[MenAtArmsTypeView.Create]"', "button_primary = {")
    ind, inner = _indent(lines[start]), _indent(lines[start]) + "\t"
    ours = list(lines[start:end + 1])
    ours.insert(1, f'{inner}visible = "[{IS_SELECTED}]"')
    ours = [f'{inner}text = "AOV_LICH_MAA_COST"' if l.strip().startswith("text = ") else l for l in ours]
    create = next(i for i, l in enumerate(ours) if l.strip() == 'onclick = "[MenAtArmsTypeView.Create]"')
    ours.insert(create + 1, f"{inner}{PAY}")
    lines[end + 1:end + 1] = [""] + _mark(ind, ours)
    lines.insert(start + 1, f'{inner}visible = "[Not( {IS_SELECTED} )]" {MARKER}: the raised dead have their own')
    # Price in the type list
    start, end = _find(lines, 'name = "men_at_arms_cost"', "text_single = {")
    ind, inner = _indent(lines[start]), _indent(lines[start]) + "\t"
    price = [f"{ind}text_single = {{", f'{inner}name = "aov_lich_maa_cost"', f'{inner}visible = "[{IS_ITEM}]"',
             f'{inner}text = "AOV_LICH_MAA_COST"', f'{inner}tooltip = "AOV_LICH_MAA_COST_TT"',
             f'{inner}default_format = "#high"', f"{ind}}}"]
    lines[end + 1:end + 1] = _mark(ind, price)
    lines.insert(start + 2, f'{inner}visible = "[Not( {IS_ITEM} )]" {MARKER}: the raised dead cost mana')
    return "\n".join(lines)


def patch_regiment_view(text: str) -> str:
    """Increase Size shows the mana for the raised dead and pays it."""
    if "aov_lich_maa_pay" in text:
        raise GeneratorError(f"{REGIMENT_VIEW} is already patched")
    lines = text.split("\n")
    buy = [i for i, l in enumerate(lines) if l.strip() == 'onclick = "[MenAtArmsView.BuyMaa]"']
    if len(buy) != 1:
        raise GeneratorError(f"expected one BuyMaa button, found {len(buy)}")
    lines.insert(buy[0] + 1, f"{_indent(lines[buy[0]])}{PAY} {MARKER}: pays mana for the raised dead")
    start, end = _find(lines, 'text = "MAA_SIZE_CHANGE"', "text_single = {")
    ind, inner = _indent(lines[start]), _indent(lines[start]) + "\t"
    price = [f"{ind}text_single = {{", f'{inner}visible = "[{IS_REGIMENT}]"', f'{inner}text = "AOV_LICH_MAA_COST"',
             f'{inner}tooltip = "AOV_LICH_MAA_COST_TT"', f"{inner}align = nobaseline", f'{inner}default_format = "#high"',
             f"{ind}}}"]
    lines[end + 1:end + 1] = _mark(ind, price)
    return "\n".join(lines)


def build_gui(raw: bytes, rel: str, patch) -> bytes:
    bom = raw.startswith(BOM.encode("utf-8"))
    text = raw.decode("utf-8-sig")
    crlf = "\r\n" in text
    text = header(rel) + patch(text.replace("\r\n", "\n"))
    if crlf:
        text = text.replace("\n", "\r\n")
    return (BOM.encode("utf-8") if bom else b"") + text.encode("utf-8")


# -------------------------------------------------------------------------------------------------------- build

def find_source(rel: str, anbennar: Path, game: Path) -> Path:
    for root in (anbennar, game):
        if (root / rel).is_file():
            return root / rel
    raise GeneratorError(f"no {rel} in {anbennar} or {game}")


def build_all(anbennar: Path = DEFAULT_ANBENNAR, game: Path = DEFAULT_GAME) -> dict:
    src = find_source(MAA_SOURCE, anbennar, game)
    files = build_maa(src.read_bytes().decode("utf-8"), MAA_SOURCE)
    for rel, patch in ((TYPE_VIEW, patch_type_view), (REGIMENT_VIEW, patch_regiment_view)):
        files[rel] = build_gui(find_source(rel, anbennar, game).read_bytes(), rel, patch)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=DEFAULT_ANBENNAR)
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.game)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
