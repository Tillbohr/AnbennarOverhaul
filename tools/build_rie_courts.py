"""Regenerate Realms in Exile's character-window backgrounds and royal court scenes for Anbennar Overhaul.

Dwarves whose capital is in dwarven terrain, wood elves and moon elves get RiE's throneroom backgrounds (by realm
level) and royal courts (data: tools/data/rie_courts.py): a generated override of Anbennar's scripted illustrations
(our entries before its first throneroom), of its court scene culture sets (ours first, every other set excluding
them) and of the game's grandeur levels, plus the RiE pictures, portrait environments, scene files and court models
they use. Rerun after an RiE, Anbennar or CK3 update:

    python -I tools/build_rie_courts.py [--rie PATH] [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_portraits as bp  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402
from data import rie_courts as data  # noqa: E402

Roots = bp.Roots
SUBMOD = bp.SUBMOD
MARKER = bp.MARKER
BOM = bp.BOM

ILLUSTRATIONS_FILE = "gfx/interface/illustrations/scripted_illustrations/ingame.txt"
ILLUSTRATION_DIR = "gfx/interface/illustrations"
TRIGGERS_FILE = "common/scripted_triggers/aov_rie_court_triggers.txt"
ENVIRONMENTS_DIR = "gfx/portraits/environments"
ENVIRONMENTS_FILE = f"{ENVIRONMENTS_DIR}/aov_rie_environments.txt"
CULTURES_FILE = "gfx/court_scene/scene_cultures/00_default_cultures.txt"
SCENES_DIR = "gfx/court_scene/scene_settings"
GRANDEUR_FILE = f"{SCENES_DIR}/grandeur_levels/grandeur_levels.txt"
ALL_SCENES_TRIGGER = "aov_rie_court_scene_trigger"
EXCLUDE_LINE = f"\t\tNOT = {{ {ALL_SCENES_TRIGGER} = yes }} {MARKER}: Realms in Exile courts\n"


def HEADER(comment="#") -> list:
    return [f"{comment} Anbennar Overhaul: generated by tools/build_rie_courts.py from Realms in Exile and Anbennar.",
            f"{comment} Anbennar Overhaul: do not edit by hand; rerun the generator after an RiE, Anbennar or CK3 update."]


def holder(group: str) -> str:
    return f"aov_rie_court_{group}_trigger"


def tier_trigger(group: str, tier: str) -> str:
    return f"aov_rie_court_{group}_{tier}_trigger"


def view_trigger(group: str, tier: str) -> str:
    return f"aov_rie_court_view_{group}_{tier}_trigger"


def scene_trigger(group: str) -> str:
    return f"aov_rie_court_scene_{group}_trigger"


def check_data() -> None:
    names = [court["scene_culture"] for court in data.COURTS.values()]
    if len(set(names)) != len(names):
        raise GeneratorError("two court groups share a scene culture")
    for group, court in data.COURTS.items():
        for tier, _texture, _environment in court["backgrounds"]:
            if tier not in data.TIERS:
                raise GeneratorError(f"{group}: unknown tier {tier}")


# ------------------------------------------------------------------------------------------------------- triggers

def triggers_file() -> dict:
    """Character-scope triggers: who holds such a court, by tier; the background trigger (the character, else a
    non-ruling spouse, the betrothed or the host, as RiE and vanilla do); the court scene triggers."""
    lines = [BOM + HEADER()[0], HEADER()[1],
             "# Realms in Exile backgrounds and royal courts (tools/data/rie_courts.py). Character scope."]
    for group, court in data.COURTS.items():
        lines += ["", f"# {court['label']}", f"{holder(group)} = {{", "\texists = capital_province"]
        lines += [f"\t{condition}" for condition in court["condition"]] + ["}"]
        for tier in dict.fromkeys(tier for tier, _t, _e in court["backgrounds"]):
            lines += [f"{tier_trigger(group, tier)} = {{", f"\t{holder(group)} = yes", f"\t{data.TIERS[tier]}", "}",
                      f"{view_trigger(group, tier)} = {{", "\tOR = {", f"\t\t{tier_trigger(group, tier)} = yes",
                      "\t\tAND = {", "\t\t\texists = primary_spouse",
                      f"\t\t\tprimary_spouse = {{ is_ruler = no {tier_trigger(group, tier)} = yes }}", "\t\t}",
                      f"\t\tbetrothed ?= {{ {tier_trigger(group, tier)} = yes }}",
                      f"\t\thost ?= {{ {tier_trigger(group, tier)} = yes }}", "\t}", "}"]
        lines += [f"{scene_trigger(group)} = {{", "\tNOT = { government_has_flag = government_is_nomadic }",
                  "\texists = capital_county", f"\t{holder(group)} = yes", "}"]
    lines += ["", f"{ALL_SCENES_TRIGGER} = {{", "\tOR = {"]
    lines += [f"\t\t{scene_trigger(group)} = yes" for group in data.COURTS] + ["\t}", "}"]
    return {TRIGGERS_FILE: ("\n".join(lines) + "\n").encode("utf-8")}


# -------------------------------------------------------------------------------------------------- illustrations

def _illustration_file(roots: Roots, ref: str, files: dict) -> str:
    """Copy the RiE picture ref (relative to gfx/interface/illustrations) unless Anbennar or the game has it; the
    reference to use."""
    rel = f"{ILLUSTRATION_DIR}/{ref}"
    if (roots.rie / rel).is_file():
        new = bp.place_file(roots, rel, rel, files, rel.rsplit("/", 1)[0])
        return new[len(ILLUSTRATION_DIR) + 1:] if new else ref
    if bp._exists_outside(roots, rel) is None:
        raise GeneratorError(f"picture {rel} is in neither RiE, Anbennar nor the game")
    return ref


def background_entries(roots: Roots, files: dict) -> str:
    pieces = [f"\t{MARKER}: Realms in Exile backgrounds (tools/build_rie_courts.py, tools/data/rie_courts.py)\n"]
    for group, court in data.COURTS.items():
        pieces.append(f"\t# {court['label']}\n")
        for tier, texture, environment in court["backgrounds"]:
            reference = _illustration_file(roots, texture, files)
            trigger = f"trigger = {{ {view_trigger(group, tier)} = yes }}"
            pieces.append(f'\ttexture = {{\n\t\treference = "{reference}"\n\t\t{trigger}\n\t}}\n'
                          f'\tenvironment = {{\n\t\treference = "{environment}"\n\t\t{trigger}\n\t}}\n')
    pieces.append(f"\t{MARKER}: end of Realms in Exile backgrounds\n\n")
    return "".join(pieces)


def build_illustrations(roots: Roots, files: dict) -> None:
    """Anbennar's scripted illustrations with our backgrounds in front of its first throneroom."""
    path = roots.anbennar / ILLUSTRATIONS_FILE
    if not path.is_file():
        raise GeneratorError(f"{path} not found")
    raw = path.read_bytes().decode("utf-8")
    text = raw.lstrip(BOM)
    anchor = None
    for names, start, _end in bp.blocks(text, 2, strict=False):
        if names == ("character_view_bg", "texture"):
            match = re.search(r'reference\s*=\s*"([^"]+)"', bp.code(text[start:_end]))
            if match and match.group(1) == data.BACKGROUND_ANCHOR:
                anchor = start
                break
    if anchor is None:
        raise GeneratorError(f"character_view_bg has no texture {data.BACKGROUND_ANCHOR} to put the backgrounds before")
    text = text[:anchor] + background_entries(roots, files) + text[anchor:]
    files[ILLUSTRATIONS_FILE] = (BOM + text).encode("utf-8")


# --------------------------------------------------------------------------------------------------- environments

def _environment_index(files) -> dict:
    index = {}
    for path, text in files:
        for names, start, end in bp.blocks(text, 1, strict=False):
            index.setdefault(names[0], (path, text[start:end]))
    return index


def build_environments(roots: Roots, files: dict) -> int:
    """RiE's portrait environments the backgrounds name and Anbennar and the game lack."""
    ours = _environment_index(bp.effective_texts(roots, ENVIRONMENTS_DIR))
    rie = _environment_index(bp._texts(str(roots.rie / ENVIRONMENTS_DIR), "*.txt"))
    lines = [BOM + HEADER()[0], HEADER()[1], "# Realms in Exile portrait environments of the copied backgrounds."]
    count = 0
    for court in data.COURTS.values():
        for _tier, _texture, environment in court["backgrounds"]:
            if environment in ours or f"# {environment}\n" in "\n".join(lines):
                continue
            if environment not in rie:
                raise GeneratorError(f"environment {environment} is in neither Anbennar, the game nor RiE")
            path, body = rie[environment]
            for ref in sorted(set(bp.FILE_REF.findall(bp.code(body)))):
                rel = bp.resolve_file(roots, ref, ENVIRONMENTS_DIR)
                if rel:
                    new = bp.place_file(roots, ref, rel, files, rel.rsplit("/", 1)[0])
                    if new:
                        body = body.replace(f'"{ref}"', f'"{new}"')
            lines += ["", f"# {environment}", f"# from RiE {ENVIRONMENTS_DIR}/{path}", bp.lf(body).rstrip("\n")]
            count += 1
    files[ENVIRONMENTS_FILE] = ("\n".join(lines) + "\n").encode("utf-8")
    return count


# ---------------------------------------------------------------------------------------------------------- courts

def build_scene_cultures(roots: Roots, files: dict) -> None:
    """Anbennar's scene culture sets with ours first and every one of its own excluding ours."""
    path = roots.anbennar / CULTURES_FILE
    if not path.is_file():
        raise GeneratorError(f"{path} not found")
    text = path.read_bytes().decode("utf-8").lstrip(BOM)
    sets = [names[0] for names, _s, _e in bp.blocks(text, 1, strict=False)]
    clash = [court["scene_culture"] for court in data.COURTS.values() if court["scene_culture"] in sets]
    if clash:
        raise GeneratorError(f"Anbennar already has the court scene culture sets {', '.join(clash)}")
    inserts = []
    for names, start, _end in bp.blocks(text, 2, strict=False):
        if names[1] == "trigger":
            line_end = text.find("\n", start) + 1
            inserts.append(line_end)
    if len(inserts) != len(sets):
        raise GeneratorError(f"{CULTURES_FILE}: {len(sets)} culture sets but {len(inserts)} trigger blocks")
    for offset in sorted(inserts, reverse=True):
        text = text[:offset] + EXCLUDE_LINE + text[offset:]
    ours = [f"{MARKER}: Realms in Exile courts (tools/build_rie_courts.py); every set below excludes them."]
    for group, court in data.COURTS.items():
        ours += [f"{court['scene_culture']} = {{ # {court['label']}",
                 f"\ttrigger = {{ {scene_trigger(group)} = yes }}", "}"]
    first = min(start for _n, start, _e in bp.blocks(text, 1, strict=False))
    text = text[:first] + "\n".join(ours) + "\n\n" + text[first:]
    files[CULTURES_FILE] = (BOM + text).encode("utf-8")


def build_grandeur(roots: Roots, files: dict) -> None:
    """The game's grandeur levels (Anbennar ships none) with RiE's entries for our scene cultures."""
    path = roots.game / "game" / GRANDEUR_FILE
    if (roots.anbennar / GRANDEUR_FILE).is_file():
        path = roots.anbennar / GRANDEUR_FILE
    raw = path.read_bytes().decode("utf-8")
    bom = BOM if raw.startswith(BOM) else ""
    text = raw.lstrip(BOM)
    rie_text = bp.read(roots.rie / GRANDEUR_FILE)
    entries = []
    for court in data.COURTS.values():
        culture = court["scene_culture"]
        found = [rie_text[s:e] for names, s, e in bp.blocks(rie_text, 2, strict=False)
                 if re.search(rf'\bculture\s*=\s*"?{culture}"?', bp.code(rie_text[s:e]))]
        if len(found) != 1:
            raise GeneratorError(f"RiE's grandeur levels have {len(found)} entries for {culture}")
        if re.search(rf'\bculture\s*=\s*"?{culture}"?\s', bp.code(text)):
            raise GeneratorError(f"{path} already has grandeur levels for {culture}")
        entries.append(bp.lf(found[0]))
    top = [(s, e) for names, s, e in bp.blocks(text, 1, strict=False) if names == ("cultures",)]
    if len(top) != 1:
        raise GeneratorError(f"{path}: no single cultures block")
    closing = text.rfind("\n", 0, top[0][1] - 1) + 1
    piece = (f"\t{MARKER}: Realms in Exile courts (tools/build_rie_courts.py)\n" + "".join(entries)
             + f"\t{MARKER}: end of Realms in Exile courts\n")
    text = text[:closing] + piece + text[closing:]
    files[GRANDEUR_FILE] = (bom + text).encode("utf-8")


def build_scenes(roots: Roots, files: dict) -> tuple:
    """The RiE scene files (verbatim), the scene environments they name, and the court models; (models, blocks)."""
    assets = []
    for court in data.COURTS.values():
        for name in court["scenes"]:
            rel = f"{SCENES_DIR}/{name}"
            source = roots.rie / rel
            if not source.is_file():
                raise GeneratorError(f"RiE scene {rel} not found")
            if bp._exists_outside(roots, rel) is not None:
                raise GeneratorError(f"Anbennar or the game already has {rel}")
            text = bp.read(source)
            culture = re.search(r'^\s*culture\s*=\s*"?(\w+)"?', text, re.M)
            if not culture or culture.group(1) != court["scene_culture"]:
                raise GeneratorError(f"{rel} is not a {court['scene_culture']} scene")
            for ref in sorted(set(re.findall(r'"(gfx/[^"]+\.(?:txt|dds))"', text))):
                if (roots.rie / ref).is_file():
                    if bp.place_file(roots, ref, ref, files, ref.rsplit("/", 1)[0]):
                        raise GeneratorError(f"{rel}: {ref} differs from Anbennar's or the game's file of that path")
                    if ref.endswith(".txt") and ref in files:
                        for sub in sorted(set(re.findall(r'"(gfx/[^"]+\.dds)"', bp.read(roots.rie / ref)))):
                            if (roots.rie / sub).is_file() and bp.place_file(roots, sub, sub, files, sub.rsplit("/", 1)[0]):
                                raise GeneratorError(f"{ref}: {sub} differs from Anbennar's or the game's file")
                elif bp._exists_outside(roots, ref) is None:
                    raise GeneratorError(f"{rel}: {ref} is in neither RiE, Anbennar nor the game")
            files[rel] = source.read_bytes()
            for asset in re.findall(r'\basset\s*=\s*"([^"]+)"', text):
                if asset not in assets:
                    assets.append(asset)
    rie = bp.model_index(str(roots.rie / "gfx/models"))
    external = bp.external_models(roots)
    entities = []
    for asset in assets:
        key = ("entity", asset)
        if bp.model_clash(roots, "entity", asset):
            raise GeneratorError(f"court asset {asset}: Anbennar defines it differently from RiE")
        if key in external:
            continue
        if key not in rie:
            raise GeneratorError(f"court asset {asset} is in neither Anbennar, the game nor RiE")
        entities.append(asset)
    models, _variations, order = bp.build_models(roots, entities)
    bp.check_shaders(roots, order)
    files.update(models)
    return len(entities), len(order)


# ------------------------------------------------------------------------------------------------------- build

def build_all(roots: Roots, notes=None) -> dict:
    roots.check()
    check_data()
    notes = [] if notes is None else notes
    bp.RENAMED.clear()
    files = {}
    files.update(triggers_file())
    build_illustrations(roots, files)
    environments = build_environments(roots, files)
    build_scene_cultures(roots, files)
    build_grandeur(roots, files)
    entities, blocks = build_scenes(roots, files)
    if bp.RENAMED:
        notes.append("files copied under aov_rie_ names (Anbennar or the game has its own): "
                     + ", ".join(target for _rel, target in bp.RENAMED))
    binary = {rel: c for rel, c in files.items() if not rel.endswith((".txt", ".asset"))}
    notes.append(f"{environments} environments, {entities} court entities ({blocks} model blocks), {len(binary)} "
                 f"pictures, meshes and textures ({sum(len(c) for c in binary.values()) / 2**20:.0f} MiB)")
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    notes = []
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game), notes)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
