def _county_lines(sb: Segbandal, ckey: str, colour: dict, tabs: int) -> list:
    t = "\t" * tabs
    lines = [f"{t}{ckey} = {{", f"{t}\tcolor = {bs.rgb_text(colour[ckey])}", ""]
    for bkey, pid in zip(sb.barony_keys(ckey), sb.county[ckey].baronies):
        lines += [f"{t}\t{bkey} = {{", f"{t}\t\tprovince = {pid}", f"{t}\t\tcolor = {bs.rgb_text(colour[ckey])}",
                  f"{t}\t}}"]
    return lines + [f"{t}}}"]


def _duchy_lines(sb: Segbandal, duchy: str, colour: dict, tabs: int) -> list:
    t = "\t" * tabs
    lines = [f"{t}{duchy} = {{", f"{t}\tcolor = {bs.rgb_text(colour[duchy])}", f"{t}\tcapital = {sb.capital(duchy)}", ""]
    for ckey in sb.duchies[duchy]:
        lines += _county_lines(sb, ckey, colour, tabs + 1)
    return lines + bs.refuse_tribes(tabs + 1) + [f"{t}}}"]


def render_titles(sb: Segbandal) -> bytes:
    """Every new title under the parking empire (`data.PARKING`), so each has a full chain at load: the new kingdom
    with its duchies; the other new duchies in the parking kingdom; the new counties of Anbennar's duchies in the
    parking duchy. The title history moves each to its real de jure parent."""
    colour = sb.colours()
    grey = bs.rgb_text(data.PARKING_COLOUR)
    empire, pk, pd = data.PARKING
    kkey = data.NEW_KINGDOM[0]
    kcapital = sb.capital(data.AREA_DUCHIES[data.KINGDOMS[kkey][1][0]][0])
    duchies = [d for d in sb.new_duchies() if sb.kingdom_of[d] != kkey]
    counties = [c for d in sb.duchies if d in sb.reused for c in sb.duchies[d]]
    lines = header_lines() + ["", f"{empire} = {{", f"\tcolor = {grey}", f"\tcapital = {kcapital}", "",
                              f"\t{kkey} = {{", f"\t\tcolor = {bs.rgb_text(colour[kkey])}", f"\t\tcapital = {kcapital}", ""]
    for area in data.KINGDOMS[kkey][1]:
        lines += _duchy_lines(sb, data.AREA_DUCHIES[area][0], colour, 2)
    lines += bs.refuse_tribes(2, drift=True) + ["\t}", "", f"\t{pk} = {{", f"\t\tcolor = {grey}", f"\t\tcapital = {sb.capital(duchies[0])}", ""]
    for duchy in duchies:
        lines += _duchy_lines(sb, duchy, colour, 2)
    lines += ["", f"\t\t{pd} = {{", f"\t\t\tcolor = {grey}", f"\t\t\tcapital = {counties[0]}", ""]
    for ckey in counties:
        lines += _county_lines(sb, ckey, colour, 3)
    return _text(lines + bs.refuse_tribes(3) + ["\t\t}"] + bs.refuse_tribes(2, drift=True) + ["\t}"]
                 + bs.refuse_tribes(1, drift=True) + ["}"])


class People:
    """An elder and his son per elder duchy, and per kingdom of KING_LINES, a king and his son: {duchy or kingdom:
    {"dynasty", "dyn_key", "dyn_name", "culture", "chars"}}."""

    def __init__(self, sb: Segbandal, names: list):
        self.lines = {}
        used = set()
        for duchy in sb.elder_duchies:
            prefix = f"aov_sb_{duchy[2:]}"
            chars = []
            for cid, birth, death in ((f"{prefix}_1", data.ELDER_BIRTH, data.ELDER_DEATH), (f"{prefix}_2", data.SON_BIRTH, None)):
                chars.append((cid, names[bs._hash("name:" + cid) % len(names)], bs.life_date(cid, birth),
                              bs.life_date(cid + "d", death) if death else None))
            base = re.sub(r"[\d|]+", "", sb.lay.area_names[sb.duchy_area[duchy]]).strip(" -")
            dyn_name = base if base not in used else f"{base}-{chars[0][1]}"
            used.add(dyn_name)
            culture = data.KINGDOM_CULTURES[sb.kingdom_of[duchy]]
            self.lines[duchy] = {"dynasty": f"aov_sb_dynasty_{duchy[2:]}", "dyn_key": f"dynn_aov_sb_{duchy[2:]}",
                                 "dyn_name": dyn_name, "culture": culture, "chars": chars}
        for kingdom, (slug, dyn_name, _hold) in data.KING_LINES.items():
            prefix = f"aov_sb_king_{slug}"
            chars = []
            for cid, birth, death in ((f"{prefix}_1", data.ELDER_BIRTH, data.ELDER_DEATH), (f"{prefix}_2", data.SON_BIRTH, None)):
                chars.append((cid, names[bs._hash("name:" + cid) % len(names)], bs.life_date(cid, birth),
                              bs.life_date(cid + "d", death) if death else None))
            self.lines[kingdom] = {"dynasty": f"aov_sb_dynasty_king_{slug}", "dyn_key": f"dynn_aov_sb_king_{slug}",
                                   "dyn_name": dyn_name, "culture": data.KINGDOM_CULTURES[kingdom], "chars": chars}


def render_title_history(sb: Segbandal, people: People) -> bytes:
    """De jure moves and the dwarves' holders: Anbennar's kings, the kings of KING_LINES, and the elders left. A living
    hold's county Anbennar leaves unheld goes to its king. Counties held by tribes are not here:
    tools/build_dwarovar_tribes.py rules them."""
    entries = {}  # title -> [(date, entry)], one block per title

    def add(key, *new):
        entries.setdefault(key, []).extend(new)

    def line_holders(line):
        (elder, _, _, death), (son, _, _, _) = line["chars"]
        return (data.START, f"holder = {elder}"), (death, f"holder = {son}")

    kkey = data.NEW_KINGDOM[0]
    add(kkey, (DE_JURE_DATE, f"de_jure_liege = {data.EMPIRE}"))
    for duchy in sb.new_duchies():
        if sb.kingdom_of[duchy] != kkey:
            add(duchy, (DE_JURE_DATE, f"de_jure_liege = {sb.kingdom_of[duchy]}"))
        line = people.lines.get(duchy)
        if line:
            start, succeed = line_holders(line)
            add(duchy, start, (sb.king[sb.kingdom_of[duchy]][0], f"liege = {sb.kingdom_of[duchy]}"), succeed)
            for ckey in sb.duchies[duchy]:
                add(ckey, start, succeed)
    for kingdom, (_slug, _name, hold) in data.KING_LINES.items():
        start, succeed = line_holders(people.lines[kingdom])
        add(kingdom, start, (data.KING_LIEGE_DATE, f"liege = {data.EMPIRE}"), succeed)
        add(hold, start, succeed)
    for duchy in sorted(sb.reused):
        for ckey in sb.duchies[duchy]:
            add(ckey, (DE_JURE_DATE, f"de_jure_liege = {duchy}"))
    for key, target in sb.moves.items():
        add(key, (DE_JURE_DATE, f"de_jure_liege = {target}"))
    for ckey, duchy in sb.dwarven_counties():
        if ckey in sb.county and duchy in people.lines:
            continue  # an elder's, added above
        kingdom = sb.kingdom_of[duchy]
        if kingdom in data.KING_LINES:
            add(ckey, *line_holders(people.lines[kingdom]))
            continue
        try:
            title_holder(sb.history_text, ckey)
        except GeneratorError:
            add(ckey, _holder_entry(sb, duchy, kingdom))
    lines = header_lines()
    for key, dated in entries.items():
        lines += ["", f"{key} = {{"] + [f"\t{d} = {{ {e} }}" for d, e in sorted(dated, key=lambda x: _date_key(x[0]))] + ["}"]
    return _text(lines)


def _holder_entry(sb: Segbandal, duchy: str, kingdom: str) -> tuple:
    """The history entry giving a county its duchy's Anbennar holder, else its kingdom's king."""
    date, holder = sb.duchy_holder.get(duchy, sb.king[kingdom])
    return date, f"holder = {holder}"


def render_province_history(sb: Segbandal) -> bytes:
    lines = header_lines()
    for c in sb.lay.counties:
        culture, religion, holdings = bs.county_people(c, sb.culture_of(c.key), data.RELIGION, data.HOLDINGS[c.type])
        for i, (pid, name) in enumerate(zip(c.baronies, sb.barony_names(c.key))):
            holding = holdings[i] if i < len(holdings) else None
            lines += ["", f"{pid} = {{\t# {name}", f"\tculture = {culture}", f"\treligion = {religion}",
                      f"\tholding = {holding or 'none'}", "}"]
    return _text(lines)


def render_dynasties(people: People) -> bytes:
    lines = header_lines()
    for line in people.lines.values():
        lines += ["", f"{line['dynasty']} = {{", '\tprefix = "dynnp_az"', f"\tname = \"{line['dyn_key']}\"",
                  f"\tculture = {line['culture']}", "}"]
    return _text(lines)


def render_characters(people: People) -> bytes:
    lines = header_lines()
    for line in people.lines.values():
        elder = line["chars"][0][0]
        for cid, name, birth, death in line["chars"]:
            lines += ["", f"{cid} = {{", f'\tname = "{name}"', f"\tdynasty = {line['dynasty']}",
                      f'\treligion = "{data.RELIGION}"', f'\tculture = "{line["culture"]}"', "\ttrait = race_dwarf"]
            if cid != elder:
                lines.append(f"\tfather = {elder}")
            lines.append(f"\t{birth} = {{ birth = yes }}")
            if death:
                lines.append(f"\t{death} = {{ death = yes }}")
            lines.append("}")
    return _text(lines)


def _flag_arms(keys, kkey: str, background: tuple) -> list:
    lines = []
    for key in keys:
        lines += [f"{key} = {{", '\tpattern = "pattern_solid.dds"', f"\tcolor1 = rgb {bs.rgb_text(background)}",
                  "\ttextured_emblem = {", f'\t\ttexture = "{bs.emblem(kkey)}"', "\t}", "}"]
    return lines


def arms_keys() -> set:
    """Anbennar titles this file gives arms to (Anbennar must not script arms for them)."""
    keys = {data.AREA_DUCHIES[a][0] for a in data.REUSED_DUCHY_CHARGES}
    for kkey, (_, duchy, county, _) in data.HOLD_ARMS.items():
        keys |= {kkey, duchy, county}
    return keys


def render_arms(sb: Segbandal) -> bytes:
    """Gor Vazumbrog's kingdom, duchy and hold county carry EU4 I14's flag, Hehodovar's and Gor Ozumbrog's their EU4
    flags (`HOLD_ARMS`); the other new duchies a dwarven charge on their map colour, Hehorod and Xazorod on Anbennar's
    (`REUSED_DUCHY_CHARGES`). Anbennar's other titles keep their arms."""
    colours = sb.colours()
    kkey, name, tag, _, background = data.NEW_KINGDOM
    hold_duchy = data.AREA_DUCHIES[data.KINGDOMS[kkey][1][0]][0]
    lines = header_lines() + ["", f"# {name} (EU4 {tag})"]
    lines += _flag_arms((kkey, hold_duchy, sb.capital(hold_duchy)), kkey, background)
    for hkey, (htag, duchy, county, field) in data.HOLD_ARMS.items():
        lines += ["", f"# {data.KINGDOMS[hkey][0]} (EU4 {htag})"] + _flag_arms((hkey, duchy, county), hkey, field)
    lines.append("")
    for duchy in sb.new_duchies():
        if duchy != hold_duchy:
            lines += bs.duchy_arms(duchy, sb.duchy_area[duchy], colours[duchy], data.DUCHY_CHARGES)
    for area in data.REUSED_DUCHY_CHARGES:
        duchy = data.AREA_DUCHIES[area][0]
        lines += bs.duchy_arms(duchy, area, sb.anbennar_colours[duchy], data.REUSED_DUCHY_CHARGES)
    return _text(lines)


def render_terrain(lay: sl.Layout) -> bytes:
    lines = header_lines() + [""]
    for c in lay.counties:
        lines += [f"{pid}={c.type}" for pid in c.baronies]
    return _text(lines)


def render_regions() -> bytes:
    duchies = " ".join(d for d, _, _ in data.AREA_DUCHIES.values())
    return _text(header_lines() + ["", "world_segbandal = {", f"\tduchies = {{ {duchies} }}", "}"])


def render_loc(sb: Segbandal, people: People) -> bytes:
    def pair(key, name, adj=True):
        return [f' {key}:0 "{name}"'] + ([f' {key}_adj:0 "{name}"'] if adj else [])

    lines = ["l_english:"] + pair(data.NEW_KINGDOM[0], data.NEW_KINGDOM[1])
    for key in data.PARKING:
        lines += pair(key, data.PARKING_NAME)
    for duchy in sb.new_duchies():
        lines += pair(duchy, sb.lay.area_names[sb.duchy_area[duchy]])
    for ckey, c in sb.county.items():
        lines += pair(ckey, c.name)
        for bkey, bname in zip(sb.barony_keys(ckey), sb.barony_names(ckey)):
            lines += pair(bkey, bname, adj=False)
    for line in people.lines.values():
        lines.append(f' {line["dyn_key"]}:0 "{line["dyn_name"]}"')
    return _text(lines)


def build_from_layout(anbennar: Path, lay: sl.Layout, eu4: Path = EU4) -> dict:
    titles_text = _read_titles(anbennar)
    sb = Segbandal(lay, titles_text, _read_history(anbennar), eu4i.province_areas(eu4), sl.area_order(eu4))
    bs.check_new_keys(sb.all_keys(), titles_text)
    for kkey in (data.NEW_KINGDOM[0],) + tuple(data.HOLD_ARMS):
        if not (SUBMOD / bs.EMBLEM_DIR / bs.emblem(kkey)).is_file():
            raise GeneratorError(f"flag emblem missing: {bs.EMBLEM_DIR}/{bs.emblem(kkey)} (see NEW_KINGDOM, HOLD_ARMS)")
    scripted = sorted(arms_keys() & _scripted_arms(anbennar))
    if scripted:
        raise GeneratorError(f"Anbennar now scripts arms for {', '.join(scripted)}; drop them from HOLD_ARMS or "
                             "REUSED_DUCHY_CHARGES, or decide which arms win")
    missing = bs.missing_charges(anbennar, DEFAULT_GAME, {**data.DUCHY_CHARGES, **data.REUSED_DUCHY_CHARGES})
    if missing:
        raise GeneratorError(f"DUCHY_CHARGES emblems found nowhere: {', '.join(missing)}")
    wanted = {data.AREA_DUCHIES[a][0] for a in data.DUCHY_CHARGES}
    other = set(sb.new_duchies()) - {data.AREA_DUCHIES[data.KINGDOMS[data.NEW_KINGDOM[0]][1][0]][0]}
    if wanted != other:
        raise GeneratorError(f"DUCHY_CHARGES must list exactly the areas of the new duchies but Gor Vazumbrog's: "
                             f"missing {sorted(other - wanted)}, extra {sorted(wanted - other)}")
    people = People(sb, bs.male_names(anbennar))
    return {
        TITLES: render_titles(sb),
        TITLE_HISTORY: render_title_history(sb, people),
        PROVINCE_HISTORY: render_province_history(sb),
        CHARACTERS: render_characters(people),
        DYNASTIES: render_dynasties(people),
        TERRAIN: render_terrain(lay),
        REGIONS: render_regions(),
        LOC: render_loc(sb, people),
        ARMS: render_arms(sb),
    }


def build_all(anbennar: Path = ANBENNAR, eu4: Path = EU4) -> dict:
    """Every output (rel path -> bytes); nothing is written here."""
    return build_from_layout(anbennar, bs.layouts(anbennar, eu4)[1], eu4)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=ANBENNAR)
    parser.add_argument("--eu4", type=Path, default=EU4)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.eu4)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
