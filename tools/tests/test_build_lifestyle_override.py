    "window = {\n"
    "\t\tbackground = {\n"
    "\t\t\tvisible = \"[EqualTo_string( Lifestyle.GetKey, 'learning_lifestyle' )]\"\n"
    "\t\t\ttexture = \"gfx/interface/progressbars/progress_gray.dds\"\n"
    "\t\t}\n"
