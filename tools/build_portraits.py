@lru_cache(maxsize=None)
def model_index(models: str) -> dict:
    """(pdxmesh|entity, name) -> (relative asset path, block text) for every .asset under a gfx/models folder."""
    index = {}
    for path, text in _texts(models, "*.asset"):
        for names, start, end in blocks(text, 1, strict=False):
            if names[0] in ("pdxmesh", "entity"):
                body = text[start:end]
                name = block_name(body)
                if name:
                    index.setdefault((names[0], name), (path, body))
    return index


@lru_cache(maxsize=None)
def file_names(folder: str) -> dict:
    names = {}
    root = Path(folder)
    if root.is_dir():
        for path in sorted(root.rglob("*")):
            if path.is_file():
                names.setdefault(path.name.lower(), []).append(path)
    return names


def external_models(roots: Roots) -> set:
    names = set()
    for root in (roots.anbennar / "gfx/models", roots.game / "game/gfx/models"):
        names.update(model_index(str(root)))
    return names


def collect_models(roots: Roots, entities: list) -> list:
    """[(kind, name, rie asset path, block)] of the RiE blocks the entities need (dependencies first); names Anbennar
    or the game define are theirs and are not copied."""
    rie = model_index(str(roots.rie / "gfx/models"))
    external = external_models(roots)
    done, order = set(), []

    def visit(kind, name, chain):
        key = (kind, name)
        if key in done or key in external:
            return
        if key in chain:
            raise GeneratorError(f"{kind} {name} refers to itself")
        if key not in rie:
            raise GeneratorError(f"{kind} {name} is in neither Anbennar, the game nor RiE (via {' -> '.join(chain)})")
        path, body = rie[key]
        if kind == "entity":
            for ref_kind, ref in MODEL_REF.findall(code(body)):
                if ref != name:
                    visit("pdxmesh" if ref_kind == "pdxmesh" else "entity", ref, chain + [name])
        done.add(key)
        order.append((kind, name, path, body))

    for entity in entities:
        visit("entity", entity, [])
    return order


def _exists_outside(roots: Roots, rel: str):
    """The bytes of rel in Anbennar or the game (Anbennar first), else None."""
    for root in (roots.anbennar, roots.game / "game"):
        path = root / rel
        if path.is_file():
            return path.read_bytes()
    return None


def _by_name_outside(roots: Roots, name: str) -> bool:
    return any(name.lower() in file_names(str(root)) for root in
               (roots.anbennar / "gfx", roots.game / "game/gfx"))


def resolve_file(roots: Roots, ref: str, asset_dir: str):
    """The RiE-relative path of the file a block names, or None when Anbennar or the game provides it."""
    rie = roots.rie
    if "/" in ref or "\\" in ref:
        rel = ref.replace("\\", "/")
        if (rie / rel).is_file():
            return rel
        if _exists_outside(roots, rel) is not None:
            return None
        raise GeneratorError(f"{ref} not found in RiE, Anbennar or the game")
    beside = f"{asset_dir}/{ref}"
    if (rie / beside).is_file():
        return beside
    if _exists_outside(roots, beside) is not None:
        return None
    found = file_names(str(rie / "gfx/models")).get(ref.lower(), [])
    if found:
        if len({p.read_bytes() for p in found}) > 1:
            raise GeneratorError(f"{ref} exists with different content in several RiE folders")
        return found[0].relative_to(rie).as_posix()
    if _by_name_outside(roots, ref):
        return None
    raise GeneratorError(f"{ref} (named in {asset_dir}) not found in RiE, Anbennar or the game")


KEPT = []  # RiE paths where Anbennar or the game has its own different file, which stays (reported as a note)


def copy_file(roots: Roots, rel: str, files: dict) -> None:
    """Copy an RiE file at its RiE path, unless Anbennar or the game has a file there: never override theirs (RiE
    edits some vanilla files in place; overriding them would change vanilla characters too)."""
    outside = _exists_outside(roots, rel)
    if outside is not None:
        if outside != (roots.rie / rel).read_bytes() and rel not in KEPT:
            KEPT.append(rel)
        return
    files[rel] = (roots.rie / rel).read_bytes()


def build_models(roots: Roots, entities: list) -> tuple:
    """(asset, mesh and texture files, variation names, model blocks)."""
    order = collect_models(roots, entities)
    by_asset, files, variations = {}, {}, []
    for kind, name, path, body in order:
        by_asset.setdefault(path, []).append((kind, name, body))
        asset_dir = "gfx/models/" + path.rsplit("/", 1)[0] if "/" in path else "gfx/models"
        for ref in FILE_REF.findall(code(body)):
            rel = resolve_file(roots, ref, asset_dir)
            if rel:
                copy_file(roots, rel, files)
        for variation in VARIATION_REF.findall(code(body)):
            if variation not in variations:
                variations.append(variation)
    for path, items in by_asset.items():
        folder, _sep, stem = path.rpartition("/")
        rel = f"gfx/models/{folder}/aov_rie_{stem}" if folder else f"gfx/models/aov_rie_{stem}"
        lines = [BOM + HEADER()[0], HEADER()[1], f"# Blocks copied from RiE gfx/models/{path}."]
        for kind, name, body in items:
            lines += ["", lf(body).rstrip("\n")]
        files[rel] = ("\n".join(lines) + "\n").encode("utf-8")
    return files, variations, order


def check_shaders(roots: Roots, order: list) -> None:
    """Every shader a copied pdxmesh names is an Effect of the game's or this mod's portrait shaders."""
    defined = set()
    for root in (roots.game / "game/gfx/FX", roots.anbennar / "gfx/FX", SUBMOD / "gfx/FX"):
        if root.is_dir():
            for path in root.rglob("*.shader"):
                defined.update(re.findall(r"^\s*Effect\s+(\w+)", read(path), re.M))
    for kind, name, _path, body in order:
        for shader in SHADER_REF.findall(code(body)):
            if shader not in defined:
                raise GeneratorError(f"{kind} {name} uses shader {shader}, which no shader file defines")


# --------------------------------------------------------------------------------------------------- variations

def variation_index(files) -> dict:
    """(kind, name) -> (path, block) for the top-level variation, pattern_textures and pattern_layout blocks."""
    index = {}
    for path, text in files:
        for names, start, end in blocks(text, 1, strict=False):
            if names[0] in ("variation", "pattern_textures", "pattern_layout"):
                body = text[start:end]
                name = block_name(body)
                if name:
                    index.setdefault((names[0], name), (path, body))
    return index


def build_variations(roots: Roots, names: list) -> tuple:
    ours = variation_index(effective_texts(roots, "gfx/portraits/accessory_variations"))
    rie = variation_index(_texts(str(roots.rie / "gfx/portraits/accessory_variations"), "*.txt"))
    wanted = [("variation", name) for name in names]
    copied, files = [], {}
    while wanted:
        key = wanted.pop(0)
        if key in ours or key in copied:
            continue
        if key not in rie:
            raise GeneratorError(f"{key[0]} {key[1]} is in neither Anbennar, the game nor RiE")
        copied.append(key)
        body = code(rie[key][1])
        wanted += [("pattern_textures", n) for n in re.findall(r'\btextures\s*=\s*"([^"]+)"', body)]
        wanted += [("pattern_layout", n) for n in re.findall(r'\blayout\s*=\s*"([^"]+)"', body)]
        for ref in FILE_REF.findall(body):
            rel = resolve_file(roots, ref, "gfx/portraits/accessory_variations")
            if rel:
                copy_file(roots, rel, files)
    lines = [BOM + HEADER()[0], HEADER()[1], "# Realms in Exile accessory variations the copied models use."]
    for kind in ("pattern_layout", "pattern_textures", "variation"):
        for key in copied:
            if key[0] == kind:
                path, body = rie[key]
                lines += ["", f"# from RiE gfx/portraits/accessory_variations/{path}", lf(body).rstrip("\n")]
    files[VARIATIONS_FILE] = ("\n".join(lines) + "\n").encode("utf-8")
    return files, len(copied)


# ------------------------------------------------------------------------------------------------------- build

def build_all(roots: Roots, notes=None) -> dict:
    roots.check()
    notes = [] if notes is None else notes
    KEPT.clear()
    entries = copied_entries(roots)
    check_references(roots, entries)
    files = {}
    files.update(modifier_files(entries))
    files.update(triggers_file())
    genes, accessory_names, gene_notes = build_genes(roots, entries)
    files.update(genes)
    notes += gene_notes
    accessories, entities, count = build_accessories(roots, accessory_names)
    files.update(accessories)
    models, variation_names, order = build_models(roots, entities)
    check_shaders(roots, order)
    files.update(models)
    variations, variation_count = build_variations(roots, variation_names)
    files.update(variations)
    if KEPT:
        notes.append(f"{len(KEPT)} files RiE changed at vanilla paths keep Anbennar's or the game's version: "
                     + ", ".join(KEPT))
    notes.append(f"{count} accessories, {len(order)} model blocks, {variation_count} variation blocks, "
                 f"{sum(1 for rel in files if not rel.endswith(('.txt', '.asset')))} meshes and textures "
                 f"({sum(len(c) for rel, c in files.items() if not rel.endswith(('.txt', '.asset'))) / 2**20:.0f} MiB)")
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    notes = []
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game), notes)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
