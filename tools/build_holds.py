"""Generate the dwarven hold levels, script values and localization from tools/data/holds.py.

The level effects are Realms in Exile's dwarven_depths_01..10, rewritten by tools/build_rie_dwarves.py
(depths_level_effects); the hold art is copied from Anbennar's castles. Rerun after editing tools/data/holds.py or
after an Anbennar, RiE or CK3 update (after tools/build_rie_dwarves.py):

    python -I tools/build_holds.py [--rie PATH] [--anbennar PATH] [--game PATH]
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I does not add the script's folder
from data import holds  # noqa: E402
from data.holding_models import HOLD_DWARF_MESHES  # noqa: E402
import build_holding_models as bhm  # noqa: E402
import build_portraits as bp  # noqa: E402
import build_rie_dwarves as rd  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
ANBENNAR_CK3 = SUBMOD.parent / "anbennar-ck3-dev-master"
CASTLE_FILE = "common/buildings/00_castle_buildings.txt"
HEADER = "# Anbennar Overhaul: generated by tools/build_holds.py from tools/data/holds.py; do not edit by hand.\n"
ICON = "icon_building_ramparts.dds"

BUILDINGS_PATH = "common/buildings/aov_dwarven_holds.txt"
VALUES_PATH = "common/script_values/aov_hold_values.txt"
LOC_PATH = "localization/english/aov_holds_l_english.yml"
SETUP_PATH = "common/scripted_effects/aov_hold_setup_effects.txt"
MODIFIERS_PATH = "common/modifiers/aov_hold_modifiers.txt"

BAND_DESCS = (
    (range(1, 3), "A young hold, a few halls and passages cut into the rock."),
    (range(3, 5), "A growing hold with wide galleries, strong gates and busy workshops."),
    (range(5, 8), "A great hold; whole quarters of the mountain have been delved and fortified."),
    (range(8, 11), "A mighty hold, a mountain-city of deep halls and unbreakable gates."),
)


def castle_assets(root: Path):
    """The @holding_illustration_* lines and, per castle level in ASSET_BAND, the lines of its asset = { } blocks."""
    lines = (Path(root) / CASTLE_FILE).read_text(encoding="utf-8-sig").splitlines()
    variables = [l for l in lines if l.startswith("@holding_illustration_")]
    assets, current, block = {}, None, None
    for line in lines:
        if line.startswith("castle_0") and line.endswith(" = {"):
            current = line.split()[0]
            assets[current] = []
            continue
        if current is None:
            continue
        if line.startswith("\t\tasset = {"):
            block = assets[current]
        if block is not None:
            block.append(line)
            if line == "\t\t}":
                block = None
    return variables, {k: v for k, v in assets.items() if k in set(holds.ASSET_BAND.values())}


def fmt(x):
    return f"{x:g}" if isinstance(x, float) else str(x)


def level_key(n):
    return f"dwarven_hold_{n:02d}"


# The hold levels work only under a dwarven holder in an unruined hold.
IS_ENABLED = ("\tis_enabled = {\n\t\tscope:holder = {\n\t\t\tis_dwarvish_culture = yes\n\t\t}\n"
              "\t\tNOT = { has_variable = aov_hold_ruined }\n\t}\n\n")


def dwarf_asset(n, castle_lines, fallback, regions, provinces):
    """The RiE dwarven model asset of hold level n. It serves every holder culture and every graphical region
    (the region outranks the culture in CK3's asset choice) and lists the dwarven-terrain provinces as the castle
    and city assets do (a province list outranks the copied western castle asset's culture and region, so a
    non-dwarf holder of a hold still sees the dwarf model), with the illustration and sound of the level's first
    castle asset that has no DLC flag and serves the fallback gfx key."""
    template = bhm.template_asset(bhm.original_assets(castle_lines), fallback)
    keep = [l for l in template if l.strip().startswith(("illustration =", "soundeffect ="))]
    return "\n".join(["\t\tasset = {  # Anbennar Overhaul: RiE dwarf hold model", "\t\t\ttype = pdxmesh",
                      f'\t\t\tname = "{HOLD_DWARF_MESHES[n]}"', *keep,
                      "\t\t\tprovinces = { %s }" % " ".join(str(p) for p in provinces),
                      "\t\t\tgraphical_regions = { %s }" % " ".join(regions), "\t\t}"])


def render_level(n, assets, gfx, effects: str):
    """dwarven_hold_<n>: the dwarf model and the castle art of its band, never built (digs only), and `effects`, the
    rewritten effect lines of RiE's dwarven_depths_<n> (one tab deep)."""
    band = holds.ASSET_BAND[n]
    out = [f"{level_key(n)} = {{\n", "\tconstruction_time = slow_construction_time\n\n",
           "\tassets = {\n", dwarf_asset(n, assets[band], *gfx) + "\n" + "\n".join(assets[band]) + "\n", "\t}\n\n",
           "\tcan_construct_potential = {\n\t\talways = no\n\t}\n\n", IS_ENABLED,
           "\tcost_gold = main_building_tier_1_cost\n"]
    if n < 10:
        out.append(f"\tnext_building = {level_key(n + 1)}\n")
    out.append("\n")
    out.append(effects)
    out.append(f"\n\tflag = castle\n\n\ttype_icon = \"{ICON}\"\n\n\tai_value = {{\n\t\tbase = 0\n\t}}\n}}\n")
    return "".join(out)


def dwarf_gfx(root: Path) -> tuple:
    """(the dwarven main key's fallback key, graphical regions, dwarf-model provinces) read from Anbennar's files."""
    texts = bhm.culture_texts(bhm.Roots(rie=None, anbennar=Path(root), game=None))
    main = bhm.data.GROUPS["dwarven"]["gfx"]
    return bhm.gfx_fallbacks(texts)[main], bhm.graphical_regions(root), bhm.dwarf_model_provinces(root)


def render_buildings(roots: bp.Roots) -> str:
    variables, assets = castle_assets(roots.anbennar)
    gfx = dwarf_gfx(roots.anbennar)
    effects = rd.depths_level_effects(roots)
    parts = [HEADER, "\n", "\n".join(variables) + "\n\n"]
    parts += [render_level(n, assets, gfx, effects[n]) + "\n" for n in range(1, 11)]
    return "".join(parts).rstrip("\n") + "\n"


def render_values() -> str:
    levels = "".join(
        f"\tif = {{\n\t\tlimit = {{ has_building_or_higher = {level_key(n)} }}\n\t\tadd = 1\n\t}}\n"
        for n in range(1, 11))
    return (HEADER + "\n"
            "# Province scope: 1..10 from the dwarven hold building, 0 without one.\n"
            f"aov_hold_level = {{\n\tvalue = 0\n{levels}}}\n\n"
            "# Province scope: the level a dig aims for: the variable aov_dig_target_level, else the next level.\n"
            "aov_dig_target_value = {\n\tvalue = aov_hold_level\n\tadd = 1\n"
            "\tif = {\n\t\tlimit = { has_variable = aov_dig_target_level }\n"
            "\t\tadd = {\n\t\t\tvalue = var:aov_dig_target_level\n\t\t\tsubtract = aov_hold_level\n\t\t\tsubtract = 1\n\t\t}\n\t}\n}\n\n"
            "# Province scope: gold cost of a dig.\n"
            f"aov_dig_cost = {{\n\tvalue = aov_dig_target_value\n\tmultiply = {holds.DIG_COST_PER_LEVEL}\n}}\n\n"
            "# Province scope: months a dig takes, 12 x (8 + 4 x (target - 1)).\n"
            "aov_dig_months = {\n\tvalue = aov_dig_target_value\n\tsubtract = 1\n\tmultiply = 4\n\tadd = 8\n\tmultiply = 12\n}\n")


HOLDING_LOC = [
    ' dwarven_hold_holding:0 "Dwarven Hold"',
    ' dwarven_hold_holding_concept_key:0 "Dwarven Hold"',  # the holding view's "Your ... Holding" (GetConceptName)
    ' dwarven_hold_holding_build_speed:0 "Dwarven Hold [buildings|E] Construction Time"',
    ' dwarven_hold_holding_build_gold_cost:0 "Dwarven Hold [buildings|E] Construction Cost"',
    ' dwarven_hold_holding_build_piety_cost:0 "Dwarven Hold [buildings|E] Piety Cost"',
    ' dwarven_hold_holding_build_prestige_cost:0 "Dwarven Hold [buildings|E] Prestige Cost"',
    ' dwarven_hold_holding_holding_build_speed:0 "Dwarven Hold [holding|E] Construction Time"',
    ' dwarven_hold_holding_holding_build_gold_cost:0 "Dwarven Hold [holding|E] Construction Cost"',
    ' dwarven_hold_holding_holding_build_piety_cost:0 "Dwarven Hold [holding|E] Piety Cost"',
    ' dwarven_hold_holding_holding_build_prestige_cost:0 "Dwarven Hold [holding|E] Prestige Cost"',
]


def render_modifiers() -> str:
    ruined = "".join(f"\t{k} = {fmt(v)}\n" for k, v in holds.RUINED_MODIFIER.items())
    return (HEADER + "\n"
            f"aov_ruined_hold = {{\n\ticon = economy_negative\n{ruined}}}\n\n"
            "# Province modifier while a ruined hold is being restored; the effects come from the restoration.\n"
            "aov_restoring_hold = {\n\ticon = economy_positive\n}\n\n"
            "# County modifier from a rich vein found while digging.\n"
            "aov_hold_rich_vein = {\n\ticon = economy_positive\n\ttax_mult = 0.1\n}\n\n"
            "# Province modifier while a dig to that level is under way; it has no effects.\n"
            + "\n".join(f"aov_delving_{n:02d} = {{\n\ticon = economy_positive\n}}" for n in range(2, 11)) + "\n")


def render_setup() -> str:
    blocks = []
    for h in holds.HOLDS:
        lines = [f"\t# {h['name']}", f"\ttitle:{h['barony']}.title_province = {{",
                 "\t\tset_holding_type = dwarven_hold_holding"]
        lines += [f"\t\tadd_building = {level_key(n)}" for n in range(2, h["start_level"] + 1)]
        lines.append("\t\tset_variable = { name = aov_dig_progress value = 0 }")
        if h["ruined"]:
            lines += ["\t\tset_variable = aov_hold_ruined",
                      "\t\tcounty = { add_county_modifier = { modifier = aov_ruined_hold } }"]
        lines.append("\t}")
        blocks.append("\n".join(lines))
    return (HEADER + "\n# Converts the nine dwarven holds at game start. Special buildings are left alone.\n"
            "aov_hold_setup_effect = {\n" + "\n".join(blocks) + "\n}\n")


def loc_lines():
    out = list(HOLDING_LOC)
    out += [' aov_ruined_hold:0 "Ruined Hold"',
            ' aov_ruined_hold_desc:0 "The halls lie broken and empty, and the county gains little from them."',
            ' aov_restoring_hold:0 "Hold Under Restoration"',
            ' aov_restoring_hold_desc:0 "Dwarven masons are clearing and rebuilding the halls of this hold."',
            ' aov_hold_rich_vein:0 "Rich Vein"',
            ' aov_hold_rich_vein_desc:0 "The diggers struck a rich vein of ore."']
    for n in range(2, 11):
        out += [f' aov_delving_{n:02d}:0 "Delving to Level {n}"',
                f' aov_delving_{n:02d}_desc:0 "Dwarves are digging this hold deeper."']
    for n in range(1, 11):
        key = level_key(n)
        desc = next(d for r, d in BAND_DESCS if n in r)
        out += [f' building_{key}:0 "Delved Hold ({n})"', f' building_{key}_desc:0 "{desc}"',
                f' building_type_{key}:0 "Delved Hold ({n})"', f' building_type_{key}_desc:0 "{desc}"']
    return out


def render_loc() -> str:
    return "l_english:\n" + "\n".join(loc_lines()) + "\n"


def render_all(root: Path = None, roots: bp.Roots = None) -> dict:
    """{relative path: text} of every generated file. roots (default bp.Roots.default()) gives RiE, Anbennar and the
    game; root, when given, replaces its Anbennar folder."""
    roots = roots or bp.Roots.default()
    if root is not None:
        roots = bp.Roots(rie=roots.rie, anbennar=Path(root), game=roots.game)
    return {BUILDINGS_PATH: render_buildings(roots), VALUES_PATH: render_values(), LOC_PATH: render_loc(),
            SETUP_PATH: render_setup(), MODIFIERS_PATH: render_modifiers()}


def write_all(files: dict, root: Path = SUBMOD) -> None:
    for rel, text in files.items():
        out = Path(root) / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(b"\xef\xbb\xbf" + text.replace("\r\n", "\n").encode("utf-8"))


def main() -> int:
    default = bp.Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    try:
        roots = bp.Roots(rie=args.rie, anbennar=args.anbennar, game=args.game)
        roots.check()
        files = render_all(roots=roots)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    write_all(files)
    for rel in files:
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
