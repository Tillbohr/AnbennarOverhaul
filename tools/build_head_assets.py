"""Regenerate the head .asset overrides that carry the overhaul's extra head shapes (gnoll head; see SHAPES).

A head shape is a blend shape on the game's own head mesh, so it must be listed in the head mesh and the head entity,
which Anbennar defines in its copies of the game's male_head.asset and female_head.asset. Assets can only be overridden
as whole files, so the submod ships full copies of those two files with these lines added next to Anbennar's kobold
head. Run this after updating the base mod:

    python -I tools/build_head_assets.py [path/to/anbennar/mod/folder]

The base path defaults to ../anbennar-ck3-dev-master next to this submod.
"""

import argparse
import re
import sys
from pathlib import Path

MARKER = "# Anbennar Overhaul"

SUBMOD = Path(__file__).resolve().parent.parent
DEFAULT_ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"

HEADS = {
    "male": "gfx/models/portraits/male_head/male_head.asset",
    "female": "gfx/models/portraits/female_head/female_head.asset",
}

# sex: (blend shape id, mesh relative to the asset's folder), added after Anbennar's kobold head normals
SHAPES = {
    "male": [("male_gnoll_head", "blendshapes/aov_gnoll_male_head_bs.mesh")],
    "female": [("female_gnoll_head", "blendshapes/aov_gnoll_female_head_bs.mesh")],
}

# sex: (attribute a gene sets, blend shape id), added after Anbennar's kobold head proportions
ATTRIBUTES = {
    "male": [("gnoll_head_bs", "male_gnoll_head")],
    "female": [("gnoll_head_bs", "female_gnoll_head")],
}


def add_head_lines(text: str, sex: str) -> str:
    """Anbennar's head asset with the blend shapes after the kobold head normals and the attributes after the kobold
    head proportions. Exits if either kobold line is missing or repeated."""
    anchors = (
        (re.compile(rf'^(\s*)blend_shape = \{{ id = "{sex}_kobold_head_normals"'),
         ['{indent}blend_shape = {{ id = "%s"\t\ttype = "%s" }} %s' % (shape_id, mesh, MARKER)
          for shape_id, mesh in SHAPES[sex]]),
        (re.compile(r'^(\s*)attribute = \{ name = "kobold_head_proportions"'),
         ['{indent}attribute = {{ name = "%s"\t\tblend_shape = "%s" }} %s' % (attribute, shape_id, MARKER)
          for attribute, shape_id in ATTRIBUTES[sex]]),
    )
    lines = [l for l in text.split("\n") if not l.endswith(" " + MARKER)]  # idempotent
    for pattern, new in anchors:
        hits = [i for i, l in enumerate(lines) if pattern.match(l)]
        if len(hits) != 1:
            sys.exit(f"error: expected one line matching {pattern.pattern!r} in the {sex} head asset, found {len(hits)}")
        indent = pattern.match(lines[hits[0]]).group(1)
        lines[hits[0] + 1:hits[0] + 1] = [line.format(indent=indent) for line in new]
    return "\n".join(lines)


def build(base: Path) -> None:
    for sex, rel in HEADS.items():
        src = base / rel
        if not src.is_file():
            sys.exit(f"error: base head asset not found: {src}")
        for _shape_id, mesh in SHAPES[sex]:
            if not (SUBMOD / Path(rel).parent / mesh).is_file():
                sys.exit(f"error: {mesh} missing; run the system's --import first")
        raw = src.read_bytes()
        bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw.decode("utf-8-sig")
        crlf = "\r\n" in text
        text = add_head_lines(text.replace("\r\n", "\n"), sex)
        header = (
            f"{MARKER}: generated by tools/build_head_assets.py from Anbennar's {rel}.\n"
            f"{MARKER}: do not edit by hand; rerun the script after an Anbennar update.\n"
        )
        text = header + text
        if crlf:
            text = text.replace("\n", "\r\n")
        out = SUBMOD / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))
        print(f"wrote {out}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("base", nargs="?", type=Path, default=DEFAULT_ANBENNAR, help="Anbennar CK3 mod folder")
    build(parser.parse_args().base)


if __name__ == "__main__":
    main()
