"""Regenerate the holding-model files for Anbennar Overhaul.

Gives Anbennar's elven, dwarven and Escanni cultures Realms in Exile's holding models: culture files
with the new building_gfx keys, and the graphical region of dwarven mountain provinces. Rerun after
an Anbennar or RiE update:

    python -I tools/build_holding_models.py [--rie PATH] [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_hud_override import GeneratorError  # noqa: E402
from data import holding_models as data  # noqa: E402

MARKER = "# Anbennar Overhaul"
SUBMOD = Path(__file__).resolve().parent.parent
CULTURES_DIR = "common/culture/cultures"
TERRAIN_FILE = "common/province_terrain/00_province_terrain.txt"
REGION_FILE = "map_data/geographical_regions/aov_graphical_regions.txt"
BOM = "\ufeff"

TOP_KEY = re.compile(r"^\ufeff?\s*([A-Za-z0-9_.\-]+)\s*=\s*\{")
HERITAGE_LINE = re.compile(r"^\s*heritage\s*=\s*([A-Za-z0-9_]+)")
GFX_LINE = re.compile(r"^(\s*building_gfx\s*=\s*\{)(.*)$")
TERRAIN_LINE = re.compile(r"^\s*(\d+)\s*=\s*([A-Za-z0-9_]+)")


@dataclass(frozen=True)
class Roots:
    rie: Path
    anbennar: Path
    game: Path

    @classmethod
    def default(cls):
        steam = Path("C:/Program Files (x86)/Steam/steamapps")
        return cls(rie=steam / "workshop/content/1158310/2291024373",
                   anbennar=SUBMOD.parent / "anbennar-ck3-dev-master",
                   game=steam / "common/Crusader Kings III")

    def check(self):
        for name, path in (("Realms in Exile", self.rie), ("Anbennar", self.anbennar),
                           ("Crusader Kings III", self.game)):
            if not path.is_dir():
                raise GeneratorError(f"{name} not found at {path}")


def HEADER() -> list:
    return [f"{MARKER}: generated by tools/build_holding_models.py from Realms in Exile and Anbennar.",
            f"{MARKER}: do not edit by hand; rerun the generator after an RiE or Anbennar update."]


def strip_comment(line: str) -> str:
    """The line without a '#' comment (a '#' inside double quotes does not start one)."""
    in_string = False
    for index, ch in enumerate(line):
        if ch == '"':
            in_string = not in_string
        elif ch == "#" and not in_string:
            return line[:index]
    return line


def culture_blocks(text: str) -> list:
    """Top-level blocks of a culture file: (key, start, end, body), offsets into text, end after the
    closing line's newline. Comments outside strings are ignored."""
    blocks, depth, current, offset = [], 0, None, 0
    for line in text.splitlines(keepends=True):
        code = strip_comment(line)
        if depth == 0:
            match = TOP_KEY.match(code)
            if match:
                current = [match.group(1), offset]
        depth += code.count("{") - code.count("}")  # strings never hold braces in culture files
        offset += len(line)
        if depth == 0 and current is not None:
            blocks.append((current[0], current[1], offset, text[current[1]:offset]))
            current = None
    return blocks


def block_heritage(body: str):
    for line in body.splitlines():
        match = HERITAGE_LINE.match(strip_comment(line))
        if match:
            return match.group(1)
    return None


def resolve_cultures(files: dict) -> dict:
    """Group name -> culture keys, from {file name: text}. Raises on a group that resolves to nothing."""
    found = {}
    for text in files.values():
        for key, _start, _end, body in culture_blocks(text):
            found[key] = block_heritage(body)
    result = {}
    for name, group in data.GROUPS.items():
        if "cultures" in group:
            keys = [key for key in group["cultures"] if key in found]
            missing = [key for key in group["cultures"] if key not in found]
            if missing:
                raise GeneratorError(f"group {name}: cultures not found: {', '.join(missing)}")
        else:
            keys = [key for key, heritage in found.items() if heritage == group["heritage"]]
        if not keys:
            raise GeneratorError(f"group {name} resolves to no cultures")
        result[name] = keys
    return result


def override_culture_file(text: str, targets: dict) -> str:
    """Prepend each target culture's gfx key to its building_gfx line, marked; all else unchanged."""
    pieces, last, remaining = [], 0, dict(targets)
    for key, start, end, body in culture_blocks(text):
        if key not in remaining:
            continue
        gfx = remaining.pop(key)
        lines, done = body.splitlines(keepends=True), False
        for index, line in enumerate(lines):
            match = GFX_LINE.match(line.rstrip("\r\n")) if not line.lstrip().startswith("#") else None
            if match:
                ending = line[len(line.rstrip("\r\n")):]
                lines[index] = f"{match.group(1)} {gfx}{match.group(2)} {MARKER}{ending}"
                done = True
                break
        if not done:
            raise GeneratorError(f"culture {key} has no building_gfx line")
        pieces.append(text[last:start])
        pieces.append("".join(lines))
        last = end
    if remaining:
        raise GeneratorError(f"cultures not found in file: {', '.join(sorted(remaining))}")
    pieces.append(text[last:])
    return "".join(pieces)


def mountain_provinces(terrain_text: str, terrains) -> list:
    """Sorted ids of provinces whose terrain is one of terrains."""
    wanted, ids = set(terrains), set()
    for line in terrain_text.splitlines():
        match = TERRAIN_LINE.match(strip_comment(line).lstrip(BOM))
        if match and match.group(2) in wanted:
            ids.add(int(match.group(1)))
    return sorted(ids)


def region_file(provinces: list) -> str:
    lines = HEADER() + [
        "",
        f"{data.REGION} = {{",
        "\tgraphical = yes",
        "\tcolor = { %d %d %d }" % data.REGION_COLOR,
        "\tprovinces = {",
    ]
    ordered = sorted(provinces)
    for index in range(0, len(ordered), 10):
        lines.append("\t\t" + " ".join(str(p) for p in ordered[index:index + 10]))
    lines += ["\t}", "}", ""]
    return BOM + "\n".join(lines)


def read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8")


def culture_texts(roots: Roots) -> dict:
    folder = roots.anbennar / CULTURES_DIR
    return {path.name: read_text(path) for path in sorted(folder.glob("*.txt"))}


def build_cultures(roots: Roots) -> dict:
    roots.check()
    texts = culture_texts(roots)
    resolved = resolve_cultures(texts)
    targets = {}
    for name, keys in resolved.items():
        for key in keys:
            targets[key] = data.GROUPS[name]["gfx"]
    out = {}
    for filename, text in texts.items():
        wanted = {key: targets[key] for key, *_ in culture_blocks(text) if key in targets}
        if wanted:
            out[f"{CULTURES_DIR}/{filename}"] = override_culture_file(text, wanted).encode("utf-8")
    return out


def build_region(roots: Roots) -> dict:
    roots.check()
    terrain = read_text(roots.anbennar / TERRAIN_FILE)
    provinces = mountain_provinces(terrain, data.DWARF_MOUNTAIN_TERRAINS)
    if not provinces:
        raise GeneratorError("no dwarven mountain provinces found")
    return {REGION_FILE: region_file(provinces).encode("utf-8")}


def block_end(lines: list, start: int) -> int:
    """Index after the line that closes the block opened on lines[start]."""
    depth = 0
    for index in range(start, len(lines)):
        code = strip_comment(lines[index])
        depth += code.count("{") - code.count("}")
        if depth <= 0 and (index > start or "{" in code):
            return index + 1
    raise GeneratorError(f"unbalanced braces from line {start + 1}")


def building_block(text: str, key: str) -> tuple:
    """(start, end) offsets of the top-level definition of key: from its line start to after its closing line."""
    lines = text.splitlines(keepends=True)
    offset, depth = 0, 0
    for index, line in enumerate(lines):
        code = strip_comment(line)
        match = TOP_KEY.match(code) if depth == 0 else None
        if match and match.group(1) == key:
            end = block_end(lines, index)
            return offset, offset + sum(len(item) for item in lines[index:end])
        depth += code.count("{") - code.count("}")
        offset += len(line)
    raise GeneratorError(f"building {key} not found")


def source_file(roots: Roots, key: str) -> tuple:
    """(path, text without BOM) of the file defining key: Anbennar's common/buildings first, else the game's."""
    pattern = re.compile(r"^﻿?%s\s*=\s*\{" % re.escape(key), re.MULTILINE)
    folders = (roots.anbennar / "common/buildings", roots.game / "game/common/buildings")
    for folder in folders:
        for path in sorted(folder.glob("*.txt")):
            text = read_text(path).removeprefix(BOM)
            if pattern.search(text):
                return path, text
    raise GeneratorError(f"building {key} is defined by neither Anbennar nor the game")


def source_building(roots: Roots, key: str) -> str:
    _path, text = source_file(roots, key)
    start, end = building_block(text, key)
    return text[start:end]


def source_variables(text: str) -> dict:
    """File-local '@name = value' definitions: name -> value text."""
    found = {}
    for line in text.splitlines():
        match = re.match(r"^@(\w+)\s*=\s*(.+?)\s*$", strip_comment(line).lstrip(BOM))
        if match:
            found[match.group(1)] = match.group(2)
    return found


def asset_block(names, gfx: str, region=None) -> str:
    """A new pdxmesh asset (two-tab indented, LF): one name or variant names, the culture gfx key and,
    for dwarves, the graphical region."""
    lines = ["\t\tasset = {", "\t\t\ttype = pdxmesh"]
    if isinstance(names, str) or len(names) == 1:
        lines.append(f'\t\t\tname = "{names if isinstance(names, str) else names[0]}"')
    else:
        lines += ["\t\t\tnames = {"] + [f'\t\t\t\t"{name}"' for name in names] + ["\t\t\t}"]
    lines.append("\t\t\tgraphical_cultures = { %s }" % gfx)
    if region:
        lines.append("\t\t\tgraphical_regions = { %s }" % region)
    lines.append("\t\t}")
    return "\n".join(lines) + "\n"


def insert_assets(block: str, assets: list, variables=None) -> str:
    """block with the new assets inserted before its first asset (and the comment lines directly above it),
    after a marker line. Each new asset takes the first original asset's illustration and soundeffect lines
    (file-local @variables resolved through variables)."""
    variables = variables or {}
    eol = "\r\n" if "\r\n" in block else "\n"
    lines = block.splitlines(keepends=True)
    first = next((i for i, line in enumerate(lines) if re.match(r"^\s*asset\s*=\s*\{", strip_comment(line))), None)
    if first is None:
        raise GeneratorError("building has no asset block to insert before")
    if not lines[first].startswith("\t\tasset"):
        raise GeneratorError("first asset is not indented by two tabs")
    extras = []
    for line in lines[first + 1:block_end(lines, first)]:
        code = strip_comment(line).rstrip()
        if re.match(r"^\s*(illustration|soundeffect)\s*=", code):
            extras.append(code.strip())
    resolved = []
    for line in extras:
        for name in re.findall(r"@(\w+)", line):
            if name not in variables:
                raise GeneratorError(f"variable @{name} used by the first asset is not defined in the source file")
            line = line.replace(f"@{name}", variables[name])
        resolved.append(f"\t\t\t{line}")
    point = first
    while point > 0 and lines[point - 1].lstrip().startswith("#"):
        point -= 1
    out = [f"\t\t{MARKER}: RiE holding model"]
    for asset in assets:
        for line in asset.splitlines():
            if line.lstrip().startswith("graphical_cultures"):
                out += resolved
            out.append(line)
    inserted = eol.join(out) + eol
    return "".join(lines[:point]) + inserted + "".join(lines[point:])


BUILDINGS_FILE = "common/buildings/zz_aov_holding_models.txt"
LOCALIZATION_FILE = "localization/english/aov_holding_models_l_english.yml"
ASSET_DIR = "gfx/models/buildings/aov_rie_holdings"
TEXTURE_REF = re.compile(r'"([^"]+\.(?:mesh|dds|png|tga))"', re.IGNORECASE)
PDXMESH_NAME = re.compile(r'^(?:pdxmesh|entity)\s*=\s*\{[ \t]*\r?\n\s*name\s*=\s*"([^"]+)"', re.MULTILINE)
ANY_NAME = re.compile(r'\bname\s*=\s*"([^"]+)"')


def build_buildings(roots: Roots) -> dict:
    roots.check()
    blocks = []
    variables = {}
    for key, groups in data.MODELS.items():
        path, text = source_file(roots, key)
        start, end = building_block(text, key)
        assets = []
        for group, meshes in groups.items():
            region = data.REGION if group == "dwarven" else None
            assets.append(asset_block(meshes, data.GROUPS[group]["gfx"], region))
        defined = source_variables(text)
        kind = key.rsplit("_", 1)[0]
        block = insert_assets(text[start:end], assets, defined)
        # The source files reuse variable names with different values, so each kind gets its own prefix.
        block = re.sub(r"@(\w+)", lambda m: f"@{kind}_{m.group(1)}", block)
        variables.update({f"{kind}_{name}": value for name, value in defined.items()})
        blocks.append(block)
    body = "\n".join(blocks)
    used = sorted(set(re.findall(r"@(\w+)", body)))
    missing = [name for name in used if name not in variables]
    if missing:
        raise GeneratorError(f"variables used but not defined in the source files: {', '.join(missing)}")
    top = "".join(f"@{name} = {variables[name]}\n" for name in used)
    content = BOM + "\n".join(HEADER()) + "\n\n" + (top + "\n" if top else "") + body
    return {BUILDINGS_FILE: content.encode("utf-8")}


def build_localization(roots: Roots) -> dict:
    """Names of the new graphical-culture keys (shown in the culture creation screen)."""
    lines = [BOM + "l_english:"]
    for group in data.GROUPS.values():
        lines.append(f' {group["gfx"]}:0 "{group["label"]}"')
    return {LOCALIZATION_FILE: ("\n".join(lines) + "\n").encode("utf-8")}


@lru_cache(maxsize=None)
def _asset_index(models: str) -> dict:
    """pdxmesh/entity name -> .asset files under a gfx/models folder."""
    index = {}
    for path in sorted(Path(models).rglob("*.asset")):
        for name in PDXMESH_NAME.findall(path.read_text("utf-8-sig", errors="replace")):
            index.setdefault(name, []).append(path)
    return index


@lru_cache(maxsize=None)
def _file_names(models: str) -> dict:
    """file name -> paths for every file under a folder."""
    names = {}
    for path in sorted(Path(models).rglob("*")):
        if path.is_file():
            names.setdefault(path.name, []).append(path)
    return names


def find_asset(rie_models: Path, mesh: str) -> Path:
    """The .asset under rie_models that defines the pdxmesh named mesh."""
    hits = _asset_index(str(rie_models)).get(mesh, [])
    if not hits:
        raise GeneratorError(f"pdxmesh {mesh} not found in {rie_models}")
    if len(hits) > 1:
        raise GeneratorError(f"pdxmesh {mesh} is defined by several assets: {', '.join(str(h) for h in hits)}")
    return hits[0]


def asset_files(asset_path: Path, rie_models=None, vanilla=()) -> list:
    """The files to copy for one asset: the asset, its mesh and every texture it names. A file sits beside the
    asset, else elsewhere under rie_models; a texture found only in a vanilla folder is left to the game. Raises
    when a file resolves nowhere."""
    asset_path = Path(asset_path)
    if rie_models is None:
        rie_models = next(p for p in asset_path.parents if p.name == "models")
    refs = []
    for line in asset_path.read_text("utf-8-sig").splitlines():
        for ref in TEXTURE_REF.findall(strip_comment(line)):
            if ref not in refs:
                refs.append(ref)
    files = [asset_path]
    for ref in refs:
        if "/" in ref or "\\" in ref:
            raise GeneratorError(f"{asset_path.name}: {ref} is a path, not a file beside the asset")
        beside = asset_path.parent / ref
        if beside.is_file():
            files.append(beside)
            continue
        found = _file_names(str(rie_models)).get(ref, [])
        if found:
            if len({p.read_bytes() for p in found}) > 1:
                raise GeneratorError(f"{asset_path.name}: {ref} exists with different content in several RiE folders")
            files.append(found[0])
            continue
        if ref.lower().endswith(".mesh") or not any(ref in _file_names(str(root)) for root in vanilla):
            raise GeneratorError(f"{asset_path.name}: {ref} not found beside the asset, in RiE or in the game")
    return files


def check_collisions(roots: Roots, files: dict) -> None:
    """No copied pdxmesh or entity name may already be defined under Anbennar's or the game's gfx/models."""
    copied = {}
    for rel, content in files.items():
        if rel.endswith(".asset"):
            for name in PDXMESH_NAME.findall(content.decode("utf-8-sig")):
                copied.setdefault(name, rel)
    clashes = []
    for root in (roots.anbennar / "gfx/models", roots.game / "game/gfx/models"):
        for path in root.rglob("*.asset"):
            for name in ANY_NAME.findall(path.read_text("utf-8-sig", errors="replace")):
                if name in copied:
                    clashes.append(f"{name} ({copied[name]}) is also defined in {path}")
    if clashes:
        raise GeneratorError("pdxmesh name collisions: " + "; ".join(sorted(set(clashes))))


def check_shaders(files: dict) -> None:
    """Every copied asset's shader needs its _mapobject effect in this mod's shader files."""
    import build_map_graphics as bmg
    fx = SUBMOD / "gfx/FX"
    text = "\n".join(read_text(fx / name) for name in ("court_scene.shader", "pdxmesh.shader", "pdxmesh_decal.shader"))
    # check_asset_effects only looks at the gate folder, so present the assets as if they lived there
    as_gate = {f"{bmg.GATE_ASSET_DIR}/{rel}": content for rel, content in files.items() if rel.endswith(".asset")}
    bmg.check_asset_effects(as_gate, text)


def build_assets(roots: Roots) -> dict:
    roots.check()
    models = roots.rie / "gfx/models"
    vanilla = (roots.game / "game/gfx/models", roots.anbennar / "gfx/models")
    files = {}
    for group in data.GROUPS:
        meshes = []
        for groups in data.MODELS.values():
            meshes += [mesh for mesh in groups.get(group, []) if mesh not in meshes]
        if group == "dwarven":  # the dwarven hold levels (tools/build_holds.py) use one more model
            meshes += [mesh for mesh in data.HOLD_DWARF_MESHES.values() if mesh not in meshes]
        folder = (models / "buildings" / data.MODEL_SETS[group]).resolve()
        for mesh in meshes:
            asset = find_asset(models, mesh)
            if asset.resolve().parent != folder:
                raise GeneratorError(f"{mesh} is defined in {asset}, not in {folder}")
            for source in asset_files(asset, models, vanilla):
                rel = f"{ASSET_DIR}/{group}/{source.name}"
                content = source.read_bytes()
                if files.get(rel, content) != content:
                    raise GeneratorError(f"{rel} would get two different files")
                files[rel] = content
    check_collisions(roots, files)
    check_shaders(files)
    return files


def build_all(roots: Roots) -> dict:
    roots.check()
    files = {}
    files.update(build_cultures(roots))
    files.update(build_region(roots))
    files.update(build_buildings(roots))
    files.update(build_localization(roots))
    files.update(build_assets(roots))
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game))
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
