"""Regenerate common/governments/*.txt for Anbennar Overhaul.

Governments can only be overridden as whole files, so the submod ships full copies of Anbennar's
government files in which every government that can hold castles also accepts the dwarven hold
holding type (added by build_holdings_override.py). Run this after updating the base Anbennar mod:

    python tools/build_governments_override.py [path/to/anbennar/mod/folder]

The base path defaults to ../anbennar-ck3-dev-master next to this submod.
"""

import re
import sys
from pathlib import Path

REL_PATHS = [
    "common/governments/00_government_types.txt",
    "common/governments/01_japan_government_types.txt",
]
HOLDING = "dwarven_hold_holding"
HOLDINGS = (HOLDING, "elven_holding")  # every holding type the overhaul adds, in this order
SOURCE_HOLDING = "castle_holding"
MARKER = "# Anbennar Overhaul"

SUBMOD = Path(__file__).resolve().parent.parent
DEFAULT_ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"

_PRIMARY = re.compile(r"^(\s*)primary_holding\s*=\s*(\w+)\s*$")
_VALID = re.compile(r"^(\s*)valid_holdings\s*=\s*\{([^}]*)\}\s*(?:#.*)?$")


def _process_block(block: list[str]) -> list[str]:
    """One government block (its lines, depth-1 lines are the direct fields)."""
    depth = 0
    primary = valid = None
    for i, line in enumerate(block):
        if depth == 1:
            if _PRIMARY.match(line):
                primary = i
            elif re.match(r"^\s*valid_holdings\s*=", line):
                if not _VALID.match(line):
                    sys.exit(f"error: unsupported valid_holdings form: {line.strip()!r}")
                valid = i
        depth += line.split("#")[0].count("{") - line.split("#")[0].count("}")
    is_castle = primary is not None and _PRIMARY.match(block[primary]).group(2) == SOURCE_HOLDING
    if valid is not None:
        indent, held = _VALID.match(block[valid]).groups()
        if SOURCE_HOLDING in held.split():
            is_castle = True
    if not is_castle:
        return block
    block = list(block)
    if valid is not None:
        missing = [h for h in HOLDINGS if h not in held.split()]
        if missing:
            block[valid] = f"{indent}valid_holdings = {{{held.rstrip()} {' '.join(missing)} }} {MARKER}"
    elif primary is not None:
        indent = _PRIMARY.match(block[primary]).group(1)
        block.insert(primary + 1, f"{indent}valid_holdings = {{ {' '.join(HOLDINGS)} }} {MARKER}")
    else:
        sys.exit("error: castle government without primary_holding or valid_holdings")
    return block


def add_valid_holding(text: str) -> str:
    out, block, depth = [], [], 0
    for line in text.split("\n"):
        code = line.split("#")[0]
        if depth == 0 and not block and "{" not in code:
            out.append(line)
            continue
        block.append(line)
        depth += code.count("{") - code.count("}")
        if depth == 0:
            out.extend(_process_block(block))
            block = []
    out.extend(block)
    return "\n".join(out)


def main() -> None:
    base = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_ANBENNAR
    for rel in REL_PATHS:
        src = base / rel
        if not src.is_file():
            sys.exit(f"error: base government file not found: {src}")
        raw = src.read_bytes()
        bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw.decode("utf-8-sig")
        crlf = "\r\n" in text
        text = add_valid_holding(text.replace("\r\n", "\n"))
        header = (
            f"{MARKER}: generated by tools/build_governments_override.py from Anbennar's {rel}.\n"
            f"{MARKER}: do not edit by hand; edit HOLDINGS in the script and rerun it.\n"
        )
        text = header + text
        if crlf:
            text = text.replace("\n", "\r\n")
        out = SUBMOD / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
