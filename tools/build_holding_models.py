def uses_elf_gfx(keys: list) -> str:
    """A culture trigger that holds when the holder's culture uses one of the gfx keys."""
    return "scope:holder ?= { culture = { OR = { %s } } }" % " ".join(f"has_building_gfx = {key}" for key in keys)


def elf_keys(group_keys: dict) -> list:
    return [key for group in ("high_elf", "wood_elf") for key in group_keys[group]]


def build_triggers(roots: Roots) -> dict:
    """Province scripted trigger: the province shows the dwarf castle/city model (dwarven terrain, minus
    DWARF_PROVINCE_EXCLUDE; the same constants as the asset's province list). `terrain = <key>` is a province
    trigger (vanilla 00_artifact_triggers.txt uses it under title_province)."""
    roots.check()
    lines = [f"{DWARF_TRIGGER} = {{", "\tOR = {"]
    lines += [f"\t\tterrain = {terrain}" for terrain in data.DWARF_TERRAIN_TERRAINS]
    lines.append("\t}")
    lines += [f"\tNOT = {{ this = province:{province} }}" for province in data.DWARF_PROVINCE_EXCLUDE]
    lines.append("}")
    return {TRIGGER_FILE: (BOM + "\n".join(HEADER()) + "\n\n" + "\n".join(lines) + "\n").encode("utf-8")}


def build_walls(roots: Roots) -> dict:
    """The aov_elven_walls background building, and Anbennar's five vanilla-style wall buildings re-emitted so they
    stand down for elven holders."""
    roots.check()
    _targets, group_keys = assign_gfx(culture_texts(roots))
    regions = graphical_regions(roots.anbennar)
    assets = "".join(asset_block(data.WALL_MODELS[group], group_keys[group], regions) for group in ("high_elf", "wood_elf"))
    elven = (f"aov_elven_walls = {{\n\tis_graphical_background = yes\n\n{assets}\n"
             f"{IS_ENABLED_LINE}\n\t\t{uses_elf_gfx(elf_keys(group_keys))}\n"
             f"\t\tNOT = {{ {DWARF_TRIGGER} = yes }}\n"
             "\t\t# the walls a vanilla holding shows (see walls_00 in Anbennar's background buildings)\n"
             "\t\tOR = {\n\t\t\tis_county_capital = yes\n\t\t\tfort_level > 0\n\t\t}\n\t}\n}\n")
    exclusion = f"\t\tNOT = {{ {uses_elf_gfx(elf_keys(group_keys))} }} {MARKER}: elven walls\n"
    # a province that shows the dwarf model gets no wall background at all (the fence and field are walls_00..04)
    dwarven = f"\t\tNOT = {{ {DWARF_TRIGGER} = yes }} {MARKER}: dwarven holds\n"
    # walls_00 ("no walls") is the one background a dwarf-model province keeps: a holding needs an active background
    # building or it shows no model at all (RiE keeps walls_00 on for its underground dwarves too).
    dwarven_00 = f"\t\t\t{DWARF_TRIGGER} = yes {MARKER}: dwarven holds\n"
    blocks = []
    for key in WALL_SOURCE_KEYS:
        text = source_building(roots, key)
        lines = text.splitlines(keepends=True)
        at = [i for i, line in enumerate(lines) if line.rstrip("\r\n") == IS_ENABLED_LINE]
        if len(at) != 1:
            raise GeneratorError(f"{key}: expected one top-level is_enabled block, found {len(at)}")
        if key == "walls_00":
            if lines[at[0] + 1].strip() != "OR = {":
                raise GeneratorError("walls_00: is_enabled does not start with OR = {")
            lines.insert(at[0] + 2, dwarven_00)
        else:
            lines.insert(at[0] + 1, dwarven)
            lines.insert(at[0] + 1, exclusion)
        if key in data.CASTANORIAN_WALLS:
            first = next((i for i, line in enumerate(lines) if ASSET_START.match(strip_comment(line))), None)
            if first is None or not lines[first].startswith("\tasset"):
                raise GeneratorError(f"{key}: first asset not found at one tab")
            asset = asset_block(data.CASTANORIAN_WALLS[key], group_keys["castanorian"], regions)
            indented = "".join(line[1:] + "\n" for line in asset.splitlines())
            lines[first:first] = [f"\t{MARKER}: RiE holding wall\n", indented, "\n"]
        blocks.append("".join(lines))
    header = "\n".join(HEADER()) + "\n\n"
    return {WALLS_FILE: (BOM + header + elven).encode("utf-8"),
            WALL_OVERRIDES_FILE: (BOM + header + "\n".join(blocks)).encode("utf-8")}


def build_localization(roots: Roots) -> dict:
    """Names of the new graphical-culture keys (shown in the culture creation screen)."""
    _targets, group_keys = assign_gfx(culture_texts(roots))
    lines = [BOM + "l_english:"] + localization_lines(group_keys)
    return {LOCALIZATION_FILE: ("\n".join(lines) + "\n").encode("utf-8")}


def localization_lines(group_keys: dict) -> list:
    """One loc line per gfx key: the group's label, or its variant label for a key derived from another list."""
    lines = []
    for name, keys in group_keys.items():
        group = data.GROUPS[name]
        for key in keys:
            variant = f'{key[len(f"aov_{name}_"):-len(GFX_SUFFIX)]}{GFX_SUFFIX}' if key != group["gfx"] else None
            label = group["label"] if variant is None else \
                group.get("variant_labels", {}).get(variant, f'{group["label"]} ({variant[:-len(GFX_SUFFIX)].title()})')
            lines.append(f' {key}:0 "{label}"')
    return lines


@lru_cache(maxsize=None)
def _asset_index(models: str) -> dict:
    """pdxmesh/entity name -> .asset files under a gfx/models folder."""
    index = {}
    for path in sorted(Path(models).rglob("*.asset")):
        for name in PDXMESH_NAME.findall(path.read_text("utf-8-sig", errors="replace")):
            index.setdefault(name, []).append(path)
    return index


@lru_cache(maxsize=None)
def _file_names(models: str) -> dict:
    """file name -> paths for every file under a folder."""
    names = {}
    for path in sorted(Path(models).rglob("*")):
        if path.is_file():
            names.setdefault(path.name, []).append(path)
    return names


def find_asset(rie_models: Path, mesh: str) -> Path:
    """The .asset under rie_models that defines the pdxmesh named mesh."""
    hits = _asset_index(str(rie_models)).get(mesh, [])
    if not hits:
        raise GeneratorError(f"pdxmesh {mesh} not found in {rie_models}")
    if len(hits) > 1:
        raise GeneratorError(f"pdxmesh {mesh} is defined by several assets: {', '.join(str(h) for h in hits)}")
    return hits[0]


def asset_files(asset_path: Path, rie_models=None, vanilla=()) -> list:
    """The files to copy for one asset: the asset, its mesh and every texture it names. A file sits beside the
    asset, else elsewhere under rie_models; a texture found only in a vanilla folder is left to the game. Raises
    when a file resolves nowhere."""
    asset_path = Path(asset_path)
    if rie_models is None:
        rie_models = next(p for p in asset_path.parents if p.name == "models")
    refs = []
    for line in asset_path.read_text("utf-8-sig").splitlines():
        for ref in TEXTURE_REF.findall(strip_comment(line)):
            if ref not in refs:
                refs.append(ref)
    files = [asset_path]
    for ref in refs:
        if "/" in ref or "\\" in ref:
            raise GeneratorError(f"{asset_path.name}: {ref} is a path, not a file beside the asset")
        beside = asset_path.parent / ref
        if beside.is_file():
            files.append(beside)
            continue
        found = _file_names(str(rie_models)).get(ref, [])
        if found:
            if len({p.read_bytes() for p in found}) > 1:
                raise GeneratorError(f"{asset_path.name}: {ref} exists with different content in several RiE folders")
            files.append(found[0])
            continue
        if ref.lower().endswith(".mesh") or not any(ref in _file_names(str(root)) for root in vanilla):
            raise GeneratorError(f"{asset_path.name}: {ref} not found beside the asset, in RiE or in the game")
    return files


def check_collisions(roots: Roots, files: dict) -> None:
    """No copied pdxmesh or entity name may already be defined under Anbennar's or the game's gfx/models."""
    copied = {}
    for rel, content in files.items():
        if rel.endswith(".asset"):
            for name in PDXMESH_NAME.findall(content.decode("utf-8-sig")):
                copied.setdefault(name, rel)
    clashes = []
    for root in (roots.anbennar / "gfx/models", roots.game / "game/gfx/models"):
        for path in root.rglob("*.asset"):
            for name in ANY_NAME.findall(path.read_text("utf-8-sig", errors="replace")):
                if name in copied:
                    clashes.append(f"{name} ({copied[name]}) is also defined in {path}")
    if clashes:
        raise GeneratorError("pdxmesh name collisions: " + "; ".join(sorted(set(clashes))))


def check_shaders(files: dict) -> None:
    """Every copied asset's shader needs its _mapobject effect in this mod's shader files."""
    import build_map_graphics as bmg
    fx = SUBMOD / "gfx/FX"
    text = "\n".join(read_text(fx / name) for name in ("court_scene.shader", "pdxmesh.shader", "pdxmesh_decal.shader"))
    # check_asset_effects only looks at the gate folder, so present the assets as if they lived there
    as_gate = {f"{bmg.GATE_ASSET_DIR}/{rel}": content for rel, content in files.items() if rel.endswith(".asset")}
    bmg.check_asset_effects(as_gate, text)


def build_assets(roots: Roots) -> dict:
    roots.check()
    models = roots.rie / "gfx/models"
    vanilla = (roots.game / "game/gfx/models", roots.anbennar / "gfx/models")
    files = {}
    for group in sorted(data.GROUPS, reverse=True):  # a texture two groups share is kept by the first
        meshes = []
        for groups in data.MODELS.values():
            meshes += [mesh for mesh in groups.get(group, []) if mesh not in meshes]
        if group in data.WALL_MODELS and data.WALL_MODELS[group] not in meshes:
            meshes.append(data.WALL_MODELS[group])
        if group == "castanorian":
            meshes += [mesh for mesh in data.CASTANORIAN_WALLS.values() if mesh not in meshes]
        if group == "dwarven":  # the dwarven hold levels (tools/build_holds.py) use one more model
            meshes += [mesh for mesh in data.HOLD_DWARF_MESHES.values() if mesh not in meshes]
        folder = (models / "buildings" / data.MODEL_SETS[group]).resolve()
        for mesh in meshes:
            asset = find_asset(models, mesh)
            if asset.resolve().parent != folder:
                raise GeneratorError(f"{mesh} is defined in {asset}, not in {folder}")
            for source in asset_files(asset, models, vanilla):
                rel = f"{ASSET_DIR}/{group}/{source.name}"
                content = source.read_bytes()
                # A texture two groups share is copied once: CK3 finds textures by name, and tiger flags duplicates.
                if source.suffix == ".dds" and any(other != rel and other.endswith("/" + source.name)
                                                   and files[other] == content for other in files):
                    continue
                if files.get(rel, content) != content:
                    raise GeneratorError(f"{rel} would get two different files")
                files[rel] = content
    check_collisions(roots, files)
    check_shaders(files)
    return files


def build_all(roots: Roots) -> dict:
    roots.check()
    files = {}
    files.update(build_cultures(roots))
    files.update(build_triggers(roots))
    files.update(build_walls(roots))
    files.update(build_buildings(roots))
    files.update(build_localization(roots))
    files.update(build_assets(roots))
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game))
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
