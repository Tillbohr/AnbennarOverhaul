def render_arms(people: TribePeople) -> str:
    """Dynasty arms, keyed by dynasty: a tribe's EU4 flag where it has one, else a charge on a field from the key."""
    tagged = {f"aov_tr_dynasty_{slug}": slug for slug, tribe in dt.TRIBES.items() if tribe.tag}
    lines = [HEADER.rstrip("\n")]
    for line in people.lines:
        dynasty = line["dynasty"]
        if dynasty in tagged:
            lines += [f"{dynasty} = {{", '\tpattern = "pattern_solid.dds"', f"\tcolor1 = rgb {bs.rgb_text(FLAG_FIELD)}",
                      "\ttextured_emblem = {", f'\t\ttexture = "aov_tribe_{tagged[dynasty]}.dds"', "\t}", "}"]
            continue
        h = bs._hash("arms:" + dynasty)
        r, g, b = colorsys.hsv_to_rgb((h % 360) / 360, 0.55, 0.45)
        field = (round(r * 255), round(g * 255), round(b * 255))
        charges = TRIBE_CHARGES[line["race"]]
        entry = ((charges[(h >> 12) % len(charges)], (0.5, 0.5), (0.65, 0.65)),)
        lines += bs.duchy_arms(dynasty, dynasty, field, {dynasty: entry}, bs.data)
    return "\n".join(lines) + "\n"


def render_loc(people: TribePeople = None) -> str:
    out = ["l_english:"]
    out += [f' dynn_aov_tr_{slug}:0 "{tribe.name}"' for slug, tribe in dt.TRIBES.items() if tribe.tag]
    for key, _trait, _flag, _colour, name, realm, desc in GOVERNMENTS:
        out += [f' {key}:0 "{name}"', f' {key}_adj:0 "{realm}"', f' {key}_adjective:0 "{realm}"',
                f' {key}_realm:0 "{realm}"', f' {key}_desc:0 "{desc}"']
    for race in dt.POOL:
        for tier in dt.POOL[race]:
            for key in pool_keys(race, tier):
                dynasty = f"[GetTitleByKey('{key}').GetHolder.GetDynasty.GetName]"
                out += [f' {key}:0 "{dynasty} {POOL_WORD[(race, tier)]}"', f' {key}_adj:0 "{dynasty}"',
                        f' {key}_article:0 "the "']
    out += [' aov_refused_challenge:0 "Refused the Challenge"',
            ' aov_refused_challenge_desc:0 "This ruler was challenged by their own vassal and would not fight."']
    return "\n".join(out) + "\n"


def build_all(anbennar: Path = ANBENNAR, game: Path = GAME, lays=None) -> dict:
    """{relative path: file bytes} of every generated file. `lays`: build_serpentreach.layouts(), traced when not given."""
    source = (SUBMOD / GOVERNMENT_SOURCE).read_bytes().decode("utf-8-sig")
    people = TribePeople(lays if lays is not None else bs.layouts(anbennar))
    charges = {c: ((c, (0.5, 0.5), (0.65, 0.65)),) for race in TRIBE_CHARGES for c in TRIBE_CHARGES[race]}
    missing = bs.missing_charges(anbennar, game, charges)
    if missing:
        raise GeneratorError(f"TRIBE_CHARGES emblems found nowhere: {', '.join(missing)}")
    flags = [f"aov_tribe_{slug}.dds" for slug, tribe in dt.TRIBES.items() if tribe.tag]
    missing = [f for f in flags if not (SUBMOD / bs.EMBLEM_DIR / f).is_file()]
    if missing:
        raise GeneratorError(f"flag emblems missing from {bs.EMBLEM_DIR}: {', '.join(missing)}")
    texts = {GOVERNMENTS_PATH: render_governments(source), TITLES_PATH: render_pool_titles(),
             TITLE_OVERRIDE_PATH: render_title_override(anbennar), TITLE_HISTORY_PATH: render_title_history(people),
             CHARACTERS_PATH: render_characters(people), DYNASTIES_PATH: render_dynasties(people),
             ARMS_PATH: render_arms(people),
             EFFECTS_PATH: render_pool_effects(), TRIGGERS_PATH: render_pool_triggers(), VALUES_PATH: render_values(),
             OVERRIDES_PATH: render_decision_overrides(anbennar, game), MODIFIERS_PATH: render_modifiers(),
             LOC_PATH: render_loc()}
    return {rel: (BOM + text).encode("utf-8") for rel, text in texts.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=ANBENNAR)
    parser.add_argument("--game", type=Path, default=GAME)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.game)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, data in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
