"""Import Realms in Exile's elven holding and elf buildings into Anbennar Overhaul as the Elven Haven.

The included building lines (tools/data/rie_elves.py LINES) are copied block by block through the rewrite rules of
tools/rie_dwarf_rewrite.py with the elf rules (data module), checked as the dwarf generator checks its blocks (every
building, trigger, parameter, value and modifier must exist in Anbennar or the game or be copied), and every copied
block must check for an elven holder. All names and descriptions are ours (NAMES); RiE's loc is copied only for the
effect descriptions the blocks name. Spec docs/superpowers/specs/2026-10-25-rie-elves-design.md. Rerun after an RiE,
Anbennar or CK3 update, after tools/build_rie_dwarves.py and before tools/build_holdings_override.py:

    python -I tools/build_rie_elves.py [--rie PATH] [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_holding_models as bhm  # noqa: E402
import build_portraits as bp  # noqa: E402
import build_rie_dwarves as rd  # noqa: E402
import rie_dwarf_rewrite as rw  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402
from data import rie_elves as data  # noqa: E402

Roots = bp.Roots
SUBMOD = bp.SUBMOD
BOM = bp.BOM

BUILDINGS_FILE = "common/buildings/aov_elven_buildings.txt"
SETTLEMENT_FILE = "common/buildings/aov_elven_haven.txt"
TRIGGERS_FILE = "common/scripted_triggers/aov_elven_triggers.txt"
VALUES_FILE = "common/script_values/aov_elven_values.txt"
EFFECTS_FILE = "common/scripted_effects/aov_elven_haven_effects.txt"
LOC_FILE = "localization/english/aov_elven_l_english.yml"
ICON_DIR = rd.ICON_DIR
# Folders where these generated files live (FreshnessTests scans them for orphans).
OWNED_FOLDERS = {"common/buildings": ("aov_elven_buildings.txt", "aov_elven_haven.txt"),
                 "common/scripted_triggers": ("aov_elven_triggers.txt",),
                 "common/script_values": ("aov_elven_values.txt",),
                 "common/scripted_effects": ("aov_elven_haven_effects.txt",),
                 "localization/english": ("aov_elven_l_english.yml",),
                 "gfx/interface/illustrations/holding_types": ("refuge_*.dds",),
                 "gfx/interface/icons/holding_types_tab": ("elven_holding.dds",)}
# Localization of keys the generator itself defines.
OWN_LOC = {"aov_rie_elf_holder_tt": "Held by an elf"}
SETTLEMENTS = tuple(f"elven_settlement_{n:02d}" for n in range(1, data.SETTLEMENT_LEVELS + 1))
ELF_CHECK = re.compile(r"\bis_elvish_culture\s*=\s*yes\b|\baov_rie_elf_holder_trigger\s*=\s*yes\b")
TERRAIN_LINE = re.compile(r"(?<![\w.])terrain\s*=\s*(\w+)")


def HEADER(comment="#") -> list:
    return [f"{comment} Anbennar Overhaul: generated by tools/build_rie_elves.py from Realms in Exile and Anbennar.",
            f"{comment} Anbennar Overhaul: do not edit by hand; rerun the generator after an RiE, Anbennar or CK3 update."]


def txt_file(pieces: list) -> bytes:
    return (BOM + "\n".join(HEADER()) + "\n\n" + "\n".join(pieces)).encode("utf-8")


def line_of(key: str) -> str:
    return rd.line_of(key)


def haven_buildings() -> list:
    """The Haven's build list (level-01 keys): the included lines, the overhaul buildings it keeps, the 15 mines."""
    return [f"{line}_01" for line in data.LINES] + list(data.KEEP_ON_CONVERSION) + list(data.MINE_BUILDINGS)


def loc_key(key: str) -> str:
    """The loc key of a NAMES entry: building_<key> for a building level, the key itself for a building type."""
    return key if key.startswith("building_type_") else f"building_{key}"


# ------------------------------------------------------------------------------------------------------- buildings

def included_blocks(roots: Roots) -> list:
    """[(key, text)] of the RiE blocks of the included lines; every line must have exactly its LINES levels."""
    blocks = [(key, text) for key, text in rd.rie_blocks(roots, data.RIE_BUILDINGS_FILE) if line_of(key) in data.LINES]
    found = {key for key, _text in blocks}
    for line, count in data.LINES.items():
        expected = {f"{line}_{n:02d}" for n in range(1, count + 1)}
        mine = {key for key in found if line_of(key) == line}
        if mine != expected:
            raise GeneratorError(f"{line}: RiE has levels {', '.join(sorted(mine)) or 'none'}, the data expects "
                                 f"{', '.join(sorted(expected))}")
    return blocks


def build_gates(text: str) -> str:
    """The can_construct_potential and can_construct blocks of a building block (where RiE checks for an elf)."""
    return "".join(text[start:end] for names, start, end in bp.blocks(text, 2, strict=False)
                   if names[-1] in ("can_construct_potential", "can_construct"))


def render_buildings(build: rd.Build) -> None:
    roots = build.roots
    blocks = included_blocks(roots)
    keys = [key for key, _text in blocks]
    clash = sorted(set(keys) & rd.external_buildings(roots))
    if clash:
        raise GeneratorError(f"RiE elf building keys Anbennar or the game already define: {', '.join(clash)}")
    buildings = set(keys) | rd.external_buildings(roots) | set(SETTLEMENTS)
    parameters = rd.known_parameters(roots)
    removed, pieces = [], []
    for key, body in blocks:
        text, notes = rw.rewrite_block(body, parameters, data)
        removed += notes
        if not ELF_CHECK.search(bp.code(build_gates(text))):
            raise GeneratorError(f"{key}: no elven holder check in can_construct_potential or can_construct after "
                                 "the rewrite")
        rd.check_block(build, key, text, buildings, data)
        text = rd.place_icons(build, key, text)
        for ref in rd.LOC_REF.findall(bp.code(text)):
            build.want_loc(ref)
        pieces.append(re.sub(r"\n{3,}", "\n\n", rd.reindent(text)))
    build.files[BUILDINGS_FILE] = txt_file(pieces)
    excluded = sorted({line_of(key) for key, _text in rd.rie_blocks(roots, data.RIE_BUILDINGS_FILE)} - set(data.LINES))
    build.notes.append(rd.removal_note("removed from RiE's elf buildings", removed))
    build.notes.append(f"RiE elf lines left out: {', '.join(excluded) or 'none'}")


# ------------------------------------------------------------------------------------------------- Haven levels

VARIABLE_DEF = re.compile(r"(?m)^@(\w+)\s*=\s*(.+?)\s*$")
ILLUSTRATION = re.compile(r'(\billustration\s*=\s*)("[^"]*"|@\w+)')
GFX_LIST = re.compile(r"\bgraphical_cultures\s*=\s*\{([^}]*)\}")


def cut_top_blocks(text: str, names) -> str:
    """text without the blocks called one of names directly inside the building block."""
    while True:
        _outer, inner = rw._top_blocks(rw.mask(text))
        found = [(start, close) for name, (start, _op, close) in inner.items() if name in names]
        if not found:
            return text
        start, close = max(found)
        text = rw.cut(text, start, min(close + 1, len(text)))


def castle_models(roots: Roots) -> tuple:
    """({castle key: its `assets = { ... }` block}, {variable: value}) of tools/build_holding_models.py's castles (the
    elf meshes for elf holders), computed, not read from the mod, so the generators run in any order."""
    text = bp.lf(bhm.build_buildings(roots)[bhm.BUILDINGS_FILE].decode("utf-8-sig"))
    variables = dict(VARIABLE_DEF.findall(text))
    assets = {}
    for names, start, end in bp.blocks(text, 1, strict=False):
        body = text[start:end]
        for sub, s, e in bp.blocks(body, 2, strict=False):
            if sub[-1] == "assets":
                assets[names[0]] = body[s:e]
    return assets, variables


def haven_assets(assets_block: str, level: int) -> str:
    """The castle assets with the elf-gfx assets' illustration swapped for RiE's refuge picture of the level."""
    def swap(asset: str) -> str:
        gfx = GFX_LIST.search(asset)
        for key in (gfx.group(1).split() if gfx else ()):
            if key in data.ILLUSTRATIONS:
                picture = data.ILLUSTRATIONS[key][0 if level <= 5 else 1]
                return ILLUSTRATION.sub(lambda m: f'{m.group(1)}"{picture}"', asset)
        return asset
    out, last = [], 0
    for names, start, end in bp.blocks(assets_block, 2, strict=False):
        if names[-1] == "asset":
            out += [assets_block[last:start], swap(assets_block[start:end])]
            last = end
    return "".join(out) + assets_block[last:]


def place_pictures(build: rd.Build) -> None:
    """RiE's refuge pictures and the holding tab icon, at RiE's paths (never over Anbennar's or the game's file)."""
    pictures = {picture for pair in data.ILLUSTRATIONS.values() for picture in pair}
    pictures |= {f"gfx/interface/icons/{target}" for target in data.UI_ICONS.values()}
    sources = {f"gfx/interface/icons/{target}": f"gfx/interface/icons/{source}"
               for source, target in data.UI_ICONS.items()}
    for picture in sorted(pictures):
        source = sources.get(picture, picture)
        if not (build.roots.rie / source).is_file():
            raise GeneratorError(f"picture {source} is not in RiE")
        if bp._exists_outside(build.roots, picture) is not None:
            raise GeneratorError(f"picture {picture} already exists in Anbennar or the game")
        build.files[picture] = (build.roots.rie / source).read_bytes()


def render_settlement(build: rd.Build) -> None:
    """elven_settlement_01..07: RiE's levels with the elf rules, without RiE's assets and is_enabled (a non-elf
    holder keeps the level's effects), with the castle band's models and an elven holder check in can_construct."""
    roots = build.roots
    blocks = dict(rd.rie_blocks(roots, data.RIE_SETTLEMENT_FILE))
    if sorted(blocks) != list(SETTLEMENTS):
        raise GeneratorError(f"{data.RIE_SETTLEMENT_FILE}: expected {', '.join(SETTLEMENTS)}, found "
                             f"{', '.join(sorted(blocks))}")
    clash = sorted(set(SETTLEMENTS) & rd.external_buildings(roots))
    if clash:
        raise GeneratorError(f"Haven level keys Anbennar or the game already define: {', '.join(clash)}")
    castles, variables = castle_models(roots)
    buildings = set(SETTLEMENTS) | rd.external_buildings(roots)
    parameters = rd.known_parameters(roots)
    removed, pieces, used = [], [], set()
    for n, key in enumerate(SETTLEMENTS, 1):
        text, notes = rw.rewrite_block(blocks[key], parameters, data)
        removed += notes
        text = cut_top_blocks(text, ("asset", "is_enabled"))
        text = re.sub(r"(?m)^[ \t]*### CASTLE PLACEHOLDER MODEL ###[ \t]*\n", "", text)
        if not ELF_CHECK.search(bp.code(build_gates(text))):
            raise GeneratorError(f"{key}: no elven holder check in can_construct after the rewrite")
        rd.check_block(build, key, text, buildings, data)
        text = rd.place_icons(build, key, text)
        band = data.HAVEN_ASSET_BAND[n]
        if band not in castles:
            raise GeneratorError(f"{band} has no assets in tools/build_holding_models.py's output")
        assets = haven_assets(castles[band], n)
        used |= set(re.findall(r"@(\w+)", assets))
        at = text.index("\n") + 1
        text = text[:at] + assets.rstrip("\n") + "\n" + text[at:]
        pieces.append(re.sub(r"\n{3,}", "\n\n", rd.reindent(text)))
    missing = sorted(name for name in used if name not in variables)
    if missing:
        raise GeneratorError(f"castle model variables without a definition: {', '.join(missing)}")
    top = "".join(f"@{name} = {variables[name]}\n" for name in sorted(used))
    build.files[SETTLEMENT_FILE] = txt_file([top] + pieces)
    place_pictures(build)
    build.notes.append(rd.removal_note("removed from RiE's Haven levels", removed))


# -------------------------------------------------------------------------------------------------------- triggers

def known_terrains(roots: Roots) -> frozenset:
    return rd._names(bp.effective_texts(roots, "common/terrain_types"))


def copied_trigger(roots: Roots, rie_name: str, ours: str, rie_triggers: dict, notes: list) -> str:
    """RiE's trigger rie_name renamed ours, without the terrain lines Anbennar and the game lack."""
    if rie_name not in rie_triggers:
        raise GeneratorError(f"{data.RIE_TRIGGERS_FILE} has no {rie_name}")
    text = rie_triggers[rie_name].replace("\r\n", "\n")
    terrains = known_terrains(roots)
    for match in reversed(list(TERRAIN_LINE.finditer(rw.mask(text)))):
        if match.group(1) not in terrains:
            notes.append(f"{ours}: terrain {match.group(1)}")
            text = rw.cut(text, match.start(), match.end())
    text = rw.prune_empty(text)
    text = re.sub(rf"^{re.escape(rie_name)}\b", ours, text)
    rd.check_trigger_names(roots, ours, bp.code(text), data)
    return rd.reindent(text).rstrip("\n") + "\n"


def render_triggers(build: rd.Build) -> None:
    rie_triggers = dict(rd.rie_blocks(build.roots, data.RIE_TRIGGERS_FILE))
    dropped = []
    pieces = ["# Province scope: the holder is an elf (RiE's building_requirement_elven, its elven government flag).",
              rd._block("aov_rie_elf_holder_trigger", "custom_tooltip = {", "\ttext = aov_rie_elf_holder_tt",
                        "\tscope:holder ?= { is_elvish_culture = yes }", "}")]
    for rie_name, ours in data.COPIED_TRIGGERS.items():
        pieces += [f"# Province scope: RiE's {rie_name}.", copied_trigger(build.roots, rie_name, ours, rie_triggers,
                                                                         dropped)]
    build.files[TRIGGERS_FILE] = txt_file(pieces)
    build.notes.append(f"terrains Anbennar and the game lack, dropped from the copied triggers: "
                       f"{'; '.join(dropped) or 'none'}")


# ---------------------------------------------------------------------------------------------------- localization

def render_loc(build: rd.Build) -> None:
    """Our names and descriptions (NAMES, HOLDING_LOC, OWN_LOC) and RiE's lines for the other wanted keys."""
    copied = rd.copy_loc(build, data)
    ours = {}
    for key, (name, desc) in data.NAMES.items():
        ours[loc_key(key)] = name
        ours[f"{loc_key(key)}_desc"] = desc
    ours.update(data.HOLDING_LOC)
    ours.update(OWN_LOC)
    twice = sorted(set(ours) & set(copied))
    if twice:
        raise GeneratorError(f"loc keys both copied from RiE and written by us: {', '.join(twice)}")
    lines = [BOM + "l_english:"] + [f" {line}" for line in HEADER()] + [f" {line}" for line in copied.values()]
    lines += [f' {key}: "{text}"' for key, text in ours.items()]
    build.files[LOC_FILE] = ("\n".join(lines) + "\n").encode("utf-8")


# ------------------------------------------------------------------------------------------------------------ main

def build_all(roots: Roots, notes=None) -> dict:
    """{relative path: bytes} of every generated file."""
    roots.check()
    notes = [] if notes is None else notes
    bp.RENAMED.clear()
    build = rd.Build(roots, notes)
    render_buildings(build)
    render_settlement(build)
    render_triggers(build)
    rd.render_values(build, VALUES_FILE, txt_file)
    render_loc(build)
    return build.files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    args = parser.parse_args()
    notes = []
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game), notes)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
