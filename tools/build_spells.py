        out.append(f' aov_spell_{k}_tt: "#T $aov_spell_{k}$#!\\n#weak $AOV_SCHOOL_{s["school"].upper()}$, $aov_spell_{k}_facts$#!'
                   f'\\n\\n{effects_text}\\n\\n$aov_spell_{k}_flavour$"')
