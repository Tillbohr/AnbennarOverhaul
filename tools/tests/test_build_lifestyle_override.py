    "\t\t\tvisible = \"[EqualTo_string( Lifestyle.GetKey, 'wanderer_lifestyle' )]\"\n"
    "\t\t\ttexture = \"gfx/interface/progressbars/progress_brown.dds\"\n"
    "\t\t\talpha = 0.2\n"
    "\t\t}\n"
    "\n"
