# ---------------------------------------------------------------------------------------------------------- parsing

def blocks(text: str, depth=None, strict=True) -> list:
    """[(names, start, end)] of the blocks at a nesting depth (1 = top level; None = every depth). start is the start
    of the opening line, end the end of the closing line (after its newline). Strings and comments are skipped. With
    strict=False (other mods' and the game's files), a stray '}' is skipped and blocks left open (some RiE files miss
    a closing brace, which CK3 tolerates) close at the end."""
    out, stack = [], []
    for match in TOKEN.finditer(text):
        token = match.group(0)
        if token[0] in '"#':
            continue
        if token.endswith("{"):
            stack.append((match.group(1) or "", text.rfind("\n", 0, match.start()) + 1))
            continue
        if not stack:
            if strict:
                raise GeneratorError(f"unbalanced '}}' at offset {match.start()}")
            continue
        name, start = stack.pop()
        if depth is None or len(stack) == depth - 1:
            newline = text.find("\n", match.end())
            out.append((tuple(item[0] for item in stack) + (name,), start, len(text) if newline < 0 else newline + 1))
    if stack and strict:
        raise GeneratorError(f"unclosed block {stack[-1][0] or '{'}")
    while stack:
        name, start = stack.pop()
        if depth is None or len(stack) == depth - 1:
            out.append((tuple(item[0] for item in stack) + (name,), start, len(text)))
    return out


def code(text: str) -> str:
    """text without comments (a '#' inside double quotes does not start one)."""
    return "\n".join(bhm.strip_comment(line) for line in text.split("\n"))


def block_name(body: str):
    match = NAME_FIELD.search(code(body))
    return match.group(1) if match else None


def lf(text: str) -> str:
    """RiE text with LF line endings (RiE files mix CRLF in)."""
    return text.replace("\r\n", "\n")


def read(path: Path) -> str:
    return Path(path).read_bytes().decode("utf-8-sig", errors="replace")


@lru_cache(maxsize=None)
def _texts(folder: str, pattern: str) -> tuple:
    """((relative posix path, text), ...) of the files under folder matching pattern, sorted."""
    root = Path(folder)
    if not root.is_dir():
        return ()
    return tuple((p.relative_to(root).as_posix(), read(p)) for p in sorted(root.rglob(pattern)) if p.is_file())


def effective_texts(roots: Roots, rel: str, pattern="*.txt") -> list:
    """Anbennar's files under rel plus the game's files Anbennar does not shadow (same relative path)."""
    anbennar = list(_texts(str(roots.anbennar / rel), pattern))
    names = {path for path, _text in anbennar}
    return anbennar + [item for item in _texts(str(roots.game / "game" / rel), pattern) if item[0] not in names]


