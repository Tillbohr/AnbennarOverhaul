"""Generate Anbennar Overhaul's map graphics from the installed Realms in Exile (RiE) mod.

Every output is built from RiE (Workshop 2291024373), Anbennar and the game, so rerun this after an RiE update, an
Anbennar update or a CK3 patch. Parts (terrain materials and textures, ...) each return a dict of output path ->
bytes; build_all merges them, and only main writes. Without RiE installed it stops naming the missing path and
writes nothing:

    python -I tools/build_map_graphics.py [--rie PATH] [--anbennar PATH] [--game PATH]

Spec: docs/superpowers/specs/2026-10-13-map-graphics-design.md
"""

import argparse
import fnmatch
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I does not add the script's folder
from build_hud_override import GeneratorError, brace_delta  # noqa: E402
from data import map_graphics as data  # noqa: E402

MARKER = "# Anbennar Overhaul"

SUBMOD = Path(__file__).resolve().parent.parent
TERRAIN = "gfx/map/terrain"
MATERIALS_REL = f"{TERRAIN}/materials.settings"

# Drop-ins that are not members of the terrain texture array (RiE's copy is 256x128, vanilla's 144x72): they are
# only checked to exist in the game's terrain folder, not for size and format.
NOT_ARRAY_MEMBERS = frozenset({"snow_diffuse_for_combined_winter.dds"})

TEXTURE_KEYS = ("diffuse", "normal", "material")
KEY_LINE = re.compile(r'^\s*(\w+)\s*=\s*(?:"([^"]*)"|([^\s#]+))')
TEXTURE_LINE = re.compile(r'^(\s*(?:diffuse|normal|material)\s*=\s*)"[^"]*"')


@dataclass(frozen=True)
class Roots:
    rie: Path
    anbennar: Path
    game: Path  # the install folder holding game/, jomini/ and clausewitz/

    @classmethod
    def default(cls):
        steam = Path("C:/Program Files (x86)/Steam/steamapps")
        return cls(rie=steam / "workshop/content/1158310/2291024373",
                   anbennar=SUBMOD.parent / "anbennar-ck3-dev-master",
                   game=steam / "common/Crusader Kings III")

    @property
    def game_terrain(self) -> Path:
        return self.game / "game" / TERRAIN

    @property
    def rie_terrain(self) -> Path:
        return self.rie / TERRAIN


def HEADER(path_rel: str) -> list:
    """Comment lines (no line endings) that start every generated text file."""
    return [f"{MARKER}: generated by tools/build_map_graphics.py from Realms in Exile ({path_rel}).",
            f"{MARKER}: do not edit by hand; rerun the generator after an RiE, Anbennar or CK3 update."]


def parse_materials(text: str) -> list:
    """The material blocks of a materials.settings text: id, diffuse, normal, material, mask, name, start, end
    (line indices of the block's braces) and lines (key -> line index of that key)."""
    materials, depth, current = [], 0, None
    for index, line in enumerate(text.splitlines()):
        delta = brace_delta(line)
        if depth == 1 and delta > 0 and current is None:
            current = {"start": index, "lines": {}}
        elif current is not None and depth == 2 and delta == 0:
            match = KEY_LINE.match(line)
            if match and match.group(1) not in current["lines"]:
                key = match.group(1)
                current[key] = match.group(2) if match.group(2) is not None else match.group(3)
                current["lines"][key] = index
        depth += delta
        if current is not None and depth == 1:
            current["end"] = index
            materials.append(current)
            current = None
    if depth != 0:
        raise GeneratorError("materials.settings has unbalanced braces")
    return materials


def _by_id(materials: list, where: str) -> dict:
    found = {}
    for material in materials:
        if "id" not in material:
            raise GeneratorError(f"a {where} material at line {material['start'] + 1} has no id")
        found.setdefault(material["id"], material)
    return found


def _check_mapping(anb_by_id: dict, rie_by_id: dict, mapping: dict) -> None:
    for anb_id, rie_id in mapping.items():
        if anb_id not in anb_by_id:
            raise GeneratorError(f"TEXTURE_MAP key {anb_id!r} is not a material id of Anbennar's materials.settings")
        if rie_id not in rie_by_id:
            raise GeneratorError(f"TEXTURE_MAP value {rie_id!r} is not a material id of RiE's materials.settings")


def remap_materials(anb_text: str, rie_text: str, mapping: dict) -> str:
    """Anbennar's materials.settings with the diffuse, normal and material line of every mapped material pointing
    at the mapped RiE material's files. Everything else (names, ids, masks, order) stays byte for byte."""
    anb_by_id = _by_id(parse_materials(anb_text), "Anbennar")
    rie_by_id = _by_id(parse_materials(rie_text), "RiE")
    _check_mapping(anb_by_id, rie_by_id, mapping)
    lines = anb_text.splitlines(keepends=True)
    for anb_id, rie_id in mapping.items():
        for key in TEXTURE_KEYS:
            if key not in rie_by_id[rie_id]:
                raise GeneratorError(f"RiE material {rie_id!r} has no {key} line")
            if key not in anb_by_id[anb_id]["lines"]:
                raise GeneratorError(f"Anbennar material {anb_id!r} has no {key} line")
            index = anb_by_id[anb_id]["lines"][key]
            line = lines[index]
            body = line.rstrip("\r\n")
            ending = line[len(body):]
            match = TEXTURE_LINE.match(body)
            if not match:
                raise GeneratorError(f"cannot read the {key} line of Anbennar material {anb_id!r}: {body!r}")
            lines[index] = f'{match.group(1)}"{rie_by_id[rie_id][key]}" {MARKER}{ending}'
    return "".join(lines)


def terrain_sources(rie_text: str, mapping: dict, rie_terrain: Path, game_terrain: Path) -> dict:
    """Output file name -> source file for the textures the mapped RiE materials name that are RiE's own.
    A texture only the game has is skipped; one that neither has stops the generator."""
    rie_by_id = _by_id(parse_materials(rie_text), "RiE")
    sources = {}
    for anb_id, rie_id in mapping.items():
        if rie_id not in rie_by_id:
            raise GeneratorError(f"TEXTURE_MAP value {rie_id!r} is not a material id of RiE's materials.settings")
        for key in TEXTURE_KEYS:
            name = rie_by_id[rie_id].get(key)
            if name is None:
                raise GeneratorError(f"RiE material {rie_id!r} has no {key} line")
            if (rie_terrain / name).is_file():
                sources[name] = rie_terrain / name
            elif not (game_terrain / name).is_file():
                raise GeneratorError(f"{name} (used by RiE material {rie_id!r}, mapped from {anb_id!r}) exists in "
                                     f"neither RiE nor the game")
    return sources


def dds_info(path: Path) -> tuple:
    """(width, height, fourCC) from a DDS header; the fourCC is empty for uncompressed files."""
    with open(path, "rb") as handle:
        head = handle.read(128)
    if len(head) < 128 or head[:4] != b"DDS ":
        raise GeneratorError(f"{path} is not a DDS file")
    height = int.from_bytes(head[12:16], "little")
    width = int.from_bytes(head[16:20], "little")
    return width, height, head[84:88].rstrip(b"\0").decode("ascii", "replace")


def _check_dds(path: Path, label: str) -> None:
    info = dds_info(path)
    if info != (1024, 1024, "DXT5"):
        raise GeneratorError(f"{label} is {info[0]}x{info[1]} {info[2] or 'uncompressed'}; terrain textures must be "
                             f"1024x1024 DXT5 (a texture array needs one size and format)")


def _read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8")  # keeps BOM and line endings


def build_terrain(roots: Roots) -> dict:
    """Output rel path -> bytes for the material list, the mapped RiE textures and the drop-ins."""
    mapping = data.TEXTURE_MAP
    anb_text = _read_text(roots.anbennar / MATERIALS_REL)
    rie_text = _read_text(roots.rie / MATERIALS_REL)
    out = {}

    remapped = remap_materials(anb_text, rie_text, mapping)
    bom = "\ufeff" if remapped.startswith("\ufeff") else ""
    eol = "\r\n" if "\r\n" in remapped else "\n"
    header = "".join(line + eol for line in HEADER(MATERIALS_REL))
    out[MATERIALS_REL] = (bom + header + remapped[len(bom):]).encode("utf-8")

    for name, source in terrain_sources(rie_text, mapping, roots.rie_terrain, roots.game_terrain).items():
        _check_dds(source, f"mapped texture {name}")
        out[f"{TERRAIN}/{name}"] = source.read_bytes()

    for name in data.DROP_INS:
        if not (roots.game_terrain / name).is_file():
            raise GeneratorError(f"drop-in {name} does not exist in the game's {TERRAIN}")
        source = roots.rie_terrain / name
        if not source.is_file():
            raise GeneratorError(f"drop-in {name} does not exist in RiE's {TERRAIN}")
        if name not in NOT_ARRAY_MEMBERS:
            _check_dds(source, f"drop-in {name}")
        out[f"{TERRAIN}/{name}"] = source.read_bytes()
    return out


FX = "gfx/FX"
INCLUDES_BLOCK = re.compile(r"\bincludes\s*=\s*\{([^}]*)\}", re.IGNORECASE)
QUOTED = re.compile(r'"([^"]+)"')
TEXTURE_REF = re.compile(r'^\s*File\s*=\s*"([^"]+)"', re.IGNORECASE)
IDENTIFIER = re.compile(r"[A-Za-z_]\w*")
NOT_FUNCTIONS = frozenset({"return", "else", "if", "while", "for", "switch", "case", "define", "elif"})
DEFINE = re.compile(r"^\s*#\s*define\s+(\w+)")
STATIC_CONST = re.compile(r"^\s*static\s+const\s+[\w<>, ]+?\s+(\w+)\s*(?:\[[^\]]*\])?\s*=")
BLOCK_NAME = re.compile(r"^\s*(?:TextureSampler|ConstantBuffer)\s+(\w+)")
FUNCTION = re.compile(r"^\s*((?:[A-Za-z_]\w*(?:<[^>]*>)?\s+)+)([A-Za-z_]\w*)\s*\(")


def _strip_comment(line: str) -> str:
    return line.split("#", 1)[0].split("//", 1)[0]


def includes(text: str) -> list:
    """The quoted paths of every Includes block of a shader file; commented lines are ignored."""
    found = []
    for block in INCLUDES_BLOCK.finditer(re.sub(r"(?m)^\s*(#|//).*$", "", text)):
        for line in block.group(1).splitlines():
            found.extend(QUOTED.findall(_strip_comment(line)))
    return found


def texture_refs(text: str) -> list:
    """The `File = "..."` paths of a shader file, in order, without duplicates; commented lines are ignored."""
    found = []
    for line in text.splitlines():
        match = TEXTURE_REF.match(line)
        if match and match.group(1) not in found:
            found.append(match.group(1))
    return found


def defined_symbols(text: str) -> set:
    """Names a shader file defines: functions, #define, static const, TextureSampler and ConstantBuffer names."""
    names = set()
    for line in text.splitlines():
        if line.lstrip().startswith("//"):
            continue
        for pattern in (DEFINE, STATIC_CONST, BLOCK_NAME):
            match = pattern.match(line)
            if match:
                names.add(match.group(1))
        match = FUNCTION.match(line)
        if match and match.group(1).split()[0] not in NOT_FUNCTIONS:
            names.add(match.group(2))
    return names


def missing_mask_symbols(snowfall: str, rie_masks: str, anb_masks: str) -> list:
    """Symbols of RiE's dynamic_masks.fxh that gh_snowfall.fxh uses and Anbennar's copy does not define."""
    used = set(IDENTIFIER.findall(snowfall))
    wanted = defined_symbols(rie_masks) & used
    return sorted(wanted - defined_symbols(anb_masks))


def shader_search(roots: Roots) -> list:
    """Where an include not taken from RiE is looked up, in order."""
    return [roots.anbennar / FX, roots.game / "game" / FX, roots.game / "jomini" / FX, roots.game / "clausewitz" / FX]


def shader_closure(shader_roots, rie_fx: Path, search: list, keep, never) -> dict:
    """Rel path (under gfx/FX) -> RiE source for the roots and every RiE file they include, directly or not.
    An include is looked up in RiE (unless kept from Anbennar), then in `search`; only RiE files are walked
    further. An include that matches `never` and resolves in RiE, or resolves nowhere, stops the generator."""
    found, todo = {}, [(rel, "the shader roots") for rel in shader_roots]
    while todo:
        rel, parent = todo.pop(0)
        if rel in found:
            continue
        in_rie = (rie_fx / rel).is_file()
        if any(fnmatch.fnmatch(rel, pattern) for pattern in never):
            if in_rie:
                raise GeneratorError(f"{parent} includes {rel}, which must never be taken from RiE")
            continue
        if in_rie and rel not in keep:
            found[rel] = rie_fx / rel
            for child in includes(_read_text(rie_fx / rel)):
                todo.append((child, rel))
        elif not any((base / rel).is_file() for base in search):
            raise GeneratorError(f"{parent} includes {rel}, which exists in none of RiE, Anbennar and the game")
    return found


def rie_dynamic_masks(roots: Roots) -> str:
    """RiE's dynamic_masks.fxh, or the game's when RiE ships none (the shaders then resolve it to the game's)."""
    for base in (roots.rie / FX, roots.game / "game" / FX):
        if (base / "dynamic_masks.fxh").is_file():
            return _read_text(base / "dynamic_masks.fxh")
    raise GeneratorError("dynamic_masks.fxh exists in neither RiE nor the game")


def build_shaders(roots: Roots) -> dict:
    """Output rel path -> bytes for the RiE shader files and the textures only RiE has that they reference."""
    rie_fx = roots.rie / FX
    for rel in data.SHADER_ROOTS:
        if not (rie_fx / rel).is_file():
            raise GeneratorError(f"shader root {rel} does not exist in RiE's {FX}")
    closure = shader_closure(data.SHADER_ROOTS, rie_fx, shader_search(roots), data.SHADER_KEEP_ANBENNAR,
                             data.SHADER_NEVER)
    snowfall = roots.rie / FX / "gh_snowfall.fxh"
    if "gh_snowfall.fxh" in closure:
        anb_masks = roots.anbennar / FX / "dynamic_masks.fxh"
        if not anb_masks.is_file():
            raise GeneratorError(f"Anbennar not found: {anb_masks} does not exist")
        missing = missing_mask_symbols(_read_text(snowfall), rie_dynamic_masks(roots), _read_text(anb_masks))
        if missing:
            raise GeneratorError("Anbennar's dynamic_masks.fxh lacks symbols gh_snowfall.fxh uses: "
                                 + ", ".join(missing))
    out = {}
    for rel, source in closure.items():
        out[f"{FX}/{rel}"] = source.read_bytes()
        for ref in texture_refs(_read_text(source)):
            if (roots.anbennar / ref).is_file() or (roots.game / "game" / ref).is_file():
                continue
            if not (roots.rie / ref).is_file():
                raise GeneratorError(f"{rel} references {ref}, which exists in none of RiE, Anbennar and the game")
            out[ref] = (roots.rie / ref).read_bytes()
    return out


def merge_parts(parts: list) -> dict:
    """Merge the parts' output dicts; two parts writing one path with different bytes is an error."""
    merged = {}
    for part in parts:
        for rel, content in part.items():
            if rel in merged and merged[rel] != content:
                raise GeneratorError(f"two parts produce {rel} with different content")
            merged[rel] = content
    return merged


def build_all(roots: Roots) -> dict:
    """Every output (rel path -> bytes). Nothing is written here."""
    if not roots.rie.is_dir():
        raise GeneratorError(f"Realms in Exile is not installed: {roots.rie} does not exist")
    if not (roots.anbennar / MATERIALS_REL).is_file():
        raise GeneratorError(f"Anbennar not found: {roots.anbennar / MATERIALS_REL} does not exist")
    return merge_parts([build_terrain(roots), build_shaders(roots)])


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder (holds game/)")
    args = parser.parse_args()
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game))
    except GeneratorError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
