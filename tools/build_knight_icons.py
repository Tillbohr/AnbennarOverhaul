"""Race knight badges for Anbennar Overhaul: knights of elven, dwarven, gnomish and kobold rulers show that race's EU4
Anbennar tech group icon (without its gear) instead of the vanilla knight badge.

    python -I tools/build_knight_icons.py                 custom loc, trigger, loc and interface overrides
    python -I tools/build_knight_icons.py --import [KEY]  (re)cut race icons from EU4 Anbennar (all races without KEY)

Data, and how to add a race: tools/data/knight_icons.py. Interface files can only be overridden whole, so each target
file is copied (Anbennar's copy if it has one, else the game's) with its knight badge textures replaced; rerun after an
Anbennar update or a CK3 patch. The icons are imported once and committed, like other EU4 art (CLAUDE.md, EU4 imports).
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import eu4_import  # noqa: E402
from build_holding_models import Roots  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402
from data.knight_icons import (GUI_TARGETS, ICON_DIR, ICON_SIZE, ILLUSTRATION_DIR, MILITARY_ART,  # noqa: E402
                               MILITARY_ICONS, RACES, SOURCE_SIZE, STRIP, VANILLA_ICON)

SUBMOD = Path(__file__).resolve().parent.parent
CUSTOM_LOC_FILE = "common/customizable_localization/aov_knight_icon_custom_loc.txt"
TRIGGERS_FILE = "common/scripted_triggers/aov_knight_icon_triggers.txt"
LOC_FILE = "localization/english/aov_knight_icons_l_english.yml"
INNOVATIONS_FILE = "common/culture/innovations/aov_knight_icon_innovations.txt"
ILLUSTRATIONS_FILE = "gfx/interface/illustrations/scripted_illustrations/aov_race_military_illustrations.txt"
MILITARY_GUI = "gui/window_military.gui"
MILITARY_MARK = "# Anbennar Overhaul: race levy and knight pictures (tools/build_knight_icons.py)"
BADGE = 'texture = "gfx/interface/icons/icon_knight_small.dds"'
MARK = "# Anbennar Overhaul: race knight badge (tools/build_knight_icons.py)"
HEADER = ("# Anbennar Overhaul: generated by tools/build_knight_icons.py from tools/data/knight_icons.py; do not edit by "
          "hand.\n# See docs/systems/knight-icons.md.\n")


# --- icons --------------------------------------------------------------------------------------------------------

def cut_icon(strip: bytes, width: int, frame: int, mask: dict) -> bytes:
    """BGRA pixels of icon frame (1-based) of a strip of SOURCE_SIZE squares, with each mask row cleared up to its x."""
    out = bytearray()
    for y in range(SOURCE_SIZE):
        start = (y * width + (frame - 1) * SOURCE_SIZE) * 4
        out += strip[start:start + SOURCE_SIZE * 4]
    for y, last in mask.items():
        for x in range(last + 1):
            out[(y * SOURCE_SIZE + x) * 4 + 3] = 0
    return bytes(out)


def icon_dds(px: bytes, mask: dict = None) -> bytes:
    """A SOURCE_SIZE icon as an ICON_SIZE DDS (one level, no mips): Lanczos 2x up, then bilinear down to size. Output pixels
    whose nearest source pixel is masked are cleared again, so resampling leaves no halo where the gear was."""
    w, h, big = eu4_import.upscale_2x(SOURCE_SIZE, SOURCE_SIZE, px)
    out = bytearray(eu4_import.resize(big, w, h, ICON_SIZE, ICON_SIZE))
    for y in range(ICON_SIZE):
        last = (mask or {}).get(min(int((y + 0.5) * SOURCE_SIZE / ICON_SIZE), SOURCE_SIZE - 1))
        if last is None:
            continue
        for x in range(ICON_SIZE):
            if int((x + 0.5) * SOURCE_SIZE / ICON_SIZE) <= last:
                out[(y * ICON_SIZE + x) * 4:(y * ICON_SIZE + x) * 4 + 4] = b"\0\0\0\0"
    # One uncompressed level, like vanilla's icon_knight_small.dds: with a mip chain the badges showed blank in game.
    return eu4_import.write_bgra(ICON_SIZE, ICON_SIZE, bytes(out))


def import_icons(keys=None, eu4: Path = eu4_import.EU4_ROOTS["anbennar"]) -> dict:
    """Relative path -> DDS bytes of the race icons cut from EU4 Anbennar's tech group strip."""
    width, height, strip = eu4_import.read_dds((eu4 / STRIP).read_bytes())
    if height != SOURCE_SIZE:
        raise GeneratorError(f"{STRIP} is {height} px high, expected {SOURCE_SIZE}")
    known = {row[0] for row in RACES}
    unknown = set(keys or ()) - known
    if unknown:
        raise GeneratorError(f"unknown race key(s): {', '.join(sorted(unknown))}")
    return {f"{ICON_DIR}/{key}.dds": icon_dds(cut_icon(strip, width, frame, mask), mask)
            for key, _name, frame, _group, _cond, mask in RACES if not keys or key in keys}


# --- script, loc and interface ------------------------------------------------------------------------------------

def triggers_file() -> str:
    return HEADER + """
# Character scope: whether the ruler this character's knight badge belongs to (the character if a ruler, else their
# court owner) has a culture matching $TRIGGER$ = $VALUE$.
aov_knight_icon_ruler_trigger = {
	trigger_if = {
		limit = { is_ruler = yes }
		culture = { $TRIGGER$ = $VALUE$ }
	}
	trigger_else_if = {
		limit = { exists = court_owner }
		court_owner.culture = { $TRIGGER$ = $VALUE$ }
	}
	trigger_else = { always = no }
}
"""


def custom_loc_file() -> str:
    lines = [HEADER, "# Character scope: the knight badge texture for a ruler or a knight (first match wins).",
             "aov_knight_icon = {", "\ttype = character"]
    for key, _name, _frame, _group, (trigger, value), _mask in RACES:
        lines.append(f"\ttext = {{ trigger = {{ aov_knight_icon_ruler_trigger = {{ TRIGGER = {trigger} VALUE = {value} }} }} "
                     f"localization_key = aov_knight_badge_{key} }}")
    lines += ["\ttext = { localization_key = aov_knight_badge_default }", "}", ""]
    lines += ["# Character scope: the race whose RiE levy and knight pictures the military window shows, or none.",
              "aov_military_art_race = {", "\ttype = character"]
    for key, (trigger, value) in _military_races():
        lines.append(f"\ttext = {{ trigger = {{ aov_knight_icon_ruler_trigger = {{ TRIGGER = {trigger} VALUE = {value} }} }} "
                     f"localization_key = aov_military_art_{key} }}")
    lines += ["\ttext = { localization_key = aov_military_art_none }", "}", ""]
    return "\n".join(lines)


def _military_races() -> list:
    """(key, culture check) of the races with RiE military pictures, in RACES order."""
    unknown = set(MILITARY_ART) - {row[0] for row in RACES}
    if unknown:
        raise GeneratorError(f"MILITARY_ART names unknown race(s): {', '.join(sorted(unknown))}")
    return [(key, cond) for key, _name, _frame, _group, cond, _mask in RACES if key in MILITARY_ART]


def _illustration_key(icon: str) -> str:
    return f"aov_race_{icon.removeprefix('icon_')}_big_illustration"


def illustrations_file() -> str:
    """Scripted illustrations (character scope) with each race's RiE levy and knight picture, the way Realms in Exile
    picks them. The window shows them only when aov_military_art_race names a race, so they need no fallback."""
    folder = ILLUSTRATION_DIR.removeprefix("gfx/interface/illustrations/")
    lines = [HEADER]
    for icon, index in MILITARY_ICONS.items():
        lines.append(f"{_illustration_key(icon)} = {{")
        for key, (trigger, value) in _military_races():
            lines += ["\ttexture = {", f'\t\treference = "{folder}/{MILITARY_ART[key][index]}"',
                      f"\t\ttrigger = {{ aov_knight_icon_ruler_trigger = {{ TRIGGER = {trigger} VALUE = {value} }} }}",
                      "\t}"]
        lines += ["}", ""]
    return "\n".join(lines)


def _badges() -> list:
    """(key, icon path) of every badge, the vanilla one last."""
    return [(key, f"{ICON_DIR}/{key}.dds") for key, *_ in RACES] + [("default", VANILLA_ICON)]


def innovations_file() -> str:
    """Hidden innovations that only carry a badge icon. An interface texture cannot take a loc string as its path, so
    the custom loc names one of these and the interface reads GetCultureInnovationType(name).GetIcon (the pattern
    Realms in Exile and Princes of Darkness use)."""
    lines = [HEADER, "# Never available to any culture (potential always no); only their icons are used."]
    for key, path in _badges():
        lines += [f"aov_knight_icon_{key} = {{", f'\ticon = "{path}"', "\tpotential = { always = no }",
                  "\tgroup = culture_group_regional", "\tculture_era = culture_era_early_medieval", "}", ""]
    return "\n".join(lines)


def loc_file() -> bytes:
    lines = ["l_english:", " # Anbennar Overhaul: generated by tools/build_knight_icons.py; do not edit by hand.",
             " # Custom loc values: the hidden innovation holding each badge icon."]
    lines += [f' aov_knight_badge_{key}:0 "aov_knight_icon_{key}"' for key, _path in _badges()]
    lines.append(" # Custom loc values: the race of the military window's RiE levy and knight pictures.")
    lines += [f' aov_military_art_{key}:0 "{key}"' for key, _cond in _military_races()]
    lines.append(' aov_military_art_none:0 "none"')
    lines.append(" # The hidden innovations' own names (never shown).")
    for key, _path in _badges():
        lines += [f' aov_knight_icon_{key}:0 "Knight Badge"', f' aov_knight_icon_{key}_desc:0 ""']
    return ("﻿" + "\n".join(lines) + "\n").encode("utf-8")


def gui_override(text: str, scope: str, count: int) -> str:
    """text with each knight badge texture replaced by the race badge of scope; stops unless exactly count."""
    found = text.count(BADGE)
    if found != count:
        raise GeneratorError(f"expected {count} knight badge(s), found {found}: update GUI_TARGETS")
    return text.replace(BADGE, f'texture = "[GetCultureInnovationType({scope}.Custom(\'aov_knight_icon\')).GetIcon]" '
                               f'{MARK}')


def _block_end(text: str, start: int) -> int:
    """Index just past the closing brace of the block whose opening brace is the first at or after start."""
    depth, i = 0, text.index("{", start)
    while True:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1


def military_override(text: str) -> str:
    """text with each MILITARY_ICONS picture shown only for rulers of no RiE race, and a copy after it that shows the
    race's RiE picture instead (a hidden icon takes no room in its layout box)."""
    is_none = "EqualTo_string( Character.Custom('aov_military_art_race'), 'none' )"
    nl = "\r\n" if "\r\n" in text else "\n"
    for icon in MILITARY_ICONS:
        marker = f'name = "{icon}"'
        if text.count(marker) != 1:
            raise GeneratorError(f"expected one {marker}, found {text.count(marker)}: update MILITARY_ICONS")
        start = text.rindex("icon = {", 0, text.index(marker))
        indent = text[text.rfind("\n", 0, start) + 1:start]
        end = _block_end(text, start)
        block = text[start:end]
        vanilla = block.replace(marker, f'{marker}{nl}{indent}\tvisible = "[{is_none}]" {MILITARY_MARK}', 1)
        race = block.replace(marker, f'name = "aov_{icon}_race" {MILITARY_MARK}{nl}'
                                     f'{indent}\tvisible = "[Not( {is_none} )]"', 1)
        texture = f"texture = \"[GetIllustration( '{_illustration_key(icon)}' ).GetTexture( Character.MakeScope )]\""
        race = re.sub(r"texture = [^\r\n]*", lambda _m: texture, race, count=1)
        text = text[:start] + vanilla + nl + indent + race + text[end:]
    return text


def base_gui(roots: Roots, rel: str) -> str:
    """The interface file the override replaces: Anbennar's copy if any, else the game's (BOM stripped)."""
    for root in (roots.anbennar, roots.game / "game"):
        path = root / rel
        if path.is_file():
            return path.read_bytes().decode("utf-8-sig")
    raise GeneratorError(f"{rel} not found in Anbennar or the game")


def build_all(roots: Roots) -> dict:
    for name, path in (("Anbennar", roots.anbennar), ("Crusader Kings III", roots.game)):
        if not path.is_dir():
            raise GeneratorError(f"{name} not found at {path}")
    files = {TRIGGERS_FILE: ("﻿" + triggers_file()).encode("utf-8"),
             CUSTOM_LOC_FILE: ("﻿" + custom_loc_file()).encode("utf-8"),
             INNOVATIONS_FILE: ("﻿" + innovations_file()).encode("utf-8"),
             ILLUSTRATIONS_FILE: ("﻿" + illustrations_file()).encode("utf-8"),
             LOC_FILE: loc_file()}
    for rel, (scope, count) in GUI_TARGETS.items():
        try:
            text = gui_override(base_gui(roots, rel), scope, count)
            if rel == MILITARY_GUI:
                text = military_override(text)
        except GeneratorError as error:
            raise GeneratorError(f"{rel}: {error}") from None
        files[rel] = ("﻿" + text).encode("utf-8")
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder")
    parser.add_argument("--import", dest="import_keys", nargs="*", metavar="KEY",
                        help="cut race icons from EU4 Anbennar (all races when no key is given) instead")
    args = parser.parse_args()
    try:
        if args.import_keys is not None:
            files = import_icons(args.import_keys)
        else:
            files = build_all(Roots(rie=default.rie, anbennar=args.anbennar, game=args.game))
    except (GeneratorError, eu4_import.EU4ImportError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
