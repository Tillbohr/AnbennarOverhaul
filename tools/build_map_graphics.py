def carved_ranges(roots: Roots, ck3: tuple = None) -> list:
    """[(county, floor {(x, y): province}, province terrain, rock provinces)] for every CARVED_RANGES county, from
    Anbennar's map. `ck3` is (province map, water, impassable) when already loaded."""
    key = str(roots.anbennar)
    if key not in _CARVED:
        folder = roots.anbennar / MAP_DATA
        if ck3 is None:
            pm = dm.load_province_map((folder / "provinces.png").read_bytes(), _read_text(folder / "definition.csv"))
            _, impassable = dm.default_map_sets(_read_text(folder / "default.map"))
        else:
            pm, _, impassable = ck3
        terrain = dm.province_terrain(_read_text(roots.anbennar / "common/province_terrain/00_province_terrain.txt"))
        titles = dm.province_titles("\n".join(_read_text(p) for p in
                                              sorted((roots.anbennar / "common/landed_titles").glob("*.txt"))))
        ranges = dm.ranges(dm.dwarven_provinces(terrain), dm.border_pixels(pm))
        out = []
        for county in data.CARVED_RANGES:
            floor = cr.floor_pixels(pm, cr.carved_range(ranges, titles, county))
            kinds = terrain
            if county in sb_data.EXISTING.values():  # Segbandal: its new caverns join Anbennar's range
                seg = segbandal_layout(roots, ck3)
                floor.update(seg.owner)
                kinds = {**terrain, **{pid: c.type for c in seg.counties for pid in c.baronies}}
            out.append((county, floor, kinds, cr.rock_around(pm, floor, impassable, data.CARVE_ROCK_RADIUS)))
        _CARVED[key] = out
    return _CARVED[key]


def build_terrain_fill(roots: Roots, notes: list = None) -> dict:
    """Anbennar's terrain blend maps with every unpainted (zero-weight, drawn black) pixel filled; see
    tools/terrain_fill.py. Whole-file overrides of detail_index.tga and detail_intensity.tga."""
    paths = [roots.anbennar / DETAIL_INDEX_REL, roots.anbennar / DETAIL_INTENSITY_REL]
    for path in paths:
        if not path.is_file():
            raise GeneratorError(f"Anbennar not found: {path} does not exist")
    material = terrain_fill_index(_read_text(roots.anbennar / MATERIALS_REL))
    index, intensity, report = tfill.fill_unpainted(tfill.read_tga(paths[0].read_bytes()),
                                                    tfill.read_tga(paths[1].read_bytes()),
                                                    fill_material=material, large=data.TERRAIN_FILL_LARGE)
    lay = serpentreach_layout(roots)
    ids = material_ids(roots)
    materials = {pid: (ids.index(floor), ids.index(wall)) for pid, (floor, wall) in sl.province_materials(lay).items()}
    pm = _SERPENTREACH[_layout_key(roots)][1]
    index, intensity = sl.paint(index, intensity, lay, materials, pm)
    for county, floor, terrain, rock in carved_ranges(roots):
        names = cr.province_materials(floor, terrain)
        if county in sb_data.EXISTING.values():  # Segbandal's new provinces by their EU4 area's style
            names.update(sl.province_materials(segbandal_layout(roots), sb_data))
        materials = {pid: (ids.index(f), ids.index(w)) for pid, (f, w) in names.items()}
        index, intensity = cr.paint(index, intensity, floor, materials, pm, rock)
    if notes is not None:
        notes.append(f"terrain gaps filled: {report['small_pixels']} px in {report['small_groups']} small gaps "
                     f"(copied from neighbours), {report['large_pixels']} px in {report['large_groups']} large "
                     f"gaps ({data.TERRAIN_FILL_MATERIAL})")
    return {DETAIL_INDEX_REL: tfill.write_tga(index), DETAIL_INTENSITY_REL: tfill.write_tga(intensity)}


def build_heightmap(roots: Roots, notes: list = None) -> dict:
    """The raised heightmap and the dwarven gates: heightmap.png, the packed and indirection files that CK3
    draws, heightmap.heightmap, the gate map objects and the gate model files.

    Blocks whose heights did not change keep Anbennar's tiles; changed blocks are sampled from the new heights
    at the coarsest level within PACK_TOLERANCE."""
    folder = roots.anbennar / MAP_DATA
    settings_file = folder / "heightmap.heightmap"
    if not settings_file.is_file():
        raise GeneratorError(f"Anbennar not found: {settings_file} does not exist")
    settings_bytes = settings_file.read_bytes()
    s = hp.parse_settings(settings_bytes.decode("utf-8"))
    height_img = _read_png_file(folder / "heightmap.png")
    packed_img = _read_png_file(folder / "packed_heightmap.png")
    ind_img = _read_png_file(folder / "indirection_heightmap.png")
    old = hp.Grid.from_png(height_img)
    packed = hp.Grid.from_png(packed_img)
    anb_blocks = hp.unpack(ind_img, packed, s)

    pm, water, impassable, dwarven, sites = _analyse(roots)
    if (pm.width, pm.height) != (old.width, old.height):
        raise GeneratorError(f"provinces.png is {pm.width}x{pm.height} but heightmap.png is "
                             f"{old.width}x{old.height}")
    lay = serpentreach_layout(roots, (pm, water, impassable))
    sr_sites = serpentreach_sites(roots, (pm, water, impassable))
    sites = sites + sr_sites
    lifted, report = dm.raise_heights(old, pm, dwarven, water)
    placed = [(site, size, pos) for site, size, _, pos in
              placed_gates(sites, data.GATE_SCALE, data.GATE_YAW_OFFSET, data.GATE_INSET, data.GATE_OVERRIDES)]
    comp = gt.load_composition(roots.rie)
    new, plans = gt.transplant(lifted, pm, water, placed, comp, transplant_overrides(sr_sites),
                               ranges=set(dwarven) | set(impassable), piece_bounds=piece_bounds(roots.rie, comp))
    carved_floors = carved_ranges(roots, (pm, water, impassable))
    for plan in plans:
        drop_pieces_on_floor(plan, lay.owner, sr_data.PIECE_FLOOR_CLEARANCE)
        for _, floor, _, _ in carved_floors:
            drop_pieces_on_floor(plan, floor, sr_data.PIECE_FLOOR_CLEARANCE)
    new, carved = sl.carve(new, lay, pm, water)
    range_reports = []
    for county, floor, terrain, rock in carved_floors:
        new, r = cr.carve(new, floor, terrain, rock, pm, water, data.CARVE_RAMP)
        range_reports.append((county, r))
    if notes is not None:
        notes.extend(_height_notes(report, plans))
        notes.append(f"serpentreach carved: ground {carved['base']}, {carved['floor_px']} floor px, "
                     f"{carved['wall_px']} wall px")
        for county, r in range_reports:
            notes.append(f"range of {county} carved: ground {r['base']}, {r['floor_px']} floor px, {r['wall_px']} "
                         f"wall px, {r['opening_px']} opening px, rock {', '.join(map(str, r['rock']))}")

    changed = hp.changed_blocks(old, new)
    blocks = {}
    for key, block in anb_blocks.items():
        if key in changed:
            level = hp.choose_level(new, key[0], key[1], data.PACK_TOLERANCE, s.max_compress_level)
            blocks[key] = hp.Block(1 << level, level, hp.sample(new, key[0], key[1], 1 << level))
        else:
            blocks[key] = block
    packed_new, ind_new, offsets, empty_offset = hp.pack(blocks, packed.width, s,
                                                         empty_tile=hp.empty_tile(packed, s))

    out = {
        f"{MAP_DATA}/heightmap.png": pngio.write_png(new.to_png()),
        f"{MAP_DATA}/packed_heightmap.png": pngio.write_png(packed_new.to_png()),
        f"{MAP_DATA}/indirection_heightmap.png": pngio.write_png(ind_new),
        f"{MAP_DATA}/heightmap.heightmap": hp.settings_text(s, offsets, empty_offset).encode("utf-8"),
    }
    gates = gate_objects(sites, data.GATE_SCALE, data.GATE_YAW_OFFSET, data.GATE_INSET, data.GATE_OVERRIDES)
    out[GATES_REL] = _with_header("﻿" + gates, GATES_REL)
    for source, names in GATE_ASSET_FILES:
        for name in names:
            path = roots.rie / source / name
            if not path.is_file():
                raise GeneratorError(f"Realms in Exile not found: {path} does not exist")
            out[f"{GATE_ASSET_DIR}/{name}"] = path.read_bytes()
    overlays = transplant_objects(plans)
    if overlays:
        out[OVERLAYS_REL] = _with_header("\ufeff" + overlays, OVERLAYS_REL)
    out.update(transplant_assets(roots.rie, plans))
    return out


def merge_parts(parts: list) -> dict:
    """Merge the parts' output dicts; two parts writing one path with different bytes is an error."""
    merged = {}
    for part in parts:
        for rel, content in part.items():
            if rel in merged and merged[rel] != content:
                raise GeneratorError(f"two parts produce {rel} with different content")
            merged[rel] = content
    return merged


SURROUND_MASK_REL = "gfx/map/surround_map/surround_mask.dds"


def build_surround_mask(roots: Roots, heightmap_png: bytes, notes: list = None) -> dict:
    """Anbennar's surround mask with its fog pulled back from the Serpentspine (`tools/surround_mask.py`), judged on
    this build's heightmap."""
    source = roots.anbennar / SURROUND_MASK_REL
    if not source.is_file():
        raise GeneratorError(f"Anbennar not found: {source} does not exist")
    raw = source.read_bytes()
    width, height = smask.dxt5_size(raw)
    _, _, pixels = eu4i.read_dds(raw)
    heights = pngio.read_png(heightmap_png)
    step = heights.width // width
    if heights.width != width * step or heights.height != height * step:
        raise GeneratorError(f"surround mask {width}x{height} does not divide heightmap.png "
                             f"{heights.width}x{heights.height}")
    bpp = 2 if heights.bit_depth == 16 else 1

    def ground(x, y):
        return heights.pixels[((y * step) * heights.width + x * step) * bpp]

    def fog(x, y):
        return pixels[(y * width + x) * 4 + 2]

    box = data.SURROUND_BOX
    if not (0 <= box[0] < box[2] <= width and 0 <= box[1] < box[3] <= height):
        raise GeneratorError(f"SURROUND_BOX {box} is outside the {width}x{height} surround mask")
    ridge = smask.range_pixels(ground, fog, box, data.SURROUND_THRESHOLD)
    edited = bytearray(pixels)
    changed = smask.push_back(edited, width, ridge, box, data.SURROUND_REVEAL, data.SURROUND_FADE,
                              data.SURROUND_FEATHER)
    if notes is not None:
        notes.append(f"surround fog pulled back from the Serpentspine: {len(changed)} mask px")
    return {SURROUND_MASK_REL: smask.patch_dxt5(raw, edited, changed)}


def build_all(roots: Roots, notes: list = None) -> dict:
    """Every output (rel path -> bytes). Nothing is written here. Notes about skipped grading boxes and the
    raised ranges and gates are appended to `notes` when given."""
    if not roots.rie.is_dir():
        raise GeneratorError(f"Realms in Exile is not installed: {roots.rie} does not exist")
    if not (roots.anbennar / MATERIALS_REL).is_file():
        raise GeneratorError(f"Anbennar not found: {roots.anbennar / MATERIALS_REL} does not exist")
    grading, grading_notes = build_grading(roots)
    if notes is not None:
        notes.extend(grading_notes)
    heights = build_heightmap(roots, notes)
    files = merge_parts([build_terrain(roots), build_shaders(roots), build_court_scene(roots), build_environment(roots),
                         grading, heights, build_terrain_fill(roots, notes),
                         build_surround_mask(roots, heights[f"{MAP_DATA}/heightmap.png"], notes)])
    check_asset_effects(files, files[COURT_SCENE_REL].decode("utf-8"))
    return files


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rie", type=Path, default=default.rie)
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder (holds game/)")
    args = parser.parse_args()
    notes = []
    try:
        files = build_all(Roots(rie=args.rie, anbennar=args.anbennar, game=args.game), notes)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
