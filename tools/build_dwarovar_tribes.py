def check_tribes(lays) -> None:
    """Stop when an Anbennar or EU4 change leaves a tribe's area or seat with no county, rather than silently dropping
    land from the placement."""
    counties = [c for lay in lays for c in lay.counties]
    areas = {c.area for c in counties}
    ids = {c.eu4_id for c in counties}
    for slug, tribe in dt.TRIBES.items():
        missing = [a for a in tribe.areas if a not in areas] + [str(e) for e in (tribe.seat, *tribe.extra) if e not in ids]
        if missing:
            raise GeneratorError(f"tribe {slug} has no county for {', '.join(missing)}; fix tools/data/dwarovar_tribes.py")


def _name_list(culture: str, field: str) -> list:
    text = (SUBMOD / NAME_LISTS_PATH).read_bytes().decode("utf-8-sig")
    m = re.search(rf"name_list_{culture} = \{{.*?\b{field} = \{{(.*?)\}}", text, re.S)
    if not m:
        raise GeneratorError(f"no {field} for {culture} in {NAME_LISTS_PATH}")
    return m.group(1).replace('"', " ").split()


class TribePeople:
    """Who rules each tribe. `tribes`: {slug: {"pool_title", "dynasty", "chief", "sub_chiefs": {area: id}, "seat_area",
    "areas": {area: [county keys]}}}. `lines`: one dynasty per chief and per sub-chief, so a vassal who wins a duel
    brings a new name and new arms: [{"dynasty", "name_key", "culture", "chars": [(id, name, birth, death or None)]}]."""

    def __init__(self, lays):
        check_tribes(lays)
        counties = [c for lay in lays for c in lay.counties]
        self.tribes, self.lines = {}, []
        self.new_names = {}  # dynn_ key -> text
        free = {race: iter(_name_list(dt.CULTURE[race], "dynasty_names")) for race in dt.POOL}
        males = {race: _name_list(dt.CULTURE[race], "male_names") for race in dt.POOL}
        pools = {race: iter(pool_keys(race, "duchy")) for race in dt.POOL}
        for slug, tribe in dt.TRIBES.items():
            race = tribe.race
            areas = {}
            for c in counties:
                if dt.tribe_of(c.eu4_id, c.area) is tribe:
                    areas.setdefault(c.area, []).append(c)
            seat_area = next(c.area for c in counties if c.eu4_id == tribe.seat)
            for group in areas.values():  # a duke's capital: the seat, else a hold, else the area's first county
                group.sort(key=lambda c: (c.eu4_id != tribe.seat, c.eu4_id not in bs.HOLD_PROVINCES))
            chief = f"aov_tr_{slug}_chief"
            if tribe.tag:
                name_key = f"dynn_aov_tr_{slug}"
                self.new_names[name_key] = tribe.name
            else:
                name_key = self._next_name(free[race], slug)
            self._line(f"aov_tr_dynasty_{slug}", name_key, chief, race, males[race])
            subs = {}
            for area in areas:
                if area != seat_area:
                    sub = f"aov_tr_{slug}_{area}"
                    self._line(f"aov_tr_dynasty_{slug}_{area}", self._next_name(free[race], slug), sub, race, males[race])
                    subs[area] = f"{sub}_1"
            self.tribes[slug] = {"pool_title": next(pools[race]), "dynasty": f"aov_tr_dynasty_{slug}",
                                 "chief": f"{chief}_1", "sub_chiefs": subs, "seat_area": seat_area,
                                 "areas": {a: [c.key for c in group] for a, group in areas.items()}}

    @staticmethod
    def _next_name(names, slug: str) -> str:
        for name in names:
            return name
        raise GeneratorError(f"{NAME_LISTS_PATH} ran out of dynasty names at tribe {slug}")

    def _line(self, dynasty: str, name_key: str, prefix: str, race: str, males: list) -> None:
        elder, child = f"{prefix}_1", f"{prefix}_2"
        chars = [(elder, males[bs._hash("name:" + elder) % len(males)], bs.life_date(elder, dt.CHIEF_BIRTH),
                  bs.life_date(elder + "d", dt.CHIEF_DEATH)),
                 (child, males[bs._hash("name:" + child) % len(males)], bs.life_date(child, dt.CHILD_BIRTH), None)]
        self.lines.append({"dynasty": dynasty, "name_key": name_key, "culture": dt.CULTURE[race], "race": race,
                           "chars": chars})

    def line_of(self, char_id: str) -> dict:
        return next(line for line in self.lines if line["chars"][0][0] == char_id)


def render_title_history(people: TribePeople) -> str:
    out = [HEADER]

    def block(key, line, government, liege=None):
        (first, _, _, death), (child, _, _, _) = line["chars"]
        extra = f" liege = {liege}" if liege else ""
        out.append(f"\n{key} = {{\n\t{dt.TRIBE_START} = {{ holder = {first} government = {government}{extra} }}\n"
                   f"\t{death} = {{ holder = {child} government = {government} }}\n}}\n")

    for slug, info in people.tribes.items():
        government = next(g[0] for g in GOVERNMENTS if g[1] == RACE_TRAIT[dt.TRIBES[slug].race])
        chief = people.line_of(info["chief"])
        block(info["pool_title"], chief, government)
        for ckey in info["areas"][info["seat_area"]]:
            block(ckey, chief, government)
        for area, char_id in info["sub_chiefs"].items():
            for ckey in info["areas"][area]:
                block(ckey, people.line_of(char_id), government, info["pool_title"])
    return "".join(out)


def render_characters(people: TribePeople) -> str:
    out = [HEADER]
    for line in people.lines:
        elder = line["chars"][0][0]
        for cid, name, birth, death in line["chars"]:
            out.append(f'\n{cid} = {{\n\tname = "{name}"\n\tdynasty = {line["dynasty"]}\n'
                       f'\treligion = "{dt.FAITH[line["race"]]}"\n\tculture = "{line["culture"]}"\n'
                       f'\ttrait = race_{line["race"]}\n')
            if cid != elder:
                out.append(f"\tfather = {elder}\n")
            out.append(f"\t{birth} = {{ birth = yes }}\n")
            if death:
                out.append(f"\t{death} = {{ death = yes }}\n")
            out.append("}\n")
    return "".join(out)


def render_dynasties(people: TribePeople) -> str:
    return HEADER + "".join(f'\n{line["dynasty"]} = {{\n\tname = "{line["name_key"]}"\n\tculture = {line["culture"]}\n}}\n'
                            for line in people.lines)


