def header_lines() -> list:
    return [f"{bs.MARKER}: generated by tools/build_segbandal.py from EU4 Anbennar's {data.REGION}.",
            f"{bs.MARKER}: do not edit by hand; edit tools/data/segbandal.py and rerun the generator."]


def _text(lines) -> bytes:
    return (bs.BOM + "\n".join(lines) + "\n").encode("utf-8")


def _strip_comments(text: str) -> str:
    return re.sub(r"#[^\n]*", "", text)


def title_parents(text: str) -> dict:
    """{title key: the title it is nested in, or None at top level} for every e/k/d/c title of landed titles text."""
    parents = {}
    stack = []
    for m in re.finditer(r"\b([ekdc]_[\w-]+)\s*=\s*\{|\{|\}", _strip_comments(text)):
        if m.group(1):
            titles = [s for s in stack if s]
            parents[m.group(1)] = titles[-1] if titles else None
            stack.append(m.group(1))
        elif m.group(0) == "{":
            stack.append(None)
        elif stack:
            stack.pop()
    return parents


def _date_key(date: str) -> tuple:
    return tuple(int(v) for v in date.split("."))


def title_holder(text: str, title: str) -> tuple:
    """(date, holder id) of the earliest `holder` in `title`'s history block; stops when it has none."""
    body = _strip_comments(text)
    m = re.search(rf"(?m)^{re.escape(title)}\s*=\s*\{{", body)
    if m:
        depth, i = 1, m.end()
        while depth and i < len(body):
            depth += {"{": 1, "}": -1}.get(body[i], 0)
            i += 1
        found = re.findall(r"(\d+\.\d+\.\d+)\s*=\s*\{[^{}]*?\bholder\s*=\s*(\w+)", body[m.end():i])
        if found:
            return min(found, key=lambda f: _date_key(f[0]))
    raise GeneratorError(f"no holder in the title history of {title}")


def _read_titles(anbennar: Path) -> str:
    return "\n".join(p.read_text(encoding="utf-8-sig", errors="replace")
                     for p in sorted((anbennar / "common/landed_titles").glob("*.txt")))


def _read_history(anbennar: Path) -> str:
    return "\n".join(p.read_text(encoding="utf-8-sig", errors="replace")
                     for p in sorted((anbennar / "history/titles").glob("*.txt")))


def _scripted_arms(anbennar: Path) -> set:
    """Title keys with arms in Anbennar's common/coat_of_arms/coat_of_arms."""
    keys = set()
    for path in sorted((anbennar / "common/coat_of_arms/coat_of_arms").glob("*.txt")):
        text = _strip_comments(path.read_text(encoding="utf-8-sig", errors="replace"))
        keys |= set(re.findall(r"(?m)^\s*([ekdcb]_\w+)\s*=", text))
    return keys


def kingdom_colour(titles_text: str, kingdom: str) -> tuple:
    m = re.search(rf"\b{kingdom}\s*=\s*\{{\s*color\s*=\s*\{{\s*(\d+)\s+(\d+)\s+(\d+)\s*\}}", titles_text)
    if not m:
        raise GeneratorError(f"no colour for {kingdom} in Anbennar's landed titles")
    return tuple(int(v) for v in m.groups())


class Segbandal:
    """The new titles (from the layout) and how they and Anbennar's counties hang under Anbennar's titles."""

    def __init__(self, lay: sl.Layout, titles_text: str, history_text: str, areas: dict, area_order: dict):
        self.lay = lay
        self.area_order = area_order
        self.areas = areas
        self.history_text = history_text
        self.county = {c.key: c for c in lay.counties}
        self.parents = title_parents(titles_text)
        self.duchy_area = {d: a for a, (d, _, _) in data.AREA_DUCHIES.items()}
        self.kingdom_of = {d: k for d, k, _ in data.AREA_DUCHIES.values()}
        self.reused = {d for d, _, r in data.AREA_DUCHIES.values() if r}
        for duchy in self.reused:
            if duchy not in self.parents:
                raise GeneratorError(f"AREA_DUCHIES reuses {duchy}, which Anbennar no longer has")
        self.duchies = {d: [] for d, _, _ in data.AREA_DUCHIES.values()}  # duchy -> new counties, capital first
        for c in lay.counties:
            self.duchies[data.AREA_DUCHIES[c.area][0]].append(c.key)
        for duchy, counties in self.duchies.items():
            holds = [c for c in counties if self.county[c].type in HOLDS]
            if holds:
                counties.insert(0, counties.pop(counties.index(holds[0])))
        # de jure moves of Anbennar's titles
        self.moves = {}
        for eu4_id, county in sorted(data.EXISTING.items()):
            target = data.AREA_DUCHIES[areas[eu4_id]][0]
            if self.parents.get(county) != target:
                self.moves[county] = target
        for duchy in sorted(self.reused):
            if self.parents[duchy] != self.kingdom_of[duchy]:
                self.moves[duchy] = self.kingdom_of[duchy]
        # Anbennar's holders that new land joins: reused duchies' holders and the elder kingdoms' kings
        self.duchy_holder = {}
        for duchy in sorted(self.reused):
            try:
                self.duchy_holder[duchy] = title_holder(history_text, duchy)
            except GeneratorError:
                pass  # unheld (Hehodovar, Gor Ozumbrog)
        self.king = {k: title_holder(history_text, k) for k in data.ELDER_KINGDOMS}
        self.elder_duchies = [d for d, counties in self.duchies.items()
                              if d not in self.reused and counties and self.kingdom_of[d] in data.ELDER_KINGDOMS
                              and all(bs.is_dwarven(self.county[c]) for c in counties)]
        new_kingdom = data.NEW_KINGDOM[0]
        self.kingdom_colours = {k: data.NEW_KINGDOM[3] if k == new_kingdom else kingdom_colour(titles_text, k)
                                for k in data.KINGDOMS}
        # Anbennar map colours of the reused duchies that get charged arms
        self.anbennar_colours = {data.AREA_DUCHIES[a][0]: kingdom_colour(titles_text, data.AREA_DUCHIES[a][0])
                                 for a in data.REUSED_DUCHY_CHARGES}

    def capital(self, duchy: str) -> str:
        """A new duchy's capital: its first new county, or for a duchy of Anbennar's counties only, the first of them
        in EU4 order."""
        if self.duchies[duchy]:
            return self.duchies[duchy][0]
        for eu4_id in self.area_order[self.duchy_area[duchy]]:
            if eu4_id in data.EXISTING:
                return data.EXISTING[eu4_id]
        raise GeneratorError(f"{duchy} has no county")

    def new_duchies(self) -> list:
        return [d for d in self.duchies if d not in self.reused]

    def barony_keys(self, ckey: str) -> list:
        n = len(self.county[ckey].baronies)
        base = "b_" + ckey[2:]
        return [base] + [f"{base}_{i}" for i in range(2, n + 1)]

    def barony_names(self, ckey: str) -> list:
        name = self.county[ckey].name
        return [name] + [f"{name} {data.BARONY_SUFFIXES[i - 1]}" for i in range(1, len(self.county[ckey].baronies))]

    def culture_of(self, ckey: str) -> str:
        return data.KINGDOM_CULTURES[data.AREA_DUCHIES[self.county[ckey].area][1]]

    def dwarven_counties(self) -> list:
        """(county, its duchy) for Anbennar's and the new counties of the living holds, Anbennar's first."""
        out = []
        for eu4_id, county in sorted(data.EXISTING.items()):
            area = self.areas[eu4_id]
            if tribes.tribe_of(eu4_id, area) is not None:
                raise GeneratorError(f"tools/data/dwarovar_tribes.py gives a tribe Anbennar's {county}")
            out.append((county, data.AREA_DUCHIES[area][0]))
        return out + [(c, d) for d, counties in self.duchies.items() for c in counties if bs.is_dwarven(self.county[c])]

    def colours(self) -> dict:
        """New titles' map colours: the new kingdom its EU4 colour; new duchies shades of their kingdom's (spread by
        their place among the kingdom's duchies); counties close to their duchy's, or to their kingdom's when they
        join an Anbennar duchy."""
        out = {data.NEW_KINGDOM[0]: data.NEW_KINGDOM[3]}
        for kingdom, (_, areas) in data.KINGDOMS.items():
            base = self.kingdom_colours[kingdom]
            duchies = [data.AREA_DUCHIES[a][0] for a in areas]
            offsets = [data.DUCHY_SHADES[i % len(data.DUCHY_SHADES)] for i in range(len(duchies))]
            light = colorsys.rgb_to_hls(*(v / 255 for v in base))[1]
            slide = min(0.0, 0.92 - light - max(offsets)) + max(0.0, 0.12 - light - min(offsets))
            for duchy, offset in zip(duchies, offsets):
                field = base if duchy in self.reused else bs.shade(base, offset + slide)
                if duchy not in self.reused:
                    out[duchy] = field
                for ckey in self.duchies[duchy]:
                    jitter = (bs._hash("colour:" + ckey) % 2001 / 1000 - 1) * data.COUNTY_JITTER
                    out[ckey] = bs.shade(field, jitter)
        return out

    def all_keys(self) -> set:
        keys = {data.NEW_KINGDOM[0]} | set(data.PARKING) | set(self.new_duchies()) | set(self.county)
        for ckey in self.county:
            keys |= set(self.barony_keys(ckey))
        return keys


