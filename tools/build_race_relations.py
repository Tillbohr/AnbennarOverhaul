"""Regenerate the race relations overrides for Anbennar Overhaul (docs/systems/race-relations.md).

Monstrous and non-monstrous characters may not marry or ally. Anbennar's marriage trigger and the game's alliance
interactions are copied from Anbennar with one gate added (scripted triggers and character interactions override by
key):
- anb_marriage_trigger (every marriage, betrothal and concubine check reaches it) calls
  aov_race_marriage_allowed_trigger, where future racial marriage rules go;
- negotiate_alliance_interaction and perk_alliance_interaction (the only interactions that create alliances) check
  aov_race_alliance_allowed_trigger first in is_valid_showing_failures_only.
Rerun after every Anbennar update and CK3 patch:

    python -I tools/build_race_relations.py [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_portraits as bp  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
DEFAULT_ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"
DEFAULT_GAME = Path("C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game")
MARKER = "# Anbennar Overhaul"
BOM = "\ufeff"

MARRIAGE_SOURCE = "common/scripted_triggers/anb_scripted_triggers/anb_racial_triggers.txt"
MARRIAGE_KEY = "anb_marriage_trigger"
MARRIAGE_FILE = "common/scripted_triggers/zz_aov_race_relations_overrides.txt"
MARRIAGE_GATE = ("\taov_race_marriage_allowed_trigger = { ACTOR = $ACTOR$ RECIPIENT = $RECIPIENT$ } "
                 f"{MARKER}: race relations")

ALLIANCE_SOURCE = "common/character_interactions/00_alliance.txt"
ALLIANCE_KEYS = ("negotiate_alliance_interaction", "perk_alliance_interaction")
ALLIANCE_FILE = "common/character_interactions/zz_aov_race_relations_overrides.txt"
ALLIANCE_GATE = ("\t\taov_race_alliance_allowed_trigger = { ACTOR = scope:actor RECIPIENT = scope:recipient } "
                 f"{MARKER}: race relations")
VALID_OPEN = re.compile(r"^\tis_valid_showing_failures_only\s*=\s*\{\s*$")


def header(source: str) -> str:
    return (f"{MARKER}: generated by tools/build_race_relations.py from {source}.\n"
            f"{MARKER}: do not edit by hand; edit the script and rerun it.\n")


def top_blocks(text: str, keys: tuple, source: str) -> dict:
    """key -> its top-level block, for each key (exactly one definition each)."""
    found = {}
    for names, start, end in bp.blocks(text, 1, strict=False):
        if names[0] in keys:
            if names[0] in found:
                raise GeneratorError(f"{names[0]} is defined twice in {source}")
            found[names[0]] = text[start:end].rstrip("\n")
    missing = [k for k in keys if k not in found]
    if missing:
        raise GeneratorError(f"not in {source}: " + ", ".join(missing))
    return found


def gate_marriage(body: str) -> str:
    """The trigger with the race relations gate before its closing brace."""
    lines = body.split("\n")
    if lines[-1] != "}":
        raise GeneratorError(f"{MARRIAGE_KEY} does not end with a lone closing brace")
    return "\n".join(lines[:-1] + ["", MARRIAGE_GATE, "}"])


def gate_alliance(key: str, body: str) -> str:
    """The interaction with the race relations gate first in is_valid_showing_failures_only."""
    lines = body.split("\n")
    opens = [i for i, line in enumerate(lines) if VALID_OPEN.match(line)]
    if len(opens) != 1:
        raise GeneratorError(f"{key} has {len(opens)} is_valid_showing_failures_only blocks")
    lines.insert(opens[0] + 1, ALLIANCE_GATE)
    return "\n".join(lines)


def file_variables(text: str, bodies: list) -> list:
    """The source's file-local @variables that the copied blocks use."""
    out = []
    for line in re.findall(r"^@\w+\s*=.*$", text, re.M):
        name = line.split("=")[0].strip()
        if any(re.search(re.escape(name) + r"\b", body) for body in bodies):
            out.append(line)
    return out


def own_overrides(submod: Path, folder: str, generated: str) -> dict:
    """Top-level keys our other files in folder define, so two overrides never fight."""
    keys = {}
    for path in sorted((submod / folder).glob("*.txt")):
        if path.name == Path(generated).name:
            continue
        text = bp.lf(path.read_bytes().decode("utf-8-sig"))
        for names, _s, _e in bp.blocks(text, 1, strict=False):
            keys[names[0]] = path.name
    return keys


def check_clash(keys: tuple, submod: Path, generated: str) -> None:
    taken = own_overrides(submod, str(Path(generated).parent), generated)
    clash = [f"{k} ({taken[k]})" for k in keys if k in taken]
    if clash:
        raise GeneratorError("already overridden elsewhere in the mod: " + ", ".join(clash))


def build_marriage(text: str, submod: Path = SUBMOD) -> bytes:
    text = bp.lf(text.lstrip(BOM))
    check_clash((MARRIAGE_KEY,), submod, MARRIAGE_FILE)
    body = top_blocks(text, (MARRIAGE_KEY,), MARRIAGE_SOURCE)[MARRIAGE_KEY]
    parts = [BOM + header(MARRIAGE_SOURCE),
             "# Anbennar's marriage trigger with the race relations gate (aov_race_relations_triggers.txt).", ""]
    parts += file_variables(text, [body])
    parts += [gate_marriage(body), ""]
    return "\n".join(parts).encode("utf-8")


def build_alliances(text: str, submod: Path = SUBMOD) -> bytes:
    text = bp.lf(text.lstrip(BOM))
    check_clash(ALLIANCE_KEYS, submod, ALLIANCE_FILE)
    bodies = top_blocks(text, ALLIANCE_KEYS, ALLIANCE_SOURCE)
    parts = [BOM + header(ALLIANCE_SOURCE),
             "# The alliance interactions with the race relations gate (aov_race_relations_triggers.txt).", ""]
    variables = file_variables(text, list(bodies.values()))
    if variables:
        parts += variables + [""]
    for key in ALLIANCE_KEYS:
        parts += [gate_alliance(key, bodies[key]), ""]
    return "\n".join(parts).encode("utf-8")


def find_source(rel: str, anbennar: Path, game: Path) -> Path:
    for root in (anbennar, game):
        if (root / rel).is_file():
            return root / rel
    raise GeneratorError(f"no {rel} in {anbennar} or {game}")


def build_all(anbennar: Path = DEFAULT_ANBENNAR, game: Path = DEFAULT_GAME, submod: Path = SUBMOD) -> dict:
    marriage = find_source(MARRIAGE_SOURCE, anbennar, game).read_bytes().decode("utf-8")
    alliance = find_source(ALLIANCE_SOURCE, anbennar, game).read_bytes().decode("utf-8")
    return {MARRIAGE_FILE: build_marriage(marriage, submod), ALLIANCE_FILE: build_alliances(alliance, submod)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=DEFAULT_ANBENNAR)
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.game)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
