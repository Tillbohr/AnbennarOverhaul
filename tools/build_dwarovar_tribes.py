OVERRIDDEN_EMPIRE = "e_middle_dwarovar"
OVERRIDDEN_KINGDOMS = {"k_seghdihr", "k_hehodovar", "k_verkal_gulan", "k_gor_ozumbrog"}
_TITLE_OPEN = re.compile(r"^\s*([ekdcb]_[\w-]+)\s*=\s*\{\s*(#.*)?$")


def _balance(line: str) -> int:
    code = line.split("#", 1)[0]
    return code.count("{") - code.count("}")


def _title_lines(lines: list, start: int) -> tuple:
    """(the lines inside the block opening at lines[start], the index after its closing line)."""
    depth, i = 1, start + 1
    while depth:
        depth += _balance(lines[i])
        i += 1
    return lines[start + 1:i - 1], i


def _own_and_children(inner: list) -> tuple:
    """(a title's own field lines, [(child key, the child's inner lines)])."""
    own, children, i = [], [], 0
    while i < len(inner):
        m = _TITLE_OPEN.match(inner[i])
        if m:
            body, i = _title_lines(inner, i)
            children.append((m.group(1), body))
            continue
        depth = _balance(inner[i])
        own.append(inner[i])
        i += 1
        while depth:
            depth += _balance(inner[i])
            own.append(inner[i])
            i += 1
    return own, children


def _override_lines(key: str, inner: list, tabs: int) -> list:
    own, children = _own_and_children(inner)
    if any(re.match(r"\s*can_create\b", line) for line in own):
        raise GeneratorError(f"Anbennar's {key} now has its own can_create; merge it with the tribal refusal")
    own = [line.rstrip() for line in own]
    while own and not own[0]:
        own.pop(0)
    while own and not own[-1]:
        own.pop()
    t = "\t" * tabs
    out = [f"{t}{key} = {{"] + own + bs.refuse_tribes(tabs + 1, drift=key[0] in "ke")
    for child, body in children:
        if child[0] in "kd":
            out += _override_lines(child, body, tabs + 1)
    return out + [f"{t}}}"]


def title_override_text(titles_text: str) -> str:
    """e_middle_dwarovar, its kingdoms and duchies, nested as Anbennar has them. Redefining a title clears its own fields
    and moves it to where it is nested (tested in game), so each repeats its fields; counties are left out and stay."""
    text = bp.lf(titles_text.lstrip(BOM))
    lines = text.split("\n")
    start = next((i for i, line in enumerate(lines) if line.startswith(f"{OVERRIDDEN_EMPIRE} = {{")), None)
    if start is None:
        raise GeneratorError(f"Anbennar no longer has {OVERRIDDEN_EMPIRE}")
    inner, _end = _title_lines(lines, start)
    kingdoms = {key for key, _body in _own_and_children(inner)[1]}
    if kingdoms != OVERRIDDEN_KINGDOMS:
        raise GeneratorError(f"{OVERRIDDEN_EMPIRE} now has kingdoms {sorted(kingdoms)}; check the tribes' refusal covers them")
    variables = brr.file_variables(text, ["\n".join(inner)])
    return "\n".join([HEADER + "# Anbennar's Segbandal titles, each with its own fields copied and the tribes refused.", "",
                      *variables, *([""] if variables else []), *_override_lines(OVERRIDDEN_EMPIRE, inner, 0), ""])


def render_title_override(anbennar: Path) -> str:
    return title_override_text(bsb._read_titles(anbennar))


