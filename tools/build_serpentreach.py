def header_lines(cfg=None) -> list:
    """The generated files' header; a data module names its generator (GENERATOR) and itself (DATA_FILE)."""
    cfg = cfg or data
    generator = getattr(cfg, "GENERATOR", "tools/build_serpentreach.py")
    data_file = getattr(cfg, "DATA_FILE", "tools/data/serpentreach.py")
    return [f"{MARKER}: generated by {generator} from EU4 Anbennar's {cfg.REGION}.",
            f"{MARKER}: do not edit by hand; edit {data_file} and rerun the generator."]


def _text(lines) -> bytes:
    return (BOM + "\n".join(lines) + "\n").encode("utf-8")


def _hash(key: str) -> int:
    return int.from_bytes(hashlib.sha256(key.encode("utf-8")).digest()[:8], "big")


def life_date(key: str, years: tuple) -> str:
    """A deterministic date `y.m.d` with the year in `years` (inclusive), from the key."""
    h = _hash(key)
    y = years[0] + h % (years[1] - years[0] + 1)
    return f"{y}.{(h >> 8) % 12 + 1}.{(h >> 16) % 28 + 1}"


def rgb_text(rgb: tuple) -> str:
    return "{ " + " ".join(str(v) for v in rgb) + " }"


def shade(rgb: tuple, delta: float) -> tuple:
    """`rgb` with its HLS lightness moved by `delta`, the other way when that leaves 0.12..0.92."""
    h, light, s = colorsys.rgb_to_hls(*(v / 255 for v in rgb))
    target = light + delta
    if not 0.12 <= target <= 0.92:
        target = light - delta
    target = min(0.92, max(0.12, target))
    return tuple(round(v * 255) for v in colorsys.hls_to_rgb(h, target, s))


def emblem(kkey: str) -> str:
    return f"aov_{kkey[2:]}.dds"


def ascii_name(name: str) -> str:
    s = unicodedata.normalize("NFKD", name)
    return "".join(c for c in s if ord(c) < 128 and c != ";")


def check_new_keys(keys: set, existing_text: str) -> None:
    """Stop when a new title key is already defined in `existing_text` (Anbennar's landed titles)."""
    existing = set(re.findall(r"(?m)^\s*([hekdcb]_[\w-]+)\s*=\s*\{", existing_text))
    clash = sorted(keys & existing)
    if clash:
        raise GeneratorError(f"title keys already defined by Anbennar: {', '.join(clash)}")


def locator_override(text: str, instances: list) -> str:
    """Anbennar's locator file `text` with one instance per (id, x, z) appended to its instances block."""
    body = text.lstrip(BOM)
    if body.count("game_object_locator") != 1 or not body.endswith("\t}\n}\n"):
        raise GeneratorError("locator file is not a single game_object_locator ending in its instances block")
    # Anbennar's other_stack_locators holds stray instances for ids it has no province for; ours replace them
    new_ids = {str(pid) for pid, _, _ in instances}
    body = re.sub(r"\t\t\{\n\t\t\tid=(\d+)\n(?:\t\t\t[^\n]*\n)*?\t\t\}\n",
                  lambda m: "" if m.group(1) in new_ids else m.group(0), body)
    extra = "".join(f"\t\t{{\n\t\t\tid={pid}\n\t\t\tposition={{ {x:.6f} 0.000000 {z:.6f} }}\n"
                    "\t\t\trotation={ -0.000000 -0.000000 -0.000000 1.000000 }\n"
                    "\t\t\tscale={ 1.000000 1.000000 1.000000 }\n\t\t}\n" for pid, x, z in instances)
    head = "".join(line + "\n" for line in header_lines())
    return BOM + head + body[:-len("\t}\n}\n")] + extra + "\t}\n}\n"


