def header_lines() -> list:
    return [f"{MARKER}: generated by tools/build_serpentreach.py from EU4 Anbennar's {data.REGION}.",
            f"{MARKER}: do not edit by hand; edit tools/data/serpentreach.py and rerun the generator."]


def _text(lines) -> bytes:
    return (BOM + "\n".join(lines) + "\n").encode("utf-8")


def _hash(key: str) -> int:
    return int.from_bytes(hashlib.sha256(key.encode("utf-8")).digest()[:8], "big")


def life_date(key: str, years: tuple) -> str:
    """A deterministic date `y.m.d` with the year in `years` (inclusive), from the key."""
    h = _hash(key)
    y = years[0] + h % (years[1] - years[0] + 1)
    return f"{y}.{(h >> 8) % 12 + 1}.{(h >> 16) % 28 + 1}"


def rgb_text(rgb: tuple) -> str:
    return "{ " + " ".join(str(v) for v in rgb) + " }"


def shade(rgb: tuple, delta: float) -> tuple:
    """`rgb` with its HLS lightness moved by `delta`, the other way when that leaves 0.12..0.92."""
    h, light, s = colorsys.rgb_to_hls(*(v / 255 for v in rgb))
    target = light + delta
    if not 0.12 <= target <= 0.92:
        target = light - delta
    target = min(0.92, max(0.12, target))
    return tuple(round(v * 255) for v in colorsys.hls_to_rgb(h, target, s))


def emblem(kkey: str) -> str:
    return f"aov_{kkey[2:]}.dds"


def ascii_name(name: str) -> str:
    s = unicodedata.normalize("NFKD", name)
    return "".join(c for c in s if ord(c) < 128 and c != ";")


def check_new_keys(keys: set, existing_text: str) -> None:
    """Stop when a new title key is already defined in `existing_text` (Anbennar's landed titles)."""
    existing = set(re.findall(r"(?m)^\s*([hekdcb]_[\w-]+)\s*=\s*\{", existing_text))
    clash = sorted(keys & existing)
    if clash:
        raise GeneratorError(f"title keys already defined by Anbennar: {', '.join(clash)}")


def locator_override(text: str, instances: list) -> str:
    """Anbennar's locator file `text` with one instance per (id, x, z) appended to its instances block."""
    body = text.lstrip(BOM)
    if body.count("game_object_locator") != 1 or not body.endswith("\t}\n}\n"):
        raise GeneratorError("locator file is not a single game_object_locator ending in its instances block")
    extra = "".join(f"\t\t{{\n\t\t\tid={pid}\n\t\t\tposition={{ {x:.6f} 0.000000 {z:.6f} }}\n"
                    "\t\t\trotation={ -0.000000 -0.000000 -0.000000 1.000000 }\n"
                    "\t\t\tscale={ 1.000000 1.000000 1.000000 }\n\t\t}\n" for pid, x, z in instances)
    head = "".join(line + "\n" for line in header_lines())
    return BOM + head + body[:-len("\t}\n}\n")] + extra + "\t}\n}\n"


# --- structure ----------------------------------------------------------------------------------------------------

class Realm:
    """Titles of the layout: kingdoms -> duchies -> counties, with keys and display names."""

    def __init__(self, lay: sl.Layout):
        self.lay = lay
        self.county = {c.key: c for c in lay.counties}
        self.duchies = {}  # duchy key -> (name, [county keys]) in order
        self.kingdom_of = {}
        self.duchy_of = {}
        self.kingdoms = {}
        area_duchy = {}
        for kkey, (kname, areas) in data.KINGDOMS.items():
            self.kingdoms[kkey] = (kname, [])
            for area in areas:
                name = lay.area_names[area]
                dkey = "d_" + sl.slug(name)
                if dkey in self.duchies:
                    raise GeneratorError(f"two areas make duchy {dkey}")
                self.duchies[dkey] = (name, [])
                area_duchy[area] = dkey
                self.kingdoms[kkey][1].append(dkey)
                self.kingdom_of[dkey] = kkey
        for c in lay.counties:
            dkey = area_duchy[c.area]
            self.duchies[dkey][1].append(c.key)
            self.duchy_of[c.key] = dkey
        for name, table in (("KINGDOM_CAPITALS", data.KINGDOM_CAPITALS), ("KINGDOM_ARMS", data.KINGDOM_ARMS)):
            if set(table) != set(self.kingdoms):
                raise GeneratorError(f"{name} does not list exactly the kingdoms of KINGDOMS")
        for kkey, ckey in data.KINGDOM_CAPITALS.items():
            if ckey not in self.county or self.kingdom_of[self.duchy_of[ckey]] != kkey:
                raise GeneratorError(f"KINGDOM_CAPITALS: {ckey} is not a county of {kkey}")
        self.hold_duchy = {kkey: self.duchy_of[ckey] for kkey, ckey in data.KINGDOM_CAPITALS.items()}
        if data.EMPIRE_CAPITAL not in self.county:
            raise GeneratorError(f"EMPIRE_CAPITAL {data.EMPIRE_CAPITAL} is not a Serpentreach county")
        self.emperor_duchy = self.duchy_of[data.EMPIRE_CAPITAL]

    def duchy_capital(self, dkey: str) -> str:
        counties = self.duchies[dkey][1]
        holds = [c for c in counties if self.county[c].type in ("dwarven_hold", "dwarven_hold_surface")]
        return (holds or counties)[0]

    def barony_keys(self, ckey: str) -> list:
        n = len(self.county[ckey].baronies)
        base = "b_" + ckey[2:]
        return [base] + [f"{base}_{i}" for i in range(2, n + 1)]

    def barony_names(self, ckey: str) -> list:
        name = self.county[ckey].name
        n = len(self.county[ckey].baronies)
        return [name] + [f"{name} {data.BARONY_SUFFIXES[i - 1]}" for i in range(1, n)]

    def colours(self) -> dict:
        """Title key -> map colour: kingdoms their EU4 colour, duchies shades of it, counties near their duchy's."""
        out = {data.EMPIRE[0]: data.EMPIRE_COLOUR}
        for kkey, (_, duchies) in self.kingdoms.items():
            out[kkey] = data.KINGDOM_ARMS[kkey][1]
            # the duchies' offsets slide together so all stay inside 0.12..0.92 and none folds onto another
            offsets = [data.DUCHY_SHADES[i % len(data.DUCHY_SHADES)] for i in range(len(duchies))]
            light = colorsys.rgb_to_hls(*(v / 255 for v in out[kkey]))[1]
            slide = min(0.0, 0.92 - light - max(offsets)) + max(0.0, 0.12 - light - min(offsets))
            for dkey, offset in zip(duchies, offsets):
                out[dkey] = shade(out[kkey], offset + slide)
                for ckey in self.duchies[dkey][1]:
                    jitter = (_hash("colour:" + ckey) % 2001 / 1000 - 1) * data.COUNTY_JITTER
                    out[ckey] = shade(out[dkey], jitter)
        return out

    def all_keys(self) -> set:
        keys = {data.EMPIRE[0]} | set(self.kingdoms) | set(self.duchies) | set(self.county)
        for ckey in self.county:
            keys |= set(self.barony_keys(ckey))
        return keys


# --- renderers ----------------------------------------------------------------------------------------------------

def render_titles(realm: Realm) -> bytes:
    colour = {key: rgb_text(rgb) for key, rgb in realm.colours().items()}
    lines = header_lines() + ["", f"{data.EMPIRE[0]} = {{", f"\tcolor = {colour[data.EMPIRE[0]]}",
                              f"\tcapital = {data.EMPIRE_CAPITAL}", ""]
    for kkey, (_, duchies) in realm.kingdoms.items():
        lines += [f"\t{kkey} = {{", f"\t\tcolor = {colour[kkey]}",
                  f"\t\tcapital = {data.KINGDOM_CAPITALS[kkey]}", ""]
        for dkey in duchies:
            lines += [f"\t\t{dkey} = {{", f"\t\t\tcolor = {colour[dkey]}",
                      f"\t\t\tcapital = {realm.duchy_capital(dkey)}", ""]
            for ckey in realm.duchies[dkey][1]:
                lines += [f"\t\t\t{ckey} = {{", f"\t\t\t\tcolor = {colour[ckey]}", ""]
                for bkey, pid in zip(realm.barony_keys(ckey), realm.county[ckey].baronies):
                    lines += [f"\t\t\t\t{bkey} = {{", f"\t\t\t\t\tprovince = {pid}",
                              f"\t\t\t\t\tcolor = {colour[ckey]}", "\t\t\t\t}"]
                lines.append("\t\t\t}")
            lines.append("\t\t}")
        lines.append("\t}")
    lines.append("}")
    return _text(lines)


def render_province_history(realm: Realm) -> bytes:
    lines = header_lines()
    for c in realm.lay.counties:
        holdings = data.HOLDINGS[c.type]
        for i, (pid, name) in enumerate(zip(c.baronies, realm.barony_names(c.key))):
            holding = holdings[i] if i < len(holdings) else None
            lines += ["", f"{pid} = {{\t# {name}", f"\tculture = {data.CULTURE}", f"\treligion = {data.RELIGION}",
                      f"\tholding = {holding or 'none'}", "}"]
    return _text(lines)


def male_names(anbennar: Path) -> list:
    path = anbennar / "common/culture/name_lists/anb_dwarven.txt"
    if not path.is_file():
        raise GeneratorError(f"Anbennar not found: {path} does not exist")
    text = path.read_text(encoding="utf-8-sig")
    m = re.search(r"name_list_dwarven\s*=\s*\{.*?male_names\s*=\s*\{([^}]*)\}", text, re.S)
    if not m:
        raise GeneratorError(f"{path}: no male_names in name_list_dwarven")
    names = [n for n in m.group(1).split() if re.fullmatch(r"[A-Za-z]+", n)]
    if not names:
        raise GeneratorError(f"{path}: name_list_dwarven has no plain male names")
    return names


class People:
    """Two generations per duchy (the emperor's duchy has the emperor's line): (dynasty, [(id, name, birth,
    death or None)])."""

    def __init__(self, realm: Realm, names: list):
        self.lines = {}  # duchy key -> {"dynasty", "dyn_name", "chars": [(id, name, birth, death)]}
        used = set()
        for dkey, (dname, _) in realm.duchies.items():
            prefix = "aov_sr_emperor" if dkey == realm.emperor_duchy else f"aov_sr_{dkey[2:]}"
            elder, son = f"{prefix}_1", f"{prefix}_2"
            chars = []
            for cid, birth, death in ((elder, life_date(elder, data.ELDER_BIRTH), life_date(elder + "d", data.ELDER_DEATH)),
                                      (son, life_date(son, data.SON_BIRTH), None)):
                chars.append((cid, names[_hash("name:" + cid) % len(names)], birth, death))
            base = re.sub(r"[\d|]+", "", dname).strip(" -")
            dyn_name = base if base not in used else f"{base}-{chars[0][1]}"
            used.add(dyn_name)
            self.lines[dkey] = {"dynasty": f"aov_dynasty_{dkey[2:]}", "dyn_key": f"dynn_aov_{dkey[2:]}",
                                "dyn_name": dyn_name, "chars": chars}


def render_dynasties(people: People) -> bytes:
    lines = header_lines()
    for line in people.lines.values():
        lines += ["", f"{line['dynasty']} = {{", '\tprefix = "dynnp_az"', f"\tname = \"{line['dyn_key']}\"",
                  f"\tculture = {data.CULTURE}", "}"]
    return _text(lines)


def render_characters(people: People) -> bytes:
    lines = header_lines()
    for line in people.lines.values():
        elder = line["chars"][0][0]
        for cid, name, birth, death in line["chars"]:
            lines += ["", f"{cid} = {{", f'\tname = "{name}"', f"\tdynasty = {line['dynasty']}",
                      f'\treligion = "{data.RELIGION}"', f'\tculture = "{data.CULTURE}"', "\ttrait = race_dwarf"]
            if cid != elder:
                lines.append(f"\tfather = {elder}")
            lines.append(f"\t{birth} = {{ birth = yes }}")
            if death:
                lines.append(f"\t{death} = {{ death = yes }}")
            lines.append("}")
    return _text(lines)


def render_title_history(realm: Realm, people: People) -> bytes:
    lines = header_lines()

    def block(key, liege, line):
        (elder, _, _, death), (son, _, _, _) = line["chars"]
        extra = f" liege = {liege}" if liege else ""
        return ["", f"{key} = {{", f"\t{data.START} = {{ holder = {elder}{extra} }}",
                f"\t{death} = {{ holder = {son} }}", "}"]

    # Each kingdom is held by the lord of its hold's duchy, a vassal of the emperor (who holds Arg-Ôrdstun's); the
    # other dukes of a kingdom are the king's vassals. A title's liege is the highest title of its holder's liege.
    empire = data.EMPIRE[0]
    lines += block(empire, None, people.lines[realm.emperor_duchy])
    for kkey, (_, duchies) in realm.kingdoms.items():
        hold = realm.hold_duchy[kkey]
        royal = hold == realm.emperor_duchy
        lines += block(kkey, None if royal else empire, people.lines[hold])
        for dkey in duchies:
            line = people.lines[dkey]
            mine = dkey == realm.emperor_duchy
            liege = None if mine else empire if royal or dkey == hold else kkey
            lines += block(dkey, liege, line)
            for ckey in realm.duchies[dkey][1]:
                lines += block(ckey, empire if mine else dkey, line)
    return _text(lines)


def render_arms(realm: Realm) -> bytes:
    """Each kingdom and its hold county carry the EU4 hold's flag as a textured emblem."""
    lines = header_lines()
    for kkey, (kname, _) in realm.kingdoms.items():
        tag, _, background = data.KINGDOM_ARMS[kkey]
        lines += ["", f"# {kname} (EU4 {tag})"]
        for key in (kkey, data.KINGDOM_CAPITALS[kkey]):
            lines += [f"{key} = {{", '\tpattern = "pattern_solid.dds"', f"\tcolor1 = rgb {rgb_text(background)}",
                      "\ttextured_emblem = {", f'\t\ttexture = "{emblem(kkey)}"', "\t}", "}"]
    return _text(lines)


def render_terrain(lay: sl.Layout) -> bytes:
    lines = header_lines() + [""]
    for c in lay.counties:
        lines += [f"{pid}={c.type}" for pid in c.baronies]
    return _text(lines)


def render_regions() -> bytes:
    # regions take kingdoms, duchies, counties or provinces, not empires
    return _text(header_lines() + ["", "world_serpentreach = {", f"\tkingdoms = {{ {' '.join(data.KINGDOMS)} }}", "}"])


def render_loc(realm: Realm, people: People) -> bytes:
    def pair(key, name, adj=True):
        out = [f' {key}:0 "{name}"']
        return out + ([f' {key}_adj:0 "{name}"'] if adj else [])

    lines = ["l_english:"]
    lines += pair(data.EMPIRE[0], data.EMPIRE[1])
    for kkey, (kname, _) in realm.kingdoms.items():
        lines += pair(kkey, kname)
    for dkey, (dname, _) in realm.duchies.items():
        lines += pair(dkey, dname)
    for ckey, c in realm.county.items():
        lines += pair(ckey, c.name)
        for bkey, bname in zip(realm.barony_keys(ckey), realm.barony_names(ckey)):
            lines += pair(bkey, bname, adj=False)
    for line in people.lines.values():
        lines.append(f' {line["dyn_key"]}:0 "{line["dyn_name"]}"')
    return _text(lines)


def render_definition(original: bytes, lay: sl.Layout) -> bytes:
    nl = b"\r\n" if b"\r\n" in original else b"\n"
    out = original if original.endswith(nl) else original + nl
    rows = []
    for c in lay.counties:
        for i, pid in enumerate(c.baronies):
            p = lay.provinces[pid]
            name = ascii_name(c.name if i == 0 else f"{c.name} {data.BARONY_SUFFIXES[i - 1]}")
            rows.append(f"{pid};{p.colour[0]};{p.colour[1]};{p.colour[2]};{name};x;".encode("ascii"))
    return out + nl.join(rows) + nl


def render_provinces(png: bytes, lay: sl.Layout) -> bytes:
    img = pngio.read_png(png)
    if img.bit_depth != 8 or img.color_type not in (2, 6):
        raise GeneratorError("provinces.png must be 8-bit RGB or RGBA")
    bpp = 3 if img.color_type == 2 else 4
    px = bytearray(img.pixels)
    for (x, y), pid in lay.owner.items():
        k = ((img.height - 1 - y) * img.width + x) * bpp
        px[k:k + 3] = bytes(lay.provinces[pid].colour)
    return pngio.write_png(pngio.Image(img.width, img.height, 8, img.color_type, bytes(px)))


def render_locators(anbennar: Path, lay: sl.Layout) -> dict:
    instances = [(pid, p.interior[0] + 0.5, p.interior[1] + 0.5) for pid, p in sorted(lay.provinces.items())]
    out = {}
    for name in LOCATOR_FILES:
        path = anbennar / LOCATOR_DIR / f"{name}.txt"
        if not path.is_file():
            raise GeneratorError(f"Anbennar not found: {path} does not exist")
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        out[f"{LOCATOR_DIR}/{name}.txt"] = locator_override(text, instances).encode("utf-8")
    return out


def build_all(anbennar: Path = ANBENNAR, eu4: Path = EU4, ck3=None) -> dict:
    """Every output (rel path -> bytes); nothing is written here."""
    lay = sl.layout(anbennar, eu4, ck3)
    return build_from_layout(anbennar, lay)


def build_from_layout(anbennar: Path, lay: sl.Layout) -> dict:
    realm = Realm(lay)
    titles_text = "\n".join(p.read_text(encoding="utf-8-sig", errors="replace")
                            for p in sorted((anbennar / "common/landed_titles").glob("*.txt")))
    check_new_keys(realm.all_keys(), titles_text)
    missing = [emblem(k) for k in realm.kingdoms if not (SUBMOD / EMBLEM_DIR / emblem(k)).is_file()]
    if missing:
        raise GeneratorError(f"flag emblems missing from {EMBLEM_DIR} (see KINGDOM_ARMS): {', '.join(missing)}")
    people = People(realm, male_names(anbennar))
    folder = anbennar / "map_data"
    files = {
        PROVINCES_PNG: render_provinces((folder / "provinces.png").read_bytes(), lay),
        DEFINITION: render_definition((folder / "definition.csv").read_bytes(), lay),
        TITLES: render_titles(realm),
        PROVINCE_HISTORY: render_province_history(realm),
        TITLE_HISTORY: render_title_history(realm, people),
        CHARACTERS: render_characters(people),
        DYNASTIES: render_dynasties(people),
        TERRAIN: render_terrain(lay),
        REGIONS: render_regions(),
        LOC: render_loc(realm, people),
        ARMS: render_arms(realm),
    }
    files.update(render_locators(anbennar, lay))
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=ANBENNAR)
    parser.add_argument("--eu4", type=Path, default=EU4)
    args = parser.parse_args()
    try:
        lay = sl.layout(args.anbennar, args.eu4)
        files = build_from_layout(args.anbennar, lay)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in lay.notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files: {len(lay.counties)} counties, {len(lay.provinces)} provinces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
