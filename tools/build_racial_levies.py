"""Generate the per-holding racial levy correction for Anbennar Overhaul.

CK3 adds every levy_size modifier into one total, so a flat racial cut (elves -75%) would let racial levies grow
faster than human ones as buildings add bonuses. Each racial holding instead gets a province modifier that takes back
the race's share of that holding's own levy bonuses, keeping its levies at a fixed share of a human holding's
(docs/systems/racial-armies.md). This script reads every levy_size in the game, Anbennar and this submod and writes:

    common/script_values/aov_racial_levy_values.txt      the holding's summed levy bonus and its tier
    common/modifiers/aov_racial_levy_modifiers.txt       one correction modifier per race and tier
    common/scripted_effects/aov_racial_levy_effects.txt  aov_refresh_holding_levy_correction (province scope)
    localization/english/aov_racial_levy_l_english.yml   modifier names

    python -I tools/build_racial_levies.py [--anbennar PATH] [--game PATH]

Rerun after an Anbennar update or a CK3 patch: both can add levy sources. It stops on a levy_size in a folder that
tools/data/racial_levies.py neither classifies nor ignores.
"""

import argparse
import os
import re
import sys
from pathlib import Path
from typing import NamedTuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_holding_models import Roots  # noqa: E402
from build_hud_override import GeneratorError  # noqa: E402
from pdx_script import parse_blocks  # noqa: E402
from data.racial_levies import (CLASSIFIED, CONTRIBUTION_CLASSIFIED, CONTRIBUTION_IGNORED, IGNORED,  # noqa: E402
                                OWN_KEYS, RACE_NAMES, RACES, S_MAX, S_MIN, SHARE_TEXT, STEP)

SUBMOD = Path(__file__).resolve().parent.parent
VALUES_FILE = "common/script_values/aov_racial_levy_values.txt"
MODIFIERS_FILE = "common/modifiers/aov_racial_levy_modifiers.txt"
EFFECTS_FILE = "common/scripted_effects/aov_racial_levy_effects.txt"
LOC_FILE = "localization/english/aov_racial_levy_l_english.yml"
HEADER = ("# Anbennar Overhaul: generated by tools/build_racial_levies.py; do not edit by hand.\n"
          "# See docs/systems/racial-armies.md.\n")
CONDITION_KEYS = ("parameter", "terrain", "is_coastal", "is_riverside", "flag", "invert_check")
LEVY = "levy_size"  # a holding's own levies (province-scope correction)
CONTRIBUTION = "vassal_levy_contribution_mult"  # what vassals send a ruler (character-scope correction)
TABLES = {LEVY: (CLASSIFIED, IGNORED), CONTRIBUTION: (CONTRIBUTION_CLASSIFIED, CONTRIBUTION_IGNORED)}
_TOKEN = re.compile(r'"[^"]*"|[{}=]|[^\s{}=#"]+|#[^\n]*')


class Source(NamedTuple):
    database: str  # folder under common/, e.g. "buildings", "culture/traditions"
    key: str  # the object the condition names (building, tradition, law ...)
    block: str  # modifier block holding the levy_size ("" for a trait's own modifiers)
    value: float
    condition: dict  # parameter / terrain / is_coastal / is_riverside of that block


# --- reading ------------------------------------------------------------------------------------------------------

def parse(text: str) -> list:
    """Paradox script -> nested [(key, value)] lists; a block's value is its own list."""
    tokens = [t for t in _TOKEN.findall(text) if not t.startswith("#")]
    pos = 0

    def block():
        nonlocal pos
        items = []
        while pos < len(tokens):
            tok = tokens[pos]
            if tok == "}":
                pos += 1
                return items
            if pos + 1 < len(tokens) and tokens[pos + 1] == "=":
                pos += 2
                if pos < len(tokens) and tokens[pos] == "{":
                    pos += 1
                    items.append((tok, block()))
                elif pos < len(tokens):
                    items.append((tok, tokens[pos]))
                    pos += 1
            else:
                if tok == "{":
                    pos += 1
                    items.append(("", block()))
                else:
                    pos += 1
        return items

    return block()


def replaced_folders(anbennar: Path) -> list:
    """Folders under common/ that Anbennar's descriptor.mod replaces outright (replace_path)."""
    descriptor = anbennar / "descriptor.mod"
    text = _read(descriptor) if descriptor.is_file() else ""
    return [p[len("common/"):] for p in re.findall(r'^\s*replace_path\s*=\s*"([^"]+)"', text, re.M)
            if p.startswith("common/")]


def script_files(roots: Roots, submod: Path) -> dict:
    """Relative path under common/ -> file; the submod replaces Anbennar, which replaces the game (and drops the
    game's files in the folders its descriptor replaces)."""
    files = {}
    replaced = replaced_folders(roots.anbennar)
    for root in (roots.game / "game", roots.anbennar, submod):  # Roots.game is the install folder
        if root == roots.anbennar:
            files = {rel: path for rel, path in files.items()
                     if not any(rel.startswith(folder + "/") for folder in replaced)}
        common = root / "common"
        for folder, _dirs, names in os.walk(common):
            for name in names:
                if name.endswith(".txt"):
                    path = Path(folder) / name
                    files[path.relative_to(common).as_posix()] = path
    return files


def database_of(rel: str, modifier: str = LEVY) -> tuple:
    """(folder, how) for a file under common/: how is a classified value, "ignored" or None."""
    folder = rel.rsplit("/", 1)[0] if "/" in rel else ""
    classified, ignored = TABLES[modifier]
    for table, kind in ((classified, None), (ignored, "ignored")):
        for name in table:
            if folder == name or folder.startswith(name + "/"):
                return name, kind or table[name]
    return folder, None


def terrain_types(files: dict) -> set:
    """Every terrain key; <terrain>_levy_size is that terrain's own levy modifier."""
    return {key for rel, path in files.items() if rel.startswith("terrain_types/")
            for key, value in parse(_read(path)) if isinstance(value, list)}


def _levy_sites(items, path, terrains, modifier=LEVY):
    """Yield (path of block names, block items, value, terrain or None) for every use of modifier in items; for
    levy_size also every <terrain>_levy_size."""
    for key, value in items:
        if isinstance(value, list):
            yield from _levy_sites(value, path + [key], terrains, modifier)
        elif key == modifier:
            yield path, items, value, None
        elif modifier == LEVY and key.endswith("_levy_size") and key[:-len("_levy_size")] in terrains:
            yield path, items, value, key[:-len("_levy_size")]


_CONSTANT = re.compile(r"^\s*(@?[A-Za-z_][\w]*)\s*=\s*(-?[0-9.]+)\s*(?:#.*)?$", re.M)


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8-sig", errors="replace")


def constant_script_values(files: dict) -> dict:
    """name -> number for every script value that is a plain number."""
    found = {}
    for rel, path in files.items():
        if rel.startswith("script_values/"):
            found.update({k: float(v) for k, v in _CONSTANT.findall(_read(path)) if not k.startswith("@")})
    return found


def resolve(value: str, local: dict, constants: dict, where: str) -> float:
    """A levy_size value: a number, a file-local @variable or a constant script value."""
    try:
        return float(value)
    except ValueError:
        pass
    table = local if value.startswith("@") else constants
    if value not in table:
        raise GeneratorError(f"levy_size {value!r} in {where} is not a number or a constant value")
    return table[value]


def building_enabled(body: str) -> str:
    """A building's is_enabled trigger, rewritten for a script value in its province's scope (scope:holder is the
    province's owner, scope:county its county), or "" when it has none."""
    gate = parse_blocks(body).get("is_enabled", "")
    gate = " ".join(gate.split())
    return re.sub(r"\bscope:county\b", "county", re.sub(r"\bscope:holder\b", "province_owner", gate))


def _defined_keys(items: list, how: str) -> set:
    if how == "nested":
        return {key for _group, value in items if isinstance(value, list)
                for key, inner in value if isinstance(inner, list)}
    return {key for key, value in items if isinstance(value, list)}


def collect_sources(roots: Roots, submod: Path = SUBMOD, modifier: str = LEVY) -> list:
    """Every covered source of modifier (levy_size or vassal_levy_contribution_mult), one per object definition:
    when several files define the same object, the one loaded last (alphabetically by path, the submod over Anbennar
    over the game) wins and the others are dropped."""
    by_object = {}  # (database, key) -> [Source]
    files = script_files(roots, submod)
    constants = constant_script_values(files)
    terrains = terrain_types(files)
    for rel, path in sorted(files.items()):
        database, how = database_of(rel, modifier)
        if how == "ignored":
            continue
        text = _read(path)
        if how is None:
            if modifier in text and list(_levy_sites(parse(text), [], terrains, modifier)):
                raise GeneratorError(f"{modifier} in common/{rel}, a folder tools/data/racial_levies.py neither "
                                     f"classifies nor ignores")
            continue
        items = parse(text)
        for key in _defined_keys(items, how):
            by_object.pop((database, key), None)
        if modifier not in text:
            continue
        local = {k: float(v) for k, v in _CONSTANT.findall(text) if k.startswith("@")}
        raw = parse_blocks(text) if database == "buildings" else {}
        for names, block_items, value, terrain in _levy_sites(items, [], terrains, modifier):
            key = names[1] if how == "nested" and len(names) > 1 else names[0] if names else ""
            if key in OWN_KEYS:
                continue
            block = next((n for n in reversed(names) if n.endswith("modifier")), "")
            if names and block == "" and len(names) > 1:
                raise GeneratorError(f"{modifier} outside a modifier block in common/{rel}: {' > '.join(names)}")
            number = resolve(value, local, constants, f"common/{rel} ({key})")
            condition = {k: v for k, v in block_items if k in CONDITION_KEYS and not isinstance(v, list)}
            if terrain:
                condition["levy_terrain"] = terrain
            enabled = building_enabled(raw.get(key, ""))
            if enabled:
                condition["enabled"] = enabled
            by_object.setdefault((database, key), []).append(Source(database, key, block, number, condition))
    return [src for sources in by_object.values() for src in sources]


# --- writing ------------------------------------------------------------------------------------------------------

def number(value: float) -> str:
    text = f"{round(value, 4):.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def _parameter(src: Source, culture: str) -> list:
    param = src.condition.get("parameter")
    return [f"{culture} = {{ has_cultural_parameter = {param} }}"] if param else []


def _faith_parameter(src: Source, faith: str) -> list:
    param = src.condition.get("parameter")
    return [f"{faith} = {{ has_doctrine_parameter = {param} }}"] if param else []


def _if(limits: list, value: float) -> str:
    return f"if = {{ limit = {{ {' '.join(limits)} }} add = {number(value)} }}"


def _county_count(limits: list, value: float) -> str:
    return f"county = {{ every_county_province = {{ limit = {{ {' '.join(limits)} }} add = {number(value)} }} }}"


CULTURE_TRIGGER = {"culture/traditions": "has_cultural_tradition", "culture/innovations": "has_innovation",
                   "culture/pillars": "has_cultural_pillar"}


def source_script(src: Source) -> str:
    """One script-value line adding src.value when src applies to this holding (province scope); a
    <terrain>_levy_size only counts in a holding of that terrain."""
    script = _source_script(src)
    terrain = src.condition.get("levy_terrain")
    return f"if = {{ limit = {{ terrain = {terrain} }} {script} }}" if terrain else script


def _source_script(src: Source) -> str:
    db, key, block = src.database, src.key, src.block
    has = f"has_building = {key}" + (f" {src.condition['enabled']}" if src.condition.get("enabled") else "")
    if db == "buildings":
        if block == "province_modifier":
            return _if([has], src.value)
        if block == "province_culture_modifier":
            return _if([has] + _parameter(src, "county.culture"), src.value)
        if block == "province_faith_modifier":
            return _if([has] + _faith_parameter(src, "county.faith"), src.value)
        if block == "province_terrain_modifier":
            limits = [has]
            if "terrain" in src.condition:
                limits.append(f"terrain = {src.condition['terrain']}")
            if "is_coastal" in src.condition:
                limits.append(f"is_coastal = {src.condition['is_coastal']}")
            if "is_riverside" in src.condition:
                limits.append(f"is_riverside_province = {src.condition['is_riverside']}")
            return _if(limits + _parameter(src, "county.culture"), src.value)
        if block == "county_modifier":
            return _county_count([has], src.value)
        if block == "duchy_capital_county_modifier":  # every de jure county of the duchy whose capital has it
            # title_province only works on counties and baronies, so go through the duchy's capital county
            return _if(["exists = county.duchy", f"county.duchy.title_capital_county.title_province = {{ {has} }}"],
                       src.value)
        if block == "county_culture_modifier":
            return _county_count([has] + _parameter(src, "county.culture"), src.value)
        if block == "county_faith_modifier":
            return _county_count([has] + _faith_parameter(src, "county.faith"), src.value)
        if block == "character_modifier":
            return _if([f"province_owner = {{ any_directly_owned_province = {{ {has} }} }}"], src.value)
        if block == "character_culture_modifier":
            return _if([f"province_owner = {{ any_directly_owned_province = {{ {has} }} }}"]
                       + _parameter(src, "province_owner.culture"), src.value)
    elif db in CULTURE_TRIGGER:
        test = f"{CULTURE_TRIGGER[db]} = {key}"
        if block == "character_modifier":
            return _if([f"province_owner.culture = {{ {test} }}"], src.value)
        if block in ("county_modifier", "province_modifier"):
            return _if([f"county.culture = {{ {test} }}"], src.value)
    elif db == "religion/doctrine_types" and block == "character_modifier":
        return _if([f"province_owner.faith = {{ has_doctrine = {key} }}"], src.value)
    elif db == "religion/holy_site_types" and block == "character_modifier":
        return _if([f"province_owner.faith = {{ controls_holy_site = {key} }}"], src.value)
    elif db == "governments" and block == "character_modifier":
        return _if([f"province_owner = {{ has_government = {key} }}"], src.value)
    elif db == "laws" and block == "modifier":
        return _if([f"province_owner = {{ has_realm_law = {key} }}"], src.value)
    elif db == "traits":
        if block == "":
            return _if([f"province_owner = {{ has_trait = {key} }}"], src.value)
        if block == "culture_modifier":
            return _if([f"province_owner = {{ has_trait = {key} }}"] + _parameter(src, "province_owner.culture"),
                       src.value)
    raise GeneratorError(f"no condition for levy_size in {db} {key} {block or '(top level)'}")


def contribution_script(src: Source) -> str:
    """One script-value line adding src.value when src applies to this ruler (character scope)."""
    db, key, block = src.database, src.key, src.block
    if db == "laws" and block == "modifier":
        return _if([f"has_realm_law = {key}"], src.value)
    if db in CULTURE_TRIGGER and block == "character_modifier":
        return _if([f"culture = {{ {CULTURE_TRIGGER[db]} = {key} }}"], src.value)
    if db == "religion/doctrine_types" and block == "character_modifier":
        return _if([f"faith = {{ has_doctrine = {key} }}"], src.value)
    if db == "religion/holy_site_types" and block == "character_modifier":
        return _if([f"faith = {{ controls_holy_site = {key} }}"], src.value)
    if db == "governments" and block == "character_modifier":
        return _if([f"has_government = {key}"], src.value)
    if db == "dynasty_perks" and block == "character_modifier":
        return _if([f"dynasty ?= {{ has_dynasty_perk = {key} }}"], src.value)
    if db == "traits" and block == "":
        return _if([f"has_trait = {key}"], src.value)
    if db == "buildings" and block == "character_modifier":
        enabled = f" {src.condition['enabled']}" if src.condition.get("enabled") else ""
        return _if([f"any_directly_owned_province = {{ has_building = {key}{enabled} }}"], src.value)
    if db == "lifestyle_perks":
        if block == "character_modifier":
            return _if([f"has_perk = {key}"], src.value)
        if block == "government_character_modifier" and "flag" in src.condition:
            test = f"government_has_flag = {src.condition['flag']}"
            if src.condition.get("invert_check") == "yes":
                test = f"NOT = {{ {test} }}"
            return _if([f"has_perk = {key}", test], src.value)
    raise GeneratorError(f"no condition for {CONTRIBUTION} in {db} {key} {block or '(top level)'}")


def tier(s: float) -> int:
    """Correction tier of a summed levy bonus: s / STEP rounded half away from zero, s clamped to the range."""
    x = max(S_MIN, min(S_MAX, s)) / STEP
    return int(abs(x) + 0.5 + 1e-9) * (1 if x >= 0 else -1)


def tier_key(race: str, n: int, family: str = "levy") -> str:
    """Correction modifier of a race and tier: family "levy" (province) or "contribution" (character)."""
    return f"aov_racial_{family}_{race}_{n}" if n >= 0 else f"aov_racial_{family}_{race}_m{-n}"


def tiers() -> range:
    return range(tier(S_MIN), tier(S_MAX) + 1)


def values_file(sources: list, contributions: list = ()) -> str:
    lines = [HEADER, "# Province scope: the summed levy_size of the covered sources that apply to this holding.",
             "aov_holding_levy_size_bonus = {", "\tvalue = 0"]
    lines += [f"\t{source_script(src)} # {src.database} {src.key}" for src in sources]
    lines += ["}", "", "# Province scope: the correction tier, aov_holding_levy_size_bonus / "
              f"{number(STEP)} rounded, clamped to {tier(S_MIN)}..{tier(S_MAX)}.",
              "aov_holding_levy_tier = {", "\tvalue = aov_holding_levy_size_bonus", f"\tdivide = {number(STEP)}",
              "\tround = yes", f"\tmin = {tier(S_MIN)}", f"\tmax = {tier(S_MAX)}", "}", ""]
    lines += ["# Character scope: the summed vassal_levy_contribution_mult of the covered sources that apply to this "
              "ruler.", "aov_ruler_contribution_bonus = {", "\tvalue = 0"]
    lines += [f"\t{contribution_script(src)} # {src.database} {src.key}" for src in contributions]
    lines += ["}", "", "# Character scope: the contribution correction tier, rounded and clamped like the holding tier.",
              "aov_ruler_contribution_tier = {", "\tvalue = aov_ruler_contribution_bonus", f"\tdivide = {number(STEP)}",
              "\tround = yes", f"\tmin = {tier(S_MIN)}", f"\tmax = {tier(S_MAX)}", "}", ""]
    return "\n".join(lines)


def modifiers_file() -> str:
    lines = [HEADER]
    for race, f in RACES.items():
        lines.append(f"# {RACE_NAMES[race]}: levy_size = -{number(f)} x {number(STEP)} x tier")
        for n in tiers():
            if n:
                lines += [f"{tier_key(race, n)} = {{", f"\tlevy_size = {number(-f * STEP * n)}", "}"]
        lines.append("")
    for race, f in RACES.items():
        lines.append(f"# {RACE_NAMES[race]} rulers: vassal_levy_contribution_mult = -{number(f)} x {number(STEP)} x tier")
        for n in tiers():
            if n:
                lines += [f"{tier_key(race, n, 'contribution')} = {{",
                          f"\tvassal_levy_contribution_mult = {number(-f * STEP * n)}", "}"]
        lines.append("")
    return "\n".join(lines)


def _chain(race: str, effect: str, family: str = "levy") -> list:
    out, first = [], True
    for n in tiers():
        if n:
            out.append(f"\t\t\t{'if' if first else 'else_if'} = {{ limit = {{ var:aov_racial_{family}_tier = {n} }} "
                       f"{effect} = {tier_key(race, n, family)} }}")
            first = False
    return out


def effects_file() -> str:
    lines = [HEADER, "# Province scope. Removes the holding's current correction, then, when its owner's culture has a",
             "# racial heritage, adds the tier for that race and the holding's summed levy bonus. Variables",
             "# aov_racial_levy_tier and aov_racial_levy_race record what was added.",
             "aov_refresh_holding_levy_correction = {", "\tif = {", "\t\tlimit = { has_variable = aov_racial_levy_tier }"]
    for i, race in enumerate(RACES):
        lines.append(f"\t\t{'if' if i == 0 else 'else_if'} = {{")
        lines.append(f"\t\t\tlimit = {{ var:aov_racial_levy_race = flag:{race} }}")
        lines += _chain(race, "remove_province_modifier")
        lines.append("\t\t}")
    lines += ["\t\tremove_variable = aov_racial_levy_tier", "\t\tremove_variable = aov_racial_levy_race", "\t}",
              "\tif = {", "\t\tlimit = {", "\t\t\texists = province_owner", "\t\t\tprovince_owner.culture = {",
              "\t\t\t\tOR = {"]
    lines += [f"\t\t\t\t\thas_cultural_parameter = aov_racial_levy_{race}" for race in RACES]
    lines += ["\t\t\t\t}", "\t\t\t}", "\t\t}",
              "\t\tset_variable = { name = aov_racial_levy_tier value = aov_holding_levy_tier }"]
    for i, race in enumerate(RACES):
        lines.append(f"\t\t{'if' if i == 0 else 'else_if'} = {{")
        lines.append(f"\t\t\tlimit = {{ province_owner.culture = {{ has_cultural_parameter = aov_racial_levy_{race} }} }}")
        lines.append(f"\t\t\tset_variable = {{ name = aov_racial_levy_race value = flag:{race} }}")
        lines += _chain(race, "add_province_modifier")
        lines.append("\t\t}")
    lines += ["\t}", "}", "",
              "# Character scope. The same for what vassals send this ruler: removes the current contribution correction,",
              "# then, when the ruler's culture has a racial heritage, adds the tier for that race and the ruler's summed",
              "# vassal_levy_contribution_mult. Variables aov_racial_contribution_tier and aov_racial_contribution_race.",
              "aov_refresh_ruler_contribution_correction = {", "\tif = {",
              "\t\tlimit = { has_variable = aov_racial_contribution_tier }"]
    for i, race in enumerate(RACES):
        lines.append(f"\t\t{'if' if i == 0 else 'else_if'} = {{")
        lines.append(f"\t\t\tlimit = {{ var:aov_racial_contribution_race = flag:{race} }}")
        lines += _chain(race, "remove_character_modifier", "contribution")
        lines.append("\t\t}")
    lines += ["\t\tremove_variable = aov_racial_contribution_tier", "\t\tremove_variable = aov_racial_contribution_race",
              "\t}", "\tif = {", "\t\tlimit = {", "\t\t\tculture = {", "\t\t\t\tOR = {"]
    lines += [f"\t\t\t\t\thas_cultural_parameter = aov_racial_levy_{race}" for race in RACES]
    lines += ["\t\t\t\t}", "\t\t\t}", "\t\t}",
              "\t\tset_variable = { name = aov_racial_contribution_tier value = aov_ruler_contribution_tier }"]
    for i, race in enumerate(RACES):
        lines.append(f"\t\t{'if' if i == 0 else 'else_if'} = {{")
        lines.append(f"\t\t\tlimit = {{ culture = {{ has_cultural_parameter = aov_racial_levy_{race} }} }}")
        lines.append(f"\t\t\tset_variable = {{ name = aov_racial_contribution_race value = flag:{race} }}")
        lines += _chain(race, "add_character_modifier", "contribution")
        lines.append("\t\t}")
    lines += ["\t}", "}", ""]
    return "\n".join(lines)


def loc_file() -> bytes:
    lines = ["l_english:", " # Anbennar Overhaul: generated by tools/build_racial_levies.py; do not edit by hand."]
    for race in RACES:
        name = f"{RACE_NAMES[race]} Levy Share"
        desc = (f"{RACE_NAMES[race]} holdings raise {SHARE_TEXT[race]} the levies of a human holding. This offsets the "
                f"part of this holding's levy bonuses that would change that share.")
        for n in tiers():
            if n:
                lines += [f' {tier_key(race, n)}:0 "{name}"', f' {tier_key(race, n)}_desc:0 "{desc}"']
        name = f"{RACE_NAMES[race]} Levy Contributions"
        desc = (f"{RACE_NAMES[race]} rulers receive {SHARE_TEXT[race]} the levies their vassals would send a human "
                f"ruler. This offsets the part of this ruler's vassal levy bonuses that would change that share.")
        for n in tiers():
            if n:
                lines += [f' {tier_key(race, n, "contribution")}:0 "{name}"',
                          f' {tier_key(race, n, "contribution")}_desc:0 "{desc}"']
    return ("﻿" + "\n".join(lines) + "\n").encode("utf-8")


def _script(text: str) -> bytes:
    return ("﻿" + text).encode("utf-8")


def build_all(roots: Roots, notes=None) -> dict:
    for name, path in (("Anbennar", roots.anbennar), ("Crusader Kings III", roots.game)):
        if not path.is_dir():
            raise GeneratorError(f"{name} not found at {path}")
    sources = collect_sources(roots)
    contributions = collect_sources(roots, modifier=CONTRIBUTION)
    if notes is not None:
        counts = {}
        for src in sources:
            counts[src.database] = counts.get(src.database, 0) + 1
        notes.append("levy sources: " + ", ".join(f"{db} {n}" for db, n in sorted(counts.items())))
        notes.append("ignored folders: " + ", ".join(sorted(IGNORED)))
        notes.append(f"vassal contribution sources: {len(contributions)}")
    return {VALUES_FILE: _script(values_file(sources, contributions)), MODIFIERS_FILE: _script(modifiers_file()),
            EFFECTS_FILE: _script(effects_file()), LOC_FILE: loc_file()}


def main() -> int:
    default = Roots.default()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=default.anbennar)
    parser.add_argument("--game", type=Path, default=default.game, help="CK3 install folder (its game/ folder)")
    args = parser.parse_args()
    notes = []
    try:
        files = build_all(Roots(rie=default.rie, anbennar=args.anbennar, game=args.game), notes)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for note in notes:
        print(f"note: {note}")
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
