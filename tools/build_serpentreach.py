class Realm:
    """Titles of the layout: kingdoms -> duchies -> counties, with keys and display names. `cfg` is the region's data
    module (default Serpentreach's). Kingdoms in `cfg.EXISTING_KINGDOMS` are Anbennar's: they and their duchies with no
    new county (Anbennar's own) are not rendered; their new duchies are parked (`render_titles`)."""

    def __init__(self, lay: sl.Layout, cfg=None):
        cfg = self.cfg = cfg or data
        self.lay = lay
        self.county = {c.key: c for c in lay.counties}
        self.duchies = {}  # duchy key -> (name, [county keys]) in order
        self.kingdom_of = {}
        self.duchy_of = {}
        self.kingdoms = {}
        self.existing_kingdoms = tuple(getattr(cfg, "EXISTING_KINGDOMS", ()))
        unknown = sorted(set(self.existing_kingdoms) - set(cfg.KINGDOMS))
        if unknown:
            raise GeneratorError(f"EXISTING_KINGDOMS: not in KINGDOMS: {', '.join(unknown)}")
        area_duchy = {}
        for kkey, (kname, areas) in cfg.KINGDOMS.items():
            self.kingdoms[kkey] = (kname, [])
            for area in areas:
                name = lay.area_names[area]
                dkey = "d_" + sl.slug(name)
                if dkey in self.duchies:
                    raise GeneratorError(f"two areas make duchy {dkey}")
                self.duchies[dkey] = (name, [])
                area_duchy[area] = dkey
                self.kingdoms[kkey][1].append(dkey)
                self.kingdom_of[dkey] = kkey
        self.duchy_area = {dkey: area for area, dkey in area_duchy.items()}
        for c in lay.counties:
            dkey = area_duchy[c.area]
            self.duchies[dkey][1].append(c.key)
            self.duchy_of[c.key] = dkey
        for name, table in (("KINGDOM_CAPITALS", cfg.KINGDOM_CAPITALS), ("KINGDOM_ARMS", cfg.KINGDOM_ARMS),
                            ("KINGDOM_CULTURES", cfg.KINGDOM_CULTURES)):
            if set(table) != set(self.kingdoms):
                raise GeneratorError(f"{name} does not list exactly the kingdoms of KINGDOMS")
        unknown = sorted(set(getattr(cfg, "DYNASTY_NAMES", {})) - set(self.duchies))
        if unknown:
            raise GeneratorError(f"DYNASTY_NAMES: not duchies of the region: {', '.join(unknown)}")
        # Anbennar's duchies inside its kingdoms: no new county
        self.existing_duchies = {d for k in self.existing_kingdoms for d in self.kingdoms[k][1] if not self.duchies[d][1]}
        self.hold_duchy = {}
        for kkey, ckey in cfg.KINGDOM_CAPITALS.items():
            if kkey in self.existing_kingdoms:  # Anbennar's hold county; its duchy is the kingdom's first
                self.hold_duchy[kkey] = self.kingdoms[kkey][1][0]
                continue
            if ckey not in self.county or self.kingdom_of[self.duchy_of[ckey]] != kkey:
                raise GeneratorError(f"KINGDOM_CAPITALS: {ckey} is not a county of {kkey}")
            self.hold_duchy[kkey] = self.duchy_of[ckey]
        empty = sorted(d for d, (_, counties) in self.duchies.items() if not counties and d not in self.existing_duchies)
        if empty:
            raise GeneratorError(f"duchies with no county: {', '.join(empty)}")
        others = ({self.duchy_area[d] for d in self.duchies} - {self.duchy_area[d] for d in self.hold_duchy.values()}
                  - {self.duchy_area[d] for d in self.existing_duchies})
        if set(cfg.DUCHY_CHARGES) != others:
            raise GeneratorError(f"DUCHY_CHARGES must list exactly the areas of duchies without a hold: missing "
                                 f"{sorted(others - set(cfg.DUCHY_CHARGES))}, "
                                 f"extra {sorted(set(cfg.DUCHY_CHARGES) - others)}")
        # The game builds a duchy's capital building in the duchy's first county, whatever its `capital` says, so the
        # capital county (the hold, when there is one) leads each duchy.
        for dkey, (dname, counties) in self.duchies.items():
            if counties:
                capital = self.duchy_capital(dkey)
                self.duchies[dkey] = (dname, [capital] + [c for c in counties if c != capital])
        if cfg.EMPIRE_CAPITAL not in self.county:
            raise GeneratorError(f"EMPIRE_CAPITAL {cfg.EMPIRE_CAPITAL} is not a county of the region")
        self.emperor_duchy = self.duchy_of[cfg.EMPIRE_CAPITAL]

    def culture_of(self, dkey: str) -> str:
        """The culture of a duchy's kingdom (KINGDOM_CULTURES)."""
        return self.cfg.KINGDOM_CULTURES[self.kingdom_of[dkey]]

    def duchy_capital(self, dkey: str) -> str:
        counties = self.duchies[dkey][1]
        holds = [c for c in counties if self.county[c].type in ("dwarven_hold", "dwarven_hold_surface")]
        return (holds or counties)[0]

    def barony_keys(self, ckey: str) -> list:
        n = len(self.county[ckey].baronies)
        base = "b_" + ckey[2:]
        return [base] + [f"{base}_{i}" for i in range(2, n + 1)]

    def barony_names(self, ckey: str) -> list:
        name = self.county[ckey].name
        n = len(self.county[ckey].baronies)
        return [name] + [f"{name} {self.cfg.BARONY_SUFFIXES[i - 1]}" for i in range(1, n)]

    def cave_counties(self) -> list:
        """The layout's counties less the surface ones (Serpent's Vale)."""
        return [c for c in self.lay.counties if c.type != "surface"]

    def new_kingdoms(self) -> list:
        return [k for k in self.kingdoms if k not in self.existing_kingdoms]

    def parked_duchies(self) -> list:
        """New duchies of Anbennar's kingdoms (rendered under PARKING_KINGDOM, moved by history)."""
        return [d for k in self.existing_kingdoms for d in self.kingdoms[k][1] if d not in self.existing_duchies]

    def colours(self) -> dict:
        """Title key -> map colour: kingdoms their EU4 colour, duchies shades of it, counties near their duchy's."""
        cfg = self.cfg
        out = {cfg.EMPIRE[0]: cfg.EMPIRE_COLOUR}
        for kkey, (_, duchies) in self.kingdoms.items():
            out[kkey] = cfg.KINGDOM_ARMS[kkey][1]
            # the duchies' offsets slide together so all stay inside 0.12..0.92 and none folds onto another
            offsets = [cfg.DUCHY_SHADES[i % len(cfg.DUCHY_SHADES)] for i in range(len(duchies))]
            light = colorsys.rgb_to_hls(*(v / 255 for v in out[kkey]))[1]
            slide = min(0.0, 0.92 - light - max(offsets)) + max(0.0, 0.12 - light - min(offsets))
            for dkey, offset in zip(duchies, offsets):
                out[dkey] = shade(out[kkey], offset + slide)
                for ckey in self.duchies[dkey][1]:
                    jitter = (_hash("colour:" + ckey) % 2001 / 1000 - 1) * cfg.COUNTY_JITTER
                    out[ckey] = shade(out[dkey], jitter)
        return out

    def all_keys(self) -> set:
        """Every title key this region defines (Anbennar's kingdoms and duchies left out)."""
        keys = ({self.cfg.EMPIRE[0]} | set(self.new_kingdoms()) | (set(self.duchies) - self.existing_duchies)
                | set(self.county))
        if self.existing_kingdoms:
            keys.add(self.cfg.PARKING_KINGDOM)
        for ckey in self.county:
            keys |= set(self.barony_keys(ckey))
        return keys


