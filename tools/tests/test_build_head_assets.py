"""Tests for tools/build_head_assets.py, the whole-file overrides of Anbennar's head assets.

    python -I tools/run_tests.py build_head_assets
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # python -I does not add the tools folder
import build_head_assets as head  # noqa: E402

ASSET_FIXTURE = """pdxmesh = {
\tname = "male_head_mesh"
\tblend_shape = { id = "male_kobold_head"\t\ttype = "blendshapes/male_kobold_head.mesh"  data = "position"}
\tblend_shape = { id = "male_kobold_head_normals"\t\ttype = "blendshapes/male_argonian_head_normals.mesh"}
}

entity = {
\tname = "head_basic_entity_male"
\tattribute = { name = "kobold_head_bs"\t\tblend_shape = "male_kobold_head" }
\tattribute = { name = "kobold_head_proportions"\t\tadditive_animation = "male_head_kobold_proportions" }
}
"""

SUBMOD = head.SUBMOD


class AddHeadLinesTests(unittest.TestCase):
    def test_lines_added_after_kobold_anchors(self):
        lines = head.add_head_lines(ASSET_FIXTURE, "male").split("\n")
        shape = next(i for i, l in enumerate(lines) if 'id = "male_gnoll_head"' in l)
        self.assertIn("male_kobold_head_normals", lines[shape - 1])
        self.assertIn('type = "blendshapes/aov_gnoll_male_head_bs.mesh"', lines[shape])
        attr = next(i for i, l in enumerate(lines) if 'name = "gnoll_head_bs"' in l)
        self.assertIn("kobold_head_proportions", lines[attr - 1])
        self.assertIn('blend_shape = "male_gnoll_head"', lines[attr])
        self.assertTrue(lines[shape].startswith("\t") and lines[attr].startswith("\t"))

    def test_only_marked_lines_added_and_idempotent(self):
        out = head.add_head_lines(ASSET_FIXTURE, "male")
        added = [l for l in out.split("\n") if l not in ASSET_FIXTURE.split("\n")]
        self.assertEqual(len(added), len(head.SHAPES["male"]) + len(head.ATTRIBUTES["male"]))
        self.assertTrue(all(l.endswith(" " + head.MARKER) for l in added))
        self.assertEqual(head.add_head_lines(out, "male"), out)

    def test_missing_kobold_anchor_stops(self):
        with self.assertRaises(SystemExit):
            head.add_head_lines(ASSET_FIXTURE.replace("kobold_head_proportions", "other"), "male")
        with self.assertRaises(SystemExit):
            head.add_head_lines(ASSET_FIXTURE, "female")  # the fixture has only the male kobold head

    def test_repeated_kobold_anchor_stops(self):
        repeated = ASSET_FIXTURE.replace("}\n\nentity", '\tblend_shape = { id = "male_kobold_head_normals" }\n}\n\nentity')
        with self.assertRaises(SystemExit):
            head.add_head_lines(repeated, "male")


def live_paths():
    return [(head.DEFAULT_ANBENNAR / rel, SUBMOD / rel, sex) for sex, rel in head.HEADS.items()]


class FreshnessTests(unittest.TestCase):
    @unittest.skipUnless(all(a.is_file() and o.is_file() for a, o, _ in live_paths()),
                         "needs Anbennar and the generated files")
    def test_head_assets_are_anbennars_plus_marked_lines(self):
        for src_path, out_path, sex in live_paths():
            src = src_path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
            out = out_path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
            lines = out.split("\n")
            self.assertTrue(lines[0].startswith(head.MARKER + ": generated by tools/build_head_assets.py"))
            self.assertTrue(lines[1].startswith(head.MARKER + ": do not edit"))
            self.assertEqual("\n".join(lines[2:]), head.add_head_lines(src, sex), f"{out_path.name} is stale")


class ArtTests(unittest.TestCase):
    def test_blend_shapes_listed_in_assets_exist(self):
        for sex, rel in head.HEADS.items():
            for _shape_id, mesh in head.SHAPES[sex]:
                self.assertTrue((SUBMOD / Path(rel).parent / mesh).is_file(), mesh)

    def test_attributes_name_a_listed_shape_or_anbennars_neutral(self):
        for sex in head.HEADS:
            shapes = {shape_id for shape_id, _mesh in head.SHAPES[sex]} | {f"{sex}_bs_neutral"}
            for attribute, shape_id in head.ATTRIBUTES[sex]:
                self.assertIn(shape_id, shapes, attribute)

    @unittest.skipUnless(all(a.is_file() for a, _o, _s in live_paths()), "needs Anbennar")
    def test_neutral_shape_exists(self):
        for src_path, _out_path, sex in live_paths():
            self.assertIn(f'id = "{sex}_bs_neutral"', src_path.read_bytes().decode("utf-8-sig"))


if __name__ == "__main__":
    unittest.main()
