"""Regenerate the racial traditions and their men-at-arms for Anbennar Overhaul (docs/systems/racial-traditions.md).

Writes, from tools/data/racial_traditions.py:
- the unique traditions of racial cultures (each pickable by its culture and the cultures descended from it);
- the new men-at-arms they unlock and their costs (the racial armies pricing: vanilla power per gold);
- the game-start effect that gives each culture its traditions;
- their localization.
Rerun after editing the data file or after an Anbennar update (it checks every culture and tradition it names):

    python -I tools/build_racial_traditions.py [--anbennar PATH] [--game PATH]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_hud_override import GeneratorError  # noqa: E402
from data import racial_traditions as data  # noqa: E402

SUBMOD = Path(__file__).resolve().parent.parent
DEFAULT_ANBENNAR = SUBMOD.parent / "anbennar-ck3-dev-master"
DEFAULT_GAME = Path("C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game")
BOM = "\ufeff"
MARKER = "# Anbennar Overhaul"

TRADITION_FILE = "common/culture/traditions/aov_racial_traditions.txt"
MAA_FILE = "common/men_at_arms_types/aov_regional_maa_types.txt"
VALUES_FILE = "common/script_values/aov_regional_maa_values.txt"
EFFECT_FILE = "common/scripted_effects/aov_racial_traditions_effects.txt"
LOC_FILE = "localization/english/aov_racial_traditions_l_english.yml"
ICON_DIR = "gfx/interface/icons/regimenttypes"
CATEGORIES = ("realm", "combat", "societal", "regional", "ritual")
PARAMETER_UNITS = {"aov_unlock_maa_thorn_druids": "druids"}  # parameters whose unit is not aov_<name>
MODIFIER_BLOCKS = (("character", "character_modifier"), ("culture", "culture_modifier"), ("county", "county_modifier"))


def header() -> str:
    return (f"{MARKER}: generated by tools/build_racial_traditions.py from tools/data/racial_traditions.py.\n"
            f"{MARKER}: do not edit by hand; edit the data and rerun it. See docs/systems/racial-traditions.md.\n")


def unit_parameter(unit: str) -> str:
    return "aov_unlock_maa_" + unit.removeprefix("aov_")


def number(value) -> str:
    return str(value) if isinstance(value, int) else f"{value:g}"


def rnd(x: float) -> int:
    """Round half away from zero, as the racial armies MAA files do."""
    return int(abs(x) + 0.5) * (1 if x >= 0 else -1)


def unit_costs(unit: dict) -> tuple:
    """(buy, low upkeep, high upkeep): the role's vanilla costs x sqrt(damage ratio x toughness ratio)."""
    vd, vt, vb, vu = data.VANILLA_ROLES[unit["type"]]
    factor = ((unit["stack"] * unit["damage"] / vd) * (unit["stack"] * unit["toughness"] / vt)) ** 0.5
    buy = 5 * rnd(vb * factor / 5)
    low = round(vu * factor, 2)
    return buy, low, round(3 * low, 2)


# --- checks ------------------------------------------------------------------------------------------------------

def _keys(paths, pattern: str) -> set:
    found = set()
    for path in paths:
        text = re.sub(r"#.*", "", path.read_bytes().decode("utf-8-sig", "replace"))
        found.update(re.findall(pattern, text, re.M))
    return found


def known_cultures(anbennar: Path, submod: Path) -> set:
    paths = [p for root in (anbennar, submod) for p in (root / "common/culture/cultures").glob("*.txt")]
    return _keys(paths, r"^([a-z_]+)\s*=\s*\{")


def known_traditions(anbennar: Path, game: Path) -> set:
    paths = [p for root in (game, anbennar) for p in (root / "common/culture/traditions").glob("*.txt")]
    return _keys(paths, r"^(tradition_\w+)\s*=\s*\{")


def check(anbennar: Path, game: Path, submod: Path) -> None:
    cultures = known_cultures(anbennar, submod)
    base_traditions = known_traditions(anbennar, game)
    clash = sorted(set(data.TRADITIONS) & base_traditions)
    if clash:
        raise GeneratorError("already defined by the game or Anbennar: " + ", ".join(clash))
    unlocked = []
    for key, t in data.TRADITIONS.items():
        if t["category"] not in CATEGORIES:
            raise GeneratorError(f"{key}: unknown category {t['category']}")
        kind, value = t["gate"]
        if kind == "culture" and value not in cultures:
            raise GeneratorError(f"{key}: unknown culture {value}")
        unlocked += t.get("units", ())
    if sorted(unlocked) != sorted(data.UNITS):
        raise GeneratorError("every unit must be unlocked by exactly one tradition")
    for culture, traditions in data.GRANTS.items():
        if culture not in cultures:
            raise GeneratorError(f"GRANTS: unknown culture {culture}")
        for tradition in traditions:
            if tradition not in data.TRADITIONS and tradition not in base_traditions:
                raise GeneratorError(f"GRANTS {culture}: unknown tradition {tradition}")
    granted = {t for ts in data.GRANTS.values() for t in ts}
    missing = sorted(set(data.TRADITIONS) - granted)
    if missing:
        raise GeneratorError("never granted: " + ", ".join(missing))
    for key, unit in data.UNITS.items():
        if unit["type"] not in data.VANILLA_ROLES:
            raise GeneratorError(f"{key}: no pricing for type {unit['type']}")
        if not (submod / ICON_DIR / f"aov_rie_{unit['art']}.dds").is_file():
            raise GeneratorError(f"{key}: no icon {ICON_DIR}/aov_rie_{unit['art']}.dds (copy it from RiE first)")
    texts = [t["name"] + " " + t["desc"] for t in data.TRADITIONS.values()]
    texts += [u["name"] + " " + u["flavor"] for u in data.UNITS.values()]
    for word in data.FORBIDDEN_LORE:
        if any(word.lower() in text.lower() for text in texts):
            raise GeneratorError(f"Realms in Exile word in our text: {word}")


# --- writers -----------------------------------------------------------------------------------------------------

def gate(t: dict) -> list:
    kind, value = t["gate"]
    if kind == "lineage":
        return [f"\t\t{value} = yes"]
    return ["\t\tOR = {", f"\t\t\tthis = culture:{value}",
            f"\t\t\tany_parent_culture_or_above = {{ this = culture:{value} }}", "\t\t}"]


def modifier_block(name: str, modifiers: dict) -> list:
    if not modifiers:
        return []
    return [f"\t{name} = {{"] + [f"\t\t{k} = {number(v)}" for k, v in modifiers.items()] + ["\t}"]


def tradition_block(key: str, t: dict) -> str:
    background, pattern, icon = t["layers"]
    parameters = [unit_parameter(u) for u in t.get("units", ())] + list(t.get("parameters", ()))
    lines = [f"{key} = {{", f"\tcategory = {t['category']}",
             "\tlayers = {", f"\t\t0 = {background}", f"\t\t1 = {pattern}", f"\t\t4 = {icon}", "\t}",
             f"\tis_shown = {{ has_cultural_pillar = {t['heritage']} }}", "\tcan_pick = {"] + gate(t) + ["\t}"]
    if parameters:
        lines += ["\tparameters = {"] + [f"\t\t{p} = yes" for p in parameters] + ["\t}"]
    for field, block in MODIFIER_BLOCKS:
        lines += modifier_block(block, t.get(field, {}))
    lines += ["\tcost = {", "\t\tprestige = {", "\t\t\tadd = {", "\t\t\t\tvalue = tradition_base_cost",
              "\t\t\t\tdesc = BASE", '\t\t\t\tformat = "BASE_VALUE_FORMAT"', "\t\t\t}",
              "\t\t\tmultiply = tradition_replacement_cost_if_relevant", "\t\t}", "\t}",
              "\tai_will_do = { value = 100 }", "}"]
    return "\n".join(lines)


def build_traditions() -> bytes:
    parts = [BOM + header(), f"# Source of each tradition: EU4 Anbennar ideas (`eu4` in the data file).", ""]
    for key, t in data.TRADITIONS.items():
        parts += [f"# {t['eu4']}", tradition_block(key, t), ""]
    return "\n".join(parts).encode("utf-8")


def unit_block(key: str, u: dict) -> str:
    lines = [f"{key} = {{", f"\ttype = {u['type']}", "", f"\tdamage = {u['damage']}", f"\ttoughness = {u['toughness']}",
             f"\tpursuit = {u.get('pursuit', 0)}", f"\tscreen = {u.get('screen', 0)}", ""]
    if u.get("counters"):
        lines += ["\tcounters = {"] + [f"\t\t{k} = {v}" for k, v in u["counters"].items()] + ["\t}"]
    if u.get("terrain"):
        lines += ["\tterrain_bonus = {"]
        lines += [f"\t\t{t} = {{ damage = {rnd(u['damage'] * f)} toughness = {rnd(u['toughness'] * f)} }}"
                  for t, f in u["terrain"].items()]
        lines += ["\t}"]
    lines += ["\tcan_recruit = {", f"\t\tvalid_for_maa_trigger = {{ PARAMETER = {unit_parameter(key)} }}", "\t}",
              f"\tbuy_cost = {{ gold = {key}_recruitment_cost }}",
              f"\tlow_maintenance_cost = {{ gold = {key}_low_maint_cost }}",
              f"\thigh_maintenance_cost = {{ gold = {key}_high_maint_cost }}",
              f"\tstack = {u['stack']}", "\tai_quality = { value = @cultural_maa_extra_ai_score }",
              f"\ticon = aov_rie_{u['art']}", "\tallowed_in_hired_troops = no", "}"]
    return "\n".join(lines)


def build_units() -> bytes:
    parts = [BOM + header(), "@cultural_maa_extra_ai_score = 80 # Anbennar's value (anb_cultural_maa_generics.txt)", ""]
    for key, u in data.UNITS.items():
        parts += [unit_block(key, u), ""]
    return "\n".join(parts).encode("utf-8")


def build_values() -> bytes:
    parts = [BOM + header(), "# Each unit costs its role's vanilla buy cost and upkeep times sqrt(regiment damage ratio "
                             "x regiment toughness ratio),", "# as in aov_racial_maa_values.txt.", ""]
    for key, u in data.UNITS.items():
        buy, low, high = unit_costs(u)
        parts += [f"{key}_recruitment_cost = {buy}", f"{key}_low_maint_cost = {low:g}",
                  f"{key}_high_maint_cost = {high:g}"]
    return "\n".join(parts + [""]).encode("utf-8")


def build_effects() -> bytes:
    lines = [BOM + header(), "# Gives each culture its traditions at game start (aov_racial_traditions_on_actions.txt).",
             "aov_racial_traditions_game_start_effect = {"]
    for culture, traditions in data.GRANTS.items():
        lines.append(f"\tculture:{culture} = {{")
        for t in traditions:
            lines.append(f"\t\tif = {{ limit = {{ NOT = {{ has_cultural_tradition = {t} }} }} "
                         f"add_culture_tradition = {t} }}")
        lines.append("\t}")
    lines += ["}", ""]
    return "\n".join(lines).encode("utf-8")


def loc_line(key: str, text: str) -> str:
    return f' {key}:0 "{text}"'


def parameter_loc(parameter: str) -> str:
    """The tradition tooltip line of an unlock parameter (the game reads culture_parameter_<name>)."""
    unit = PARAMETER_UNITS.get(parameter, "aov_" + parameter.removeprefix("aov_unlock_maa_"))
    return loc_line(f"culture_parameter_{parameter}", f"Can recruit [GetMaA('{unit}').GetName] as [men_at_arms|E]")


def build_loc() -> bytes:
    lines = [BOM + "l_english:", f" # {MARKER}: generated by tools/build_racial_traditions.py; do not edit by hand."]
    for key, t in data.TRADITIONS.items():
        lines += [loc_line(f"{key}_name", t["name"]), loc_line(f"{key}_desc", t["desc"])]
    for key, u in data.UNITS.items():
        lines += [loc_line(key, u["name"]), loc_line(f"{key}_flavor", f"#F {u['flavor']}#!"),
                  parameter_loc(unit_parameter(key))]
    for t in data.TRADITIONS.values():
        lines += [parameter_loc(p) for p in t.get("parameters", ())]
    return "\n".join(lines + [""]).encode("utf-8")


def build_all(anbennar: Path = DEFAULT_ANBENNAR, game: Path = DEFAULT_GAME, submod: Path = SUBMOD) -> dict:
    check(anbennar, game, submod)
    return {TRADITION_FILE: build_traditions(), MAA_FILE: build_units(), VALUES_FILE: build_values(),
            EFFECT_FILE: build_effects(), LOC_FILE: build_loc()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--anbennar", type=Path, default=DEFAULT_ANBENNAR)
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME)
    args = parser.parse_args()
    try:
        files = build_all(args.anbennar, args.game)
    except (GeneratorError, OSError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for rel, content in files.items():
        target = SUBMOD / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
