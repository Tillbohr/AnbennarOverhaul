def castle_assets(root: Path):
    """The @holding_illustration_* lines and, per castle level in ASSET_BAND, the lines of its asset = { } blocks."""
    lines = (Path(root) / CASTLE_FILE).read_text(encoding="utf-8-sig").splitlines()
    variables = [l for l in lines if l.startswith("@holding_illustration_")]
    assets, current, block = {}, None, None
    for line in lines:
        if line.startswith("castle_0") and line.endswith(" = {"):
            current = line.split()[0]
            assets[current] = []
            continue
        if current is None:
            continue
        if line.startswith("\t\tasset = {"):
            block = assets[current]
        if block is not None:
            block.append(line)
            if line == "\t\t}":
                block = None
    return variables, {k: v for k, v in assets.items() if k in set(holds.ASSET_BAND.values())}


def fmt(x):
    return f"{x:g}" if isinstance(x, float) else str(x)


def modifier_block(name, values):
    values = {k: v for k, v in values.items() if v}
    if not values:
        return ""
    body = "".join(f"\t\t{k} = {fmt(v)}\n" for k, v in values.items())
    return f"\t{name} = {{\n{body}\t}}\n"


def level_key(n):
    return f"dwarven_hold_{n:02d}"


# The hold levels and the dwarven buildings work only under a dwarven holder in an unruined hold.
IS_ENABLED = ("\tis_enabled = {\n\t\tscope:holder = {\n\t\t\tis_dwarvish_culture = yes\n\t\t}\n"
              "\t\tNOT = { has_variable = aov_hold_ruined }\n\t}\n\n")

# The AI's build preference per dwarven building (level 1, upgrades): the scripted modifiers vanilla buildings of
# that kind use.
AI_PREFERENCE = {
    "deep_mine": (("ai_tier_1_economical_building_preference_modifier", "directive_to_build_economy_modifier"),
                  ("ai_economical_building_preference_modifier", "directive_to_build_economy_modifier")),
    "runeforge": (("directive_to_build_military_modifier",), ("directive_to_build_military_modifier",)),
    "hall_of_the_ancestors": (("ai_tier_1_pious_building_preference_modifier",),
                              ("ai_pious_building_preference_modifier",)),
}


def dwarf_asset(n, castle_lines, gfx_keys, fallback, regions):
    """The RiE dwarven model asset of hold level n. It serves every dwarven gfx key and every graphical region
    (the region outranks the culture in CK3's asset choice), with the illustration and sound of the level's first
    castle asset that has no DLC flag and serves the fallback gfx key."""
    template = bhm.template_asset(bhm.original_assets(castle_lines), fallback)
    keep = [l for l in template if l.strip().startswith(("illustration =", "soundeffect ="))]
    return "\n".join(["\t\tasset = {  # Anbennar Overhaul: RiE dwarf hold model", "\t\t\ttype = pdxmesh",
                      f'\t\t\tname = "{HOLD_DWARF_MESHES[n]}"', *keep,
                      "\t\t\tgraphical_cultures = { %s }" % " ".join(gfx_keys),
                      "\t\t\tgraphical_regions = { %s }" % " ".join(regions), "\t\t}"])


def render_level(n, assets, gfx):
    lvl = holds.LEVELS[n - 1]
    band = holds.ASSET_BAND[n]
    out = [f"{level_key(n)} = {{\n", "\tconstruction_time = slow_construction_time\n\n",
           "\tassets = {\n", dwarf_asset(n, assets[band], *gfx) + "\n" + "\n".join(assets[band]) + "\n", "\t}\n\n",
           "\tcan_construct_potential = {\n\t\talways = no\n\t}\n\n", IS_ENABLED,
           "\tcost_gold = main_building_tier_1_cost\n"]
    if n < 10:
        out.append(f"\tnext_building = {level_key(n + 1)}\n")
    out.append("\n")
    out += [f"\t{k} = {lvl[k]}\n" for k in LEVEL_FLAT]
    out.append(modifier_block("province_modifier", {k: lvl[k] for k in LEVEL_PROVINCE}))
    out.append(modifier_block("county_modifier", {k: lvl[k] for k in LEVEL_COUNTY}))
    out.append(f"\n\tflag = castle\n\n\ttype_icon = \"{ICON}\"\n\n\tai_value = {{\n\t\tbase = 0\n\t}}\n}}\n")
    return "".join(out)


def render_dwarven_building(spec, n):
    key = f"{spec['key']}_{n:02d}"
    effects = {k: round(v * n, 4) for k, v in spec["effects"].items()}
    out = [f"{key} = {{\n", "\tconstruction_time = standard_construction_time\n\n",
           "\tcan_construct_potential = {\n\t\tscope:holder = {\n\t\t\tis_dwarvish_culture = yes\n\t\t}\n\t}\n\n",
           f"\tcan_construct = {{\n\t\thas_building_or_higher = {level_key(spec['min_level'])}\n\t}}\n\n",
           IS_ENABLED,
           f"\tcost_gold = normal_building_tier_{n}_cost\n"]
    if n < 3:
        out.append(f"\tnext_building = {spec['key']}_{n + 1:02d}\n")
    out.append("\n")
    out.append(modifier_block(spec["block"], effects))
    first, upgrade = AI_PREFERENCE[spec["key"]]
    ai = ("ai_tier_1_building_modifier", "ai_general_building_modifier", *first) if n == 1 else \
        ("ai_general_building_modifier", *upgrade)
    ai_lines = "".join(f"\t\t{m} = yes\n" for m in ai)
    # base 10/9/8 as vanilla-like economy buildings (Anbennar's fungus farms)
    out.append(f"\n\ttype_icon = \"{ICON}\"\n\n\tai_value = {{\n\t\tbase = {11 - n}\n{ai_lines}\t}}\n}}\n")
    return "".join(out)


def dwarf_gfx(root: Path) -> tuple:
    """(dwarven gfx keys, the main key's fallback key, graphical regions) read from Anbennar's files."""
    texts = bhm.culture_texts(bhm.Roots(rie=None, anbennar=Path(root), game=None))
    _targets, group_keys = bhm.assign_gfx(texts)
    main = bhm.data.GROUPS["dwarven"]["gfx"]
    return group_keys["dwarven"], bhm.gfx_fallbacks(texts)[main], bhm.graphical_regions(root)


def render_buildings(root: Path = ANBENNAR) -> str:
    variables, assets = castle_assets(root)
    gfx = dwarf_gfx(root)
    parts = [HEADER, "\n", "\n".join(variables) + "\n\n"]
    parts += [render_level(n, assets, gfx) + "\n" for n in range(1, 11)]
    for spec in holds.DWARVEN_BUILDINGS:
        parts += [render_dwarven_building(spec, n) + "\n" for n in (1, 2, 3)]
    return "".join(parts).rstrip("\n") + "\n"


def render_values() -> str:
    levels = "".join(
        f"\tif = {{\n\t\tlimit = {{ has_building_or_higher = {level_key(n)} }}\n\t\tadd = 1\n\t}}\n"
        for n in range(1, 11))
    return (HEADER + "\n"
            "# Province scope: 1..10 from the dwarven hold building, 0 without one.\n"
            f"aov_hold_level = {{\n\tvalue = 0\n{levels}}}\n\n"
            "# Province scope: the level a dig aims for: the variable aov_dig_target_level, else the next level.\n"
            "aov_dig_target_value = {\n\tvalue = aov_hold_level\n\tadd = 1\n"
            "\tif = {\n\t\tlimit = { has_variable = aov_dig_target_level }\n"
            "\t\tadd = {\n\t\t\tvalue = var:aov_dig_target_level\n\t\t\tsubtract = aov_hold_level\n\t\t\tsubtract = 1\n\t\t}\n\t}\n}\n\n"
            "# Province scope: gold cost of a dig.\n"
            f"aov_dig_cost = {{\n\tvalue = aov_dig_target_value\n\tmultiply = {holds.DIG_COST_PER_LEVEL}\n}}\n\n"
            "# Province scope: months a dig takes, 12 x (8 + 4 x (target - 1)).\n"
            "aov_dig_months = {\n\tvalue = aov_dig_target_value\n\tsubtract = 1\n\tmultiply = 4\n\tadd = 8\n\tmultiply = 12\n}\n")


