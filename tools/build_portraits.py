# --------------------------------------------------------------------------------------------- portrait modifiers

def rie_clothing_keys(rie: Path) -> set:
    """RiE's clothing culture keys: the <k> of every portrait_<k>_clothing_contents_trigger and every
    <k>_clothing_gfx in RiE's culture files."""
    keys = set()
    for _path, text in _texts(str(rie / "common/scripted_triggers"), "*.txt"):
        keys.update(re.findall(r"^portrait_(\w+?)_clothing_contents_trigger\s*=", text, re.M))
    for _path, text in _texts(str(rie / "common/culture/cultures"), "*.txt"):
        keys.update(re.findall(r"\b(\w+?)_clothing_gfx\b", code(text)))
    return keys


def map_input(value: str, overrides: dict) -> str:
    if value in overrides:
        return overrides[value]
    return data.INPUTS.get(value, data.NONE_INPUT)


def transform(text: str, rie_keys: set, overrides=None) -> str:
    """An RiE modifier with our culture inputs, triggers, heritages, game rules and literal replacements."""
    overrides = overrides or {}
    text = re.sub(r"\bCULTURE_INPUT(\s*=\s*)(\w+)", lambda m: f"CULTURE_INPUT{m.group(1)}{map_input(m.group(2), overrides)}",
                  text)

    def trigger(match):
        key = match.group(1)
        if key not in rie_keys:
            return match.group(0)
        return f"portrait_{map_input(key, overrides)}_clothing{match.group(2) or ''}_trigger"
    text = re.sub(r"\bportrait_(\w+?)_clothing(_spouse|_contents)?_trigger\b", trigger, text)

    def gfx(match):
        key = match.group(2)
        if key not in rie_keys:
            return match.group(0)
        mapped = map_input(key, overrides)
        return "always = no" if mapped == data.NONE_INPUT else f"{match.group(1)}{mapped}_clothing_gfx"
    text = re.sub(r"(\bhas_clothing_gfx\s*=\s*)(\w+?)_clothing_gfx\b", gfx, text)
    text = re.sub(r"\bhas_cultural_pillar\s*=\s*(heritage_\w+)",
                  lambda m: f"{data.HERITAGES[m.group(1)]} = yes" if m.group(1) in data.HERITAGES else m.group(0), text)
    text = re.sub(r"\bhas_game_rule\s*=\s*(\w+)",
                  lambda m: f"always = {data.GAME_RULES[m.group(1)]}" if m.group(1) in data.GAME_RULES else m.group(0),
                  text)
    for old, new in data.REPLACE:
        text = text.replace(old, new)
    return text


def _entry_spec(item) -> tuple:
    return (item, {}) if isinstance(item, str) else item


@lru_cache(maxsize=None)
def rie_group(rie: str, filename: str, group: str) -> tuple:
    """(settings lines, [(entry name, entry text)]) of one group of an RiE portrait modifier file."""
    path = Path(rie) / MODIFIERS_DIR / filename
    if not path.is_file():
        raise GeneratorError(f"RiE portrait modifier file {path} not found")
    text = read(path)
    group_block = [(s, e) for names, s, e in blocks(text, 1) if names == (group,)]
    if len(group_block) != 1:
        raise GeneratorError(f"{filename}: group {group} found {len(group_block)} times")
    start, end = group_block[0]
    entries = [(names[1], text[s:e]) for names, s, e in blocks(text, 2) if names[0] == group and start <= s < end]
    head_end = min((s for _n, s, _e in blocks(text, 2) if start <= s < end), default=end)
    head = code(text[start:head_end])
    settings = []
    for key in ("priority", "selection_behavior"):
        match = re.search(rf"\b{key}\s*=\s*(\w+)", head)
        if match:
            settings.append(f"\t{key} = {match.group(1)}")
    return settings, entries


def copied_entries(roots: Roots) -> dict:
    """RiE file -> RiE group -> (settings, [entry texts]) after the renames, with EXTRA_ENTRIES appended."""
    rie_keys = rie_clothing_keys(roots.rie)
    out = {}
    for filename, groups in data.ENTRIES.items():
        for group, items in groups.items():
            settings, entries = rie_group(str(roots.rie), filename, group)
            texts, seen = [], {}
            for item in items:
                name, options = _entry_spec(item)
                found = [body for entry, body in entries if entry == name]
                if not found:
                    raise GeneratorError(f"{filename}: {group} has no modifier {name}")
                for body in found:
                    seen[name] = seen.get(name, 0) + 1
                    if seen[name] > 1:
                        body = re.sub(rf"\b{re.escape(name)}(\s*=\s*\{{)", rf"{name}_{seen[name]}\1", body, count=1)
                    texts.append(lf(transform(body, rie_keys, options.get("inputs"))))
            texts += data.EXTRA_ENTRIES.get(group, [])
            out.setdefault(filename, {})[group] = (settings, texts)
    for group in data.EXTRA_ENTRIES:
        if not any(group in groups for groups in data.ENTRIES.values()):
            raise GeneratorError(f"EXTRA_ENTRIES group {group} has no copied group to join")
    return out


def modifier_files(entries: dict) -> dict:
    out = {}
    for filename, groups in entries.items():
        lines = [BOM + HEADER()[0], HEADER()[1],
                 f"# Realms in Exile's {filename} entries for the halflings, gnomes, elves and dwarves; see tools/data/portraits.py.",
                 "# A new group with RiE's priority: it applies after Anbennar's group of the same priority (file order)."]
        for group, (settings, texts) in groups.items():
            lines += ["", f"aov_rie_{group} = {{", "\tusage = game"] + settings + [""]
            lines += ["".join(text.rstrip("\n") + "\n\n" for text in texts).rstrip("\n"), "}"]
        out[f"{MODIFIERS_DIR}/aov_rie_{filename}"] = ("\n".join(lines) + "\n").encode("utf-8")
    return out


def check_references(roots: Roots, entries: dict) -> None:
    """Every culture, heritage, title and scripted trigger an entry names exists in Anbennar, the game or our
    triggers."""
    cultures, pillars = set(), set()
    for _path, text in effective_texts(roots, "common/culture/cultures"):
        cultures.update(name for name, *_ in bhm.culture_blocks(text))
    for _path, text in effective_texts(roots, "common/culture/pillars"):
        pillars.update(name for name, *_ in bhm.culture_blocks(text))
    triggers = set(TRIGGER_NAMES())
    for _path, text in effective_texts(roots, "common/scripted_triggers"):
        triggers.update(name for name, *_ in bhm.culture_blocks(text))
    activities = set()
    for _path, text in effective_texts(roots, "common/activities/activity_types"):
        activities.update(name for name, *_ in bhm.culture_blocks(text))
    problems = []
    for filename, groups in entries.items():
        for group, (_settings, texts) in groups.items():
            body = code("".join(texts))
            for name in set(re.findall(r"\bculture:(\w+)", body)) - cultures:
                problems.append(f"{filename} {group}: culture:{name}")
            for name in set(re.findall(r"\b(heritage_\w+)", body)) - pillars:
                problems.append(f"{filename} {group}: {name}")
            for kind in ("title", "dynasty", "house", "character"):
                for name in set(re.findall(rf"\b{kind}:(\w+)", body)):
                    problems.append(f"{filename} {group}: {kind}:{name}")
            for name in set(re.findall(r"\b(\w+_trigger)\s*=", body)) - triggers:
                problems.append(f"{filename} {group}: trigger {name}")
            for name in set(re.findall(r"\bhas_activity_type\s*=\s*(\w+)", body)) - activities:
                problems.append(f"{filename} {group}: activity {name}")
    if problems:
        raise GeneratorError("copied portrait modifiers refer to things Anbennar lacks: " + "; ".join(sorted(problems)))


